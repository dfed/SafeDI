/// Thrown when a diagnostic needs the source location of a declaration that has none.
///
/// `SafeDITool` records a location for every declaration it parses, so this is reached only when a
/// `.safedi` module info file supplied through `--dependent-module-info-file-path` omits locations –
/// for example one written by a SafeDITool that predates them. Locations are optional on the models
/// because the macro expansion path builds the same models without a file, but that path never
/// builds a dependency tree.
public struct MissingSourceLocationError: Error, CustomStringConvertible {
	public init(declaration: String) {
		self.declaration = declaration
	}

	/// The declaration that lacks a location, as it would be named in a diagnostic.
	public let declaration: String

	public var description: String {
		"SafeDI has no source location for \(declaration). Every `.safedi` module info file must be regenerated by this version of SafeDITool."
	}
}

extension Dependency {
	/// The location of the dependency’s declaration on `instantiable`.
	/// - Throws: `MissingSourceLocationError` when the dependency was parsed without a file context.
	public func requireDeclarationLocation(on instantiable: Instantiable) throws -> DeclarationLocation {
		guard let declarationLocation else {
			throw MissingSourceLocationError(declaration: "property `\(property.asSource)` on `\(instantiable.concreteInstantiable.asSource)`")
		}
		return declarationLocation
	}
}

extension Instantiable {
	/// The location of this `@Instantiable`’s decorated declaration.
	/// - Throws: `MissingSourceLocationError` when the instantiable was parsed without a file context.
	public func requireDeclarationLocation() throws -> Dependency.DeclarationLocation {
		guard let declarationLocation else {
			throw MissingSourceLocationError(declaration: "`@\(InstantiableVisitor.macroName)` type `\(concreteInstantiable.asSource)`")
		}
		return declarationLocation
	}
}
