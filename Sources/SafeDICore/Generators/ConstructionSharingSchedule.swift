/// The sharing oracle's schedule, test only: which places of a tree share a generator the construction memo offers them,
/// and which of the alike candidates each takes. Two candidates whose reads a place's context answers alike are equal
/// builds (`ConstructionMemo`), so what `generate` emits must not depend on the schedule. The oracle runs a graph under
/// several schedules and compares every generated byte and diagnostic with the run that shares wherever it can.
///
/// It draws what parallel construction will do by timing: a place that builds again what an earlier place stored, a place
/// that takes any alike candidate rather than the first that arrived, and, through `offersLaterPlacesCandidates`, a place
/// that takes the candidate a place later in the walk built, as it is when another job runs ahead.
public struct ConstructionSharingSchedule: Sendable {
	/// - Parameters:
	///   - seed: The seed of the draws: for each memo lookup of a tree's pass, in walk order, whether the place builds again
	///     and in which order it asks the candidates. `nil` draws nothing: every place shares where it can.
	///   - offersLaterPlacesCandidates: Whether each tree's first pass starts from the memo a discarded build of the same pass
	///     filled, asking the newest candidate first, so that a place is offered what a place after it built.
	public init(seed: UInt64?, offersLaterPlacesCandidates: Bool) {
		self.seed = seed
		self.offersLaterPlacesCandidates = offersLaterPlacesCandidates
	}

	public let seed: UInt64?
	public let offersLaterPlacesCandidates: Bool

	/// The schedule every tree `Scope.createScopeGenerator` creates follows, or `nil` outside the sharing oracle.
	@TaskLocal public static var current: ConstructionSharingSchedule?

	/// Called for each memo lookup that has a candidate, with whether the schedule changed which generator the place holds
	/// from the one the place holds when it shares wherever it can: so the oracle can say how many places each draw moved.
	@TaskLocal public static var observer: TaskLocalFunction<@Sendable (_ changesHeldGenerator: Bool) -> Void>?

	/// The draw for the lookup numbered `lookupCount` in the pass, which it advances.
	func draw(atLookup lookupCount: inout Int) -> Draw {
		let lookup = lookupCount
		lookupCount += 1
		let mixed = seed.map { Self.mixed($0 &+ UInt64(lookup) &* 0x9E3779B97F4A7C15) }
		return Draw(
			buildsAgain: mixed.map { $0 % 4 == 0 } ?? false,
			permutationSeed: mixed.map { Self.mixed($0) },
			asksNewestFirst: offersLaterPlacesCandidates,
		)
	}

	/// What one lookup does with the candidates of its key.
	struct Draw {
		let buildsAgain: Bool
		let permutationSeed: UInt64?
		let asksNewestFirst: Bool

		/// The reuse of the first candidate, in this draw's order, that `answer` accepts, or `nil` where the draw builds the
		/// place again or no candidate is accepted.
		func reuse(among candidates: [ConstructionMemo.Entry], _ answer: (ConstructionMemo.Entry) -> ConstructionMemo.Reuse?) -> ConstructionMemo.Reuse? {
			var reuse: ConstructionMemo.Reuse?
			if !buildsAgain {
				for entry in ordered(candidates) {
					if let accepted = answer(entry) {
						reuse = accepted
						break
					}
				}
			}
			if let observer = ConstructionSharingSchedule.observer {
				let sharedReuse = candidates.lazy.compactMap(answer).first
				observer(sharedReuse?.entry.generator !== reuse?.entry.generator)
			}
			return reuse
		}

		private func ordered(_ candidates: [ConstructionMemo.Entry]) -> [ConstructionMemo.Entry] {
			var ordered = asksNewestFirst ? candidates.reversed() : candidates
			if var state = permutationSeed, ordered.count > 1 {
				for index in ordered.indices.dropLast() {
					state = ConstructionSharingSchedule.mixed(state)
					let otherIndex = index + Int(state % UInt64(ordered.count - index))
					ordered.swapAt(index, otherIndex)
				}
			}
			return ordered
		}
	}

	/// SplitMix64's output function, so that each lookup's draw is the same on every run and platform.
	public static func mixed(_ value: UInt64) -> UInt64 {
		var mixed = value &+ 0x9E3779B97F4A7C15
		mixed = (mixed ^ (mixed >> 30)) &* 0xBF58476D1CE4E5B9
		mixed = (mixed ^ (mixed >> 27)) &* 0x94D049BB133111EB
		return mixed ^ (mixed >> 31)
	}
}
