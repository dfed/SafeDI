	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_passesNilOrTheSource_whenRenameRenamesASourceOnlyIfAvailable() async throws {
		// The macro's fix-it for a required rename of a rename of `x` only if available: `b` is `nil` where `x` is
		// unavailable and `x` where it is, as the two renames were.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable
				public final class X: Instantiable {
				    public init() {}
				}

				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init(available: Available, unavailable: Child) {
				        self.available = available
				        self.unavailable = unavailable
				    }

				    @Instantiated let available: Available
				    @Instantiated let unavailable: Child
				}

				@Instantiable
				public final class Available: Instantiable {
				    public init(x: X, child: Child) {
				        self.x = x
				        self.child = child
				    }

				    @Instantiated let x: X
				    @Instantiated let child: Child
				}
				""",
				"""
				@Instantiable
				public final class Child: Instantiable {
				    public init(a: X?, b: X?) {
				        self.a = a
				        self.b = b
				    }

				    @Received(fulfilledByDependencyNamed: "x", ofType: X.self, onlyIfAvailable: true) let a: X?
				    @Received(fulfilledByDependencyNamed: "x", ofType: X.self, onlyIfAvailable: true) let b: X?
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.generatedFiles == [
			"X+SafeDI.swift": """
			// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
			// Any modifications made to this file will be overwritten on subsequent builds.
			// Please refrain from editing this file directly.

			extension Root {
			    public convenience init() {
			        func __safeDI_available() -> Available {
			            let x = X()
			            func __safeDI_child() -> Child {
			                #sourceLocation(file: "\(output.fixtures["Child.swift"])", line: 8)
			                let a: X? = x
			                #sourceLocation()
			                #sourceLocation(file: "\(output.fixtures["Child.swift"])", line: 9)
			                let b: X? = x
			                #sourceLocation()
			                return Child(a: a, b: b)
			            }
			            let child: Child = __safeDI_child()
			            return Available(x: x, child: child)
			        }
			        let available: Available = __safeDI_available()
			        func __safeDI_unavailable() -> Child {
			            #sourceLocation(file: "\(output.fixtures["Child.swift"])", line: 8)
			            let a: X? = nil
			            #sourceLocation()
			            #sourceLocation(file: "\(output.fixtures["Child.swift"])", line: 9)
			            let b: X? = nil
			            #sourceLocation()
			            return Child(a: a, b: b)
			        }
			        let unavailable: Child = __safeDI_unavailable()
			        self.init(available: available, unavailable: unavailable)
			    }
			}
			""",
		])
	}

