/// The two rename spellings the `@Instantiable` macro rejects – a rename of another rename of the same declaration,
/// and a rename of a dependency to itself – as SafeDITool meets them: every build runs it before the compiler expands
/// the macro, so it reports each plainly where its evaluation of `#if` blocks forms one, and generates the code of the
/// shapes the macro accepts.
struct SafeDIToolRenameSpellingTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: A rename of another rename

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_throwsPlainError_whenRenameRenamesAnotherRenameOfTheSameDeclaration() async {
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["Child.swift"]):9:5: error: `sink: any LogSink` is renamed from `logger`, which `Child` also renames. The @Instantiable macro rejects a rename of another rename of the same declaration. Rename the property the renames start from instead. SafeDITool also rejects such renames where `#if` blocks that are active together declare them, or clauses of a condition only the compiler decides, such as `os(iOS)`, which SafeDITool reads together; there, give the rename `logger` another label.
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: [
					Self.root,
					"""
					@Instantiable
					public final class Child: Instantiable {
					    public init(logger: any Logger, sink: any LogSink) {
					        self.logger = logger
					        self.sink = sink
					    }

					    @Received(fulfilledByDependencyNamed: "fileLogger", ofType: FileLogger.self) let logger: any Logger
					    @Received(fulfilledByDependencyNamed: "logger", ofType: (any Logger).self) let sink: any LogSink
					}
					""",
				],
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

