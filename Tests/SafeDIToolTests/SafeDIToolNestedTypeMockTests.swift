		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_callsHandWrittenMock_whenNestedTypeMockReturnsUnqualifiedTypeName() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				public enum Feature {
				    @Instantiable
				    public final class Service: Instantiable {
				        public init() {}
				    }

				    @Instantiable
				    public final class Consumer: Instantiable {
				        public init(service: Service) {
				            self.service = service
				        }

				        @Instantiated let service: Service

				        public static func mock(service: Service) -> Consumer {
				            Consumer(service: service)
				        }
				    }
				}
				""",
				"""
				@Instantiable(generateMock: true)
				public final class Root: Instantiable {
				    public init(consumer: Feature.Consumer) {
				        self.consumer = consumer
				    }

				    @Instantiated let consumer: Feature.Consumer
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(try #require(output.generatedFiles?["Root+SafeDIMock.swift"]) == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            consumer: Feature.Consumer.SafeDIMockConfiguration = .init()
		        ) {
		            self.consumer = consumer
		        }

		        let consumer: Feature.Consumer.SafeDIMockConfiguration
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        func __safeDI_consumer() -> Feature.Consumer {
		            let service = if let safeDIBuilder = safeDIOverrides.consumer.service { safeDIBuilder() } else { Feature.Service() }
		            return if let safeDIBuilder = safeDIOverrides.consumer.safeDIBuilder { safeDIBuilder(service) } else { Feature.Consumer.mock(service: service) }
		        }
		        let consumer: Feature.Consumer = __safeDI_consumer()
		        return Root(consumer: consumer)
		    }
		}
		#endif
		""")
	}

