	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func dependencyTree_bindsRootInitializerToMainActor_whenGeneratedInitializerAttributesIsMainActor() async throws {
		// `Child`'s initializer is bound to the main actor, so the root's generated `init()` compiles only when it is too.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true, generatedInitializerAttributes: "@MainActor")
				public final class Root: Instantiable {
				    public init(child: Child) {
				        self.child = child
				    }

				    @Instantiated let child: Child
				}
				""",
				"""
				@Instantiable
				public struct Child: Instantiable {
				    @MainActor public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.dependencyTreeFiles["Root+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    @MainActor public convenience init() {
		        let child = Child()
		        self.init(child: child)
		    }
		}
		""", "Unexpected output \(output.dependencyTreeFiles["Root+SafeDI.swift"] ?? "")")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func dependencyTree_buildsInstantiatorOfMainActorInitializer_whenGeneratedInitializerAttributesIsMainActor() async throws {
		// The function that builds the `Instantiator` is nested in the root's generated `init()`, so it takes that
		// initializer's isolation, and can call `Child`'s initializer only when the root's `init()` is bound to the main actor.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true, generatedInitializerAttributes: "@MainActor")
				public final class Root: Instantiable {
				    public init(childBuilder: Instantiator<Child>) {
				        self.childBuilder = childBuilder
				    }

				    @Instantiated let childBuilder: Instantiator<Child>
				}
				""",
				"""
				@Instantiable
				public final class Child: Instantiable {
				    @MainActor public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.dependencyTreeFiles["Root+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    @MainActor public convenience init() {
		        func __safeDI_childBuilder() -> Child {
		            Child()
		        }
		        let childBuilder = Instantiator<Child>(__safeDI_childBuilder)
		        self.init(childBuilder: childBuilder)
		    }
		}
		""", "Unexpected output \(output.dependencyTreeFiles["Root+SafeDI.swift"] ?? "")")
	}

