	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_bindsMockToMainActor_whenGeneratedAttributesIsMainActor() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: Self.mainActorRootWithMainActorChild,
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            child: (() -> Child)? = nil
		        ) {
		            self.child = child
		        }

		        let child: (() -> Child)?
		    }

		    @MainActor static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        let child = if let safeDIBuilder = safeDIOverrides.child { safeDIBuilder() } else { Child() }
		        return Root(child: child)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_buildsInstantiatorOfMainActorInitializer_whenMockAttributesIsMainActor() async throws {
		// The function that builds the `Instantiator` is nested in the generated `mock()`, so it takes the mock's
		// isolation, and can call `Child`'s initializer only when the mock is bound to the main actor.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(mockAttributes: "@MainActor", generateMock: true)
				public final class Parent: Instantiable {
				    public init(childBuilder: Instantiator<Child>) {
				        self.childBuilder = childBuilder
				    }

				    @Instantiated let childBuilder: Instantiator<Child>
				}
				""",
				"""
				@Instantiable
				public final class Child: Instantiable {
				    @MainActor public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.mockFiles["Parent+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Parent {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            childBuilder: (() -> Child)? = nil
		        ) {
		            self.childBuilder = childBuilder
		        }

		        let childBuilder: (() -> Child)?
		    }

		    @MainActor static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Parent {
		        func __safeDI_childBuilder() -> Child {
		            if let safeDIBuilder = safeDIOverrides.childBuilder { safeDIBuilder() } else { Child() }
		        }
		        let childBuilder = Instantiator<Child>(__safeDI_childBuilder)
		        return Parent(childBuilder: childBuilder)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Parent+SafeDIMock.swift"] ?? "")")
	}

