		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				public final class ExternalService {
				    @MainActor public init() {}
				}

				@Instantiable(generatedAttributes: "@MainActor", generateMock: true)
				extension ExternalService: Instantiable {
				    @MainActor public static func instantiate() -> ExternalService {
				        ExternalService()
				    }
				}
