import Foundation
import SafeDICore
import Testing
@testable import SafeDITool

/// Files reached through `#SafeDIConfiguration(additionalDirectoriesToInclude:)` in a project laid out as a
/// build tool plugin hands it to the tool: the project root is the working directory, the input CSV lists
/// paths relative to it, and the additional directory lies under it.
struct SafeDIToolAdditionalDirectoryTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_writesRootInAdditionalDirectoryAsWithScanCache_whenScanCacheIsDeleted() async throws {
		let project = try makeProject(inputsIncludeAdditionalDirectoryFile: false)
		try await project.scan()
		try await project.generateWithManifest()
		let outputWithScanCache = try project.removingGeneratedFiles()

		try FileManager.default.removeItem(at: scannedModuleInfoURL(forManifestPath: project.manifestFile.path))
		try await project.generateWithManifest()

		let outputWithoutScanCache = try project.removingGeneratedFiles()
		#expect(outputWithoutScanCache == outputWithScanCache)
		#expect(outputWithoutScanCache == Self.expectedOutput)
		try verifyGeneratedCodeCompiles(
			inputSwiftFiles: project.targetFiles,
			additionalDirectorySwiftFiles: [project.additionalDirectoryFile],
			generatedFiles: outputWithoutScanCache,
			filesToDelete: &filesToDelete,
		)
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_parsesInputInAdditionalDirectoryOnceAsWithScanCache_whenScanCacheIsDeleted() async throws {
		// A package's configuration can name a dependency module's directory, whose files the plugin also lists as inputs.
		let project = try makeProject(inputsIncludeAdditionalDirectoryFile: true)
		try await project.scan()
		try await project.generateWithManifest()
		let outputWithScanCache = try project.removingGeneratedFiles()

		try FileManager.default.removeItem(at: scannedModuleInfoURL(forManifestPath: project.manifestFile.path))
		try await project.generateWithManifest()

		let outputWithoutScanCache = try project.removingGeneratedFiles()
		#expect(outputWithoutScanCache == outputWithScanCache)
		#expect(outputWithoutScanCache == Self.expectedOutput)
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_writesRootInAdditionalDirectory_whenScanningForItself() async throws {
		let project = try makeProject(inputsIncludeAdditionalDirectoryFile: false)

		try await project.generateWithOutputDirectory()

		let output = try project.removingGeneratedFiles()
		#expect(output == Self.expectedOutput)
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_writesRootInAdditionalDirectory_whenScanningForItselfCannotWriteScanCache() async throws {
		let project = try makeProject(inputsIncludeAdditionalDirectoryFile: false)
		// A directory where the scan cache belongs makes writing the cache fail, so `generate` parses afresh.
		try FileManager.default.createDirectory(
			at: scannedModuleInfoURL(forManifestPath: project.outputDirectory.appendingPathComponent("SafeDIManifest.json").path),
			withIntermediateDirectories: true,
		)

		try await project.generateWithOutputDirectory()

		let output = try project.removingGeneratedFiles()
		#expect(output == Self.expectedOutput)
	}

	// MARK: Private

	private var filesToDelete: [URL]

	private static let expectedOutput = [
		"InnerRoot+SafeDI.swift": """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if canImport(SafeDI)
		import SafeDI
		#endif

		extension InnerRoot {
		    public init() {
		        let dependency = Dependency()
		        self.init(dependency: dependency)
		    }
		}
		""",
	]

	private struct Project {
		let swiftFileCSV: URL
		/// The target's own files, as the build system reports them to a build tool plugin.
		let targetFiles: [URL]
		/// The root's file, in the directory the configuration includes.
		let additionalDirectoryFile: URL
		let outputDirectory: URL
		let manifestFile: URL

		/// Runs `scan` as a build tool plugin runs it while planning the build.
		func scan() async throws {
			try await Scan.parse([
				"--input-sources-file", swiftFileCSV.path,
				"--project-root", FileManager.default.currentDirectoryPath,
				"--output-directory", outputDirectory.path,
				"--manifest-file", manifestFile.path,
				"--mock-scoped-files",
			] + targetFiles.map(\.path)).run()
		}

		/// Runs `generate` with the manifest `scan` wrote.
		func generateWithManifest() async throws {
			try await Generate.parse([
				swiftFileCSV.path,
				"--swift-manifest", manifestFile.path,
			]).generate()
		}

		/// Runs `generate` as a build tool plugin runs it when it could not run `scan` while planning the build.
		func generateWithOutputDirectory() async throws {
			try await Generate.parse([
				swiftFileCSV.path,
				"--output-directory", outputDirectory.path,
				"--mock-scoped-files",
			] + targetFiles.map(\.path)).generate()
		}

		/// The Swift files `generate` wrote, keyed by file name, which this removes so the next run writes them again.
		func removingGeneratedFiles() throws -> [String: String] {
			var generatedFiles = [String: String]()
			for fileName in try FileManager.default.contentsOfDirectory(atPath: outputDirectory.path) where fileName.hasSuffix(".swift") {
				let fileURL = outputDirectory.appendingPathComponent(fileName)
				generatedFiles[fileName] = try String(contentsOf: fileURL, encoding: .utf8)
				try FileManager.default.removeItem(at: fileURL)
			}
			return generatedFiles
		}
	}

	/// A project whose target declares a configuration that includes the `Extra` directory, which holds a root.
	/// - Parameter inputsIncludeAdditionalDirectoryFile: Whether the input CSV also lists the root's file.
	private mutating func makeProject(inputsIncludeAdditionalDirectoryFile: Bool) throws -> Project {
		// The plugin's paths are relative to the project root, which is `generate`'s working directory.
		let projectDirectory = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
			.appendingPathComponent(".build")
			.appendingPathComponent("SafeDIToolTestFixtures")
			.appendingPathComponent(UUID().uuidString)
		let targetDirectory = projectDirectory.appendingPathComponent("Target")
		let additionalDirectory = projectDirectory.appendingPathComponent("Extra")
		try FileManager.default.createDirectory(at: targetDirectory, withIntermediateDirectories: true)
		try FileManager.default.createDirectory(at: additionalDirectory, withIntermediateDirectories: true)
		let outputDirectory = projectDirectory.appendingPathComponent("Output")
		try FileManager.default.createDirectory(at: outputDirectory, withIntermediateDirectories: true)
		filesToDelete.append(projectDirectory)

		let configurationFile = targetDirectory.appendingPathComponent("SafeDIConfiguration.swift")
		try """
		import SafeDI

		#SafeDIConfiguration(
		    additionalDirectoriesToInclude: ["\(currentDirectoryRelativePath(to: additionalDirectory))"]
		)
		""".write(to: configurationFile, atomically: true, encoding: .utf8)
		let dependencyFile = targetDirectory.appendingPathComponent("Dependency.swift")
		try """
		import SafeDI

		@Instantiable
		public struct Dependency: Instantiable {
		    public init() {}
		}
		""".write(to: dependencyFile, atomically: true, encoding: .utf8)
		let rootFile = additionalDirectory.appendingPathComponent("InnerRoot.swift")
		try """
		import SafeDI

		@Instantiable(isRoot: true)
		public struct InnerRoot: Instantiable {
		    public init(dependency: Dependency) {
		        self.dependency = dependency
		    }

		    @Instantiated let dependency: Dependency
		}
		""".write(to: rootFile, atomically: true, encoding: .utf8)

		let targetFiles = [configurationFile, dependencyFile]
		let inputFiles = inputsIncludeAdditionalDirectoryFile ? targetFiles + [rootFile] : targetFiles
		let swiftFileCSV = projectDirectory.appendingPathComponent("InputSwiftFiles.csv")
		try inputFiles
			.map(currentDirectoryRelativePath(to:))
			.joined(separator: ",")
			.write(to: swiftFileCSV, atomically: true, encoding: .utf8)

		return Project(
			swiftFileCSV: swiftFileCSV,
			targetFiles: targetFiles,
			additionalDirectoryFile: rootFile,
			outputDirectory: outputDirectory,
			manifestFile: projectDirectory.appendingPathComponent("SafeDIManifest.json"),
		)
	}
}
