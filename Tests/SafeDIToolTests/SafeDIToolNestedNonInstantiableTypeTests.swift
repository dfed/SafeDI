	// MARK: Private

	private var filesToDelete: [URL]

	/// Scans and generates code for a module whose input files also hold the files of the modules it depends on, as a
	/// build tool plugin hands them to `SafeDITool`.
	/// - Returns: The generated files, by name.
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	private mutating func generatedFiles(moduleFiles: [String: String], dependencyFiles: [String: String]) async throws -> [String: String] {
		let projectRoot = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent(UUID().uuidString)
		let moduleDirectory = projectRoot.appendingPathComponent("Module")
		let dependencyDirectory = projectRoot.appendingPathComponent("Dependency")
		try FileManager.default.createDirectory(at: moduleDirectory, withIntermediateDirectories: true)
		try FileManager.default.createDirectory(at: dependencyDirectory, withIntermediateDirectories: true)
		let outputDirectory = projectRoot.appendingPathComponent("Output")
		try FileManager.default.createDirectory(at: outputDirectory, withIntermediateDirectories: true)
		filesToDelete.append(projectRoot)
		func write(_ files: [String: String], in directory: URL) throws -> [String] {
			try files.sorted { $0.key < $1.key }.map { fileName, content in
				let file = directory.appendingPathComponent(fileName)
				try content.write(to: file, atomically: true, encoding: .utf8)
				return file.path
			}
		}
		let moduleFilePaths = try write(moduleFiles, in: moduleDirectory)
		let dependencyFilePaths = try write(dependencyFiles, in: dependencyDirectory)
		let swiftFileCSV = projectRoot.appendingPathComponent("Inputs.csv")
		try (moduleFilePaths + dependencyFilePaths).joined(separator: ",").write(to: swiftFileCSV, atomically: true, encoding: .utf8)
		let manifestFile = projectRoot.appendingPathComponent("SafeDIManifest.json")
		try await performScan(
			inputSourcesFile: swiftFileCSV.path,
			projectFilePaths: ProjectFilePaths(projectRoot: projectRoot.path),
			outputDirectory: outputDirectory.path,
			manifestFile: manifestFile.path,
			mockScopedFiles: moduleFilePaths,
		)
		try await Generate.parse([swiftFileCSV.path, "--swift-manifest", manifestFile.path]).generate()
		var generatedFiles = [String: String]()
		for fileName in try FileManager.default.contentsOfDirectory(atPath: outputDirectory.path) where fileName.hasSuffix(".swift") {
			generatedFiles[fileName] = try String(contentsOf: outputDirectory.appendingPathComponent(fileName), encoding: .utf8)
		}
		return generatedFiles
	}
