/// The values a generated mock hands a `@Sendable` builder function that production creates inside it: a labeled
/// default-valued parameter of a type the function builds, which the mock reads from the type's
/// `SafeDIMockConfiguration`, and a dependency the mock cannot build, which `mock()` takes as a parameter. A
/// `@Sendable` function cannot capture either when its type is not `Sendable`, so the mock takes both as `@Sendable`
/// closures and calls them where it builds the type.
struct SafeDIToolSendableBuilderValueTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests – Default-valued parameters inside a `@Sendable` builder function

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_callsStoredDefaultWhereChildIsBuilt_whenNonSendableDefaultValuedParameterIsReachedThroughSendableInstantiator() async throws {
		// `Formatter` is not `Sendable`. Production calls `Child(grandchild:)` inside the `@Sendable` function, which
		// evaluates the default there. The mock stores the default as a `@Sendable` closure and calls it there too.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				public final class Formatter {
				    public init() {}
				}
				""",
				"""
				@Instantiable(generateMock: true)
				public struct Root: Instantiable {
				    public init(childBuilder: SendableInstantiator<Child>) { self.childBuilder = childBuilder }
				    @Instantiated let childBuilder: SendableInstantiator<Child>
				}
				""",
				"""
				@Instantiable
				public struct Child: Instantiable, Sendable {
				    public init(grandchild: Grandchild, formatter: Formatter = Formatter()) { self.grandchild = grandchild }
				    @Instantiated let grandchild: Grandchild
				}
				""",
				"""
				@Instantiable
				public struct Grandchild: Instantiable, Sendable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            childBuilder: Child.SafeDIMockConfiguration = .init()
		        ) {
		            self.childBuilder = childBuilder
		        }

		        let childBuilder: Child.SafeDIMockConfiguration
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        let __safeDI_childBuilder__childBuilder_grandchild_safeDIBuilder = safeDIOverrides.childBuilder.grandchild
		        let __safeDI_childBuilder__childBuilder_formatter = safeDIOverrides.childBuilder.formatter
		        let __safeDI_childBuilder__safeDIBuilder = safeDIOverrides.childBuilder.safeDIBuilder
		        @Sendable func __safeDI_childBuilder() -> Child {
		            let grandchild = if let safeDIBuilder = __safeDI_childBuilder__childBuilder_grandchild_safeDIBuilder { safeDIBuilder() } else { Grandchild() }
		            return if let safeDIBuilder = __safeDI_childBuilder__safeDIBuilder { safeDIBuilder(grandchild, __safeDI_childBuilder__childBuilder_formatter()) } else { Child(grandchild: grandchild, formatter: __safeDI_childBuilder__childBuilder_formatter()) }
		        }
		        let childBuilder = SendableInstantiator<Child>(__safeDI_childBuilder)
		        return Root(childBuilder: childBuilder)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")

		#expect(output.mockConfigurationFile == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Child {
		    /// Configuration for how this type is constructed within a mock tree.
		    struct SafeDIMockConfiguration {
		        init(
		            grandchild: (@Sendable () -> Grandchild)? = nil,
		            formatter: @autoclosure @escaping @Sendable () -> Formatter = Formatter(),
		            _ safeDIBuilder: (@Sendable (Grandchild, Formatter) -> Child)? = nil
		        ) {
		            self.grandchild = grandchild
		            self.formatter = formatter
		            self.safeDIBuilder = safeDIBuilder
		        }

		        let grandchild: (@Sendable () -> Grandchild)?
		        let formatter: @Sendable () -> Formatter
		        /// Overrides how this type is constructed. Parameters match the type’s initializer or custom mock method. When `nil`, the default generated construction function is used.
		        let safeDIBuilder: (@Sendable (Grandchild, Formatter) -> Child)?
		    }
		}
