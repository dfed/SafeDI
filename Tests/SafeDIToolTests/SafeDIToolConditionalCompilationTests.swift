@testable import SafeDITool

/// How `SafeDITool` scans `#if` blocks, verified from source to generated output.
///
/// Guarded types are roots, so whether a clause was scanned shows in the generated files,
/// and every decision shows as an assertion at the top of each file. An unconditional
/// `Root` carries the assertions when every guarded type is skipped. `STAGING` stands in
/// for a condition the build may or may not define; the verification compile defines it
/// exactly when the test supplies it.
struct SafeDIToolConditionalCompilationTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_scansElseClause_whenConditionIsFalse() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable
				public struct NetworkService: Instantiable {
				    public init() {}
				}
				""",
				"""
				#if false
				@Instantiable(isRoot: true)
				public struct InactiveService: Instantiable {
				    public init(networkService: NetworkService) {
				        self.networkService = networkService
				    }

				    @Instantiated let networkService: NetworkService
				}
				#else
				@Instantiable(isRoot: true)
				public struct ActiveService: Instantiable {
				    public init(networkService: NetworkService) {
				        self.networkService = networkService
				    }

				    @Instantiated let networkService: NetworkService
				}
				#endif
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.generatedFiles == [
			"InactiveService+SafeDI.swift": """
			// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
			// Any modifications made to this file will be overwritten on subsequent builds.
			// Please refrain from editing this file directly.

			extension ActiveService {
			    public init() {
			        let networkService = NetworkService()
			        self.init(networkService: networkService)
			    }
			}
			""",
		])
	}

