	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_qualifiesBuiltType_whenInstantiatedInstantiatorBuildsUnqualifiedNestedType() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				public enum Feature {
				    @Instantiable
				    public final class Service: Instantiable {
				        public init() {}
				    }

				    @Instantiable(isRoot: true)
				    public final class Root: Instantiable {
				        public init(serviceBuilder: Instantiator<Service>) {
				            self.serviceBuilder = serviceBuilder
				        }

				        @Instantiated let serviceBuilder: Instantiator<Service>
				    }
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(try #require(output.generatedFiles?["Service+SafeDI.swift"]) == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Feature.Root {
		    public convenience init() {
		        func __safeDI_serviceBuilder() -> Feature.Service {
		            Feature.Service()
		        }
		        let serviceBuilder = Instantiator<Feature.Service>(__safeDI_serviceBuilder)
		        self.init(serviceBuilder: serviceBuilder)
		    }
		}
		""")
	}

