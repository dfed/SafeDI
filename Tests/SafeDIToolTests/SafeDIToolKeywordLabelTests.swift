/// Labels that Swift requires in backticks where they declare or name a value: keywords such as `default`, and raw
/// identifiers such as `my leaf`. Generated code escapes such a label only where Swift requires it, so it neither
/// fails to compile nor warns, and never escapes a name it makes by joining text to a label.
struct SafeDIToolKeywordLabelTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_namesBuilderFunctionsWithoutBackticks_whenKeywordLabeledPropertiesAreBuiltByBuilderFunctions() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable
				public final class Leaf: Instantiable {
				    public init() {}
				}
				""",
				"""
				@Instantiable
				public final class Thing: Instantiable {
				    public init(leaf: Leaf) {
				        self.leaf = leaf
				    }

				    @Instantiated let leaf: Leaf
				}
				""",
				"""
				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init(`default`: Thing, `class`: Instantiator<Thing>) {
				        self.`default` = `default`
				        self.`class` = `class`
				    }

				    @Instantiated let `default`: Thing
				    @Instantiated let `class`: Instantiator<Thing>
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.dependencyTreeFiles["Root+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public convenience init() {
		        func __safeDI_default() -> Thing {
		            let leaf = Leaf()
		            return Thing(leaf: leaf)
		        }
		        let `default`: Thing = __safeDI_default()
		        func __safeDI_class() -> Thing {
		            let leaf = Leaf()
		            return Thing(leaf: leaf)
		        }
		        let `class` = Instantiator<Thing>(__safeDI_class)
		        self.init(default: `default`, class: `class`)
		    }
		}
		""", "Unexpected output \(output.dependencyTreeFiles["Root+SafeDI.swift"] ?? "")")
	}

