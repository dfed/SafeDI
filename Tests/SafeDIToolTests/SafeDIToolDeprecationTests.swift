import Foundation
import SafeDICore
import Testing
@testable import SafeDITool
@testable import SafeDIToolTestSupport

/// The command-line uses `generate` still accepts but warns about, because SafeDI 3.0 removes them: the
/// `--additional-imported-modules` option, and a manifest written by hand rather than by `scan`.
struct SafeDIToolDeprecationTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests – --additional-imported-modules

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_importsModuleAndWarnsThatOptionIsDeprecated_whenAdditionalImportedModulesIsPassed() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true)
				public struct Root: Instantiable {
				    public init(dependency: Dependency) {
				        self.dependency = dependency
				    }

				    @Instantiated let dependency: Dependency
				}
				""",
				"""
				@Instantiable
				public struct Dependency: Instantiable {
				    public init() {}
				}
				""",
			],
			additionalImportedModules: ["AnalyticsKit"],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.warnings == [
			SourceDiagnostic(
				severity: .warning,
				location: nil,
				message: "`--additional-imported-modules` is deprecated and will be removed in SafeDI 3.0: list its modules in the module’s `#SafeDIConfiguration` instead, as `#SafeDIConfiguration(additionalImportedModules: [\"AnalyticsKit\"])`.",
			),
		])
		#expect(output.dependencyTreeFiles == [
			"Root+SafeDI.swift": """
			// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
			// Any modifications made to this file will be overwritten on subsequent builds.
			// Please refrain from editing this file directly.

			#if canImport(AnalyticsKit)
			import AnalyticsKit
			#endif

			extension Root {
			    public init() {
			        let dependency = Dependency()
			        self.init(dependency: dependency)
			    }
			}
			""",
		])
	}

