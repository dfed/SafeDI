	// MARK: Tests – hand-written manifests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_writesOutputAndWarnsThatHandWrittenManifestsAreDeprecated_whenManifestLacksEveryFieldScanAlwaysWrites() async throws {
		let project = try makeProject()
		try await project.scan()
		try project.editManifest {
			$0.projectRoot = nil
			$0.activeCompilationConditions = nil
			$0.mockScopedFilePaths = nil
		}

		let generateOutput = try await project.generate()

		#expect(generateOutput.warnings == [project.handWrittenManifestWarning])
		let generatedFiles = try project.generatedFiles()
		#expect(generatedFiles == Self.expectedOutput)
		try verifyGeneratedCodeCompiles(
			inputSwiftFiles: [project.rootFile],
			additionalDirectorySwiftFiles: [],
			generatedFiles: generatedFiles,
			mockConditionalCompilation: nil,
			filesToDelete: &filesToDelete,
		)
	}

