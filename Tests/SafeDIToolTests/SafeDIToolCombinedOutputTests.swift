/// Every string in a decoded JSON value that is an absolute path.
private func absolutePaths(in jsonValue: Any) -> [String] {
	if let string = jsonValue as? String {
		(string as NSString).isAbsolutePath ? [string] : []
	} else if let array = jsonValue as? [Any] {
		array.flatMap(absolutePaths(in:))
	} else if let dictionary = jsonValue as? [String: Any] {
		dictionary.values.flatMap(absolutePaths(in:))
	} else {
		[]
	}
}
