	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_keepsSourceLocationPathRelative_whenCompilerReceivesRelativeInputPathsUnchanged() async throws {
		// Bazel's rule writes a CSV of execution-root-relative paths, runs
		// `generate --combined-output` with no `scan`, and states that rules_swift
		// hands the compiler those same paths. Hermetic, remotely cached output
		// requires the `#sourceLocation` directive to carry that relative path
		// verbatim rather than a machine-specific absolute one.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true)
				public struct Root: Instantiable {
				    public init(service: Service, consumer: Consumer) {
				        self.service = service
				        self.consumer = consumer
				    }

				    @Instantiated let service: Service
				    @Instantiated let consumer: Consumer
				}
				""",
				"""
				@Instantiable
				public struct Consumer: Instantiable {
				    public init(renamedService: Service) {
				        self.renamedService = renamedService
				    }

				    @Received(fulfilledByDependencyNamed: "service", ofType: Service.self) let renamedService: Service
				}
				""",
				"""
				@Instantiable
				public struct Service: Instantiable {
				    public init() {}
				}
				""",
			],
			buildCombinedOutput: true,
			filesToDelete: &filesToDelete,
			inputPathsRelativeToCurrentDirectory: true,
			compilerReceivesInputPathsUnchanged: true,
		)

		let consumerInputPath = output.fixtures["Consumer.swift"]
		#expect(!consumerInputPath.hasPrefix("/"), "Expected a relative input path but got \(consumerInputPath)")
		#expect(output.combinedOutput == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public init() {
		        let service = Service()
		        func __safeDI_consumer() -> Consumer {
		            #sourceLocation(file: "\(consumerInputPath)", line: 7)
		            let renamedService: Service = service
		            #sourceLocation()
		            return Consumer(renamedService: renamedService)
		        }
		        let consumer: Consumer = __safeDI_consumer()
		        self.init(service: service, consumer: consumer)
		    }
		}
		""", "Unexpected combined output: \(output.combinedOutput ?? "")")
	}

