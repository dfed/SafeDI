	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_combinedOutput_writesRootDependencyTreeAndMockIntoOneFile() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true, generateMock: true)
				public struct Root: Instantiable {
				    public init(dep: Dep) {
				        self.dep = dep
				    }
				    @Instantiated let dep: Dep
				}
				""",
				"""
				@Instantiable
				public struct Dep: Instantiable {
				    public init() {}
				}
				""",
			],
			buildCombinedOutput: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.combinedOutput == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public init() {
		        let dep = Dep()
		        self.init(dep: dep)
		    }
		}

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            dep: (() -> Dep)? = nil
		        ) {
		            self.dep = dep
		        }

		        let dep: (() -> Dep)?
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        let dep = (safeDIOverrides.dep ?? Dep.init)()
		        return Root(dep: dep)
		    }
		}
		#endif
		""", "Unexpected combined output: \(output.combinedOutput ?? "")")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_combinedOutput_includesSharedMockConfiguration_whenMocksShareConfigurationExtensions() async throws {
		// Middle lacks `generateMock: true`; its `SafeDIMockConfiguration`
		// extension therefore lives in the shared mock-configuration section
		// and gets appended onto the combined output.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true, generateMock: true)
				public struct Root: Instantiable {
				    public init(middle: Middle) {
				        self.middle = middle
				    }
				    @Instantiated let middle: Middle
				}
				""",
				"""
				@Instantiable
				public struct Middle: Instantiable {
				    public init(leaf: Leaf) {
				        self.leaf = leaf
				    }
				    @Instantiated let leaf: Leaf
				}
				""",
				"""
				@Instantiable
				public struct Leaf: Instantiable {
				    public init() {}
				}
				""",
			],
			buildCombinedOutput: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.combinedOutput == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public init() {
		        func __safeDI_middle() -> Middle {
		            let leaf = Leaf()
		            return Middle(leaf: leaf)
		        }
		        let middle: Middle = __safeDI_middle()
		        self.init(middle: middle)
		    }
		}

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            middle: Middle.SafeDIMockConfiguration = .init()
		        ) {
		            self.middle = middle
		        }

		        let middle: Middle.SafeDIMockConfiguration
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        func __safeDI_middle() -> Middle {
		            let leaf = (safeDIOverrides.middle.leaf ?? Leaf.init)()
		            return (safeDIOverrides.middle.safeDIBuilder ?? Middle.init(leaf:))(leaf)
		        }
		        let middle: Middle = __safeDI_middle()
		        return Root(middle: middle)
		    }
		}
		#endif

		#if DEBUG
		extension Middle {
		    /// Configuration for how this type is constructed within a mock tree.
		    struct SafeDIMockConfiguration {
		        init(
		            leaf: (() -> Leaf)? = nil,
		            _ safeDIBuilder: ((Leaf) -> Middle)? = nil
		        ) {
		            self.leaf = leaf
		            self.safeDIBuilder = safeDIBuilder
		        }

		        let leaf: (() -> Leaf)?
		        /// Overrides how this type is constructed. Parameters match the type’s initializer or custom mock method. When `nil`, the default generated construction function is used.
		        let safeDIBuilder: ((Leaf) -> Middle)?
		    }
		}
		#endif

		""", "Unexpected combined output: \(output.combinedOutput ?? "")")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_combinedOutput_isStableForStableInputsRegardlessOfFixtureOrdering() async throws {
		// Generating the same module twice — with the input files in different
		// declaration orders — should produce byte-identical combined output.
		// Guards against ordering non-determinism (dictionary iteration,
		// unsorted collections) leaking into the concatenated result.
		let fileAlpha = """
		@Instantiable(isRoot: true)
		public struct AlphaRoot: Instantiable {
		    public init(a: Alpha) {
		        self.a = a
		    }
		    @Instantiated let a: Alpha
		}
		"""
		let fileBeta = """
		@Instantiable(generateMock: true)
		public struct Alpha: Instantiable {
		    public init() {}
		}
		"""
		let fileGamma = """
		@Instantiable(isRoot: true)
		public struct BetaRoot: Instantiable {
		    public init(a: Alpha) {
		        self.a = a
		    }
		    @Instantiated let a: Alpha
		}
		"""

		let firstOutput = try await executeSafeDIToolTest(
			swiftFileContent: [fileAlpha, fileBeta, fileGamma],
			buildCombinedOutput: true,
			filesToDelete: &filesToDelete,
		)
		let secondOutput = try await executeSafeDIToolTest(
			swiftFileContent: [fileGamma, fileBeta, fileAlpha],
			buildCombinedOutput: true,
			filesToDelete: &filesToDelete,
		)

		let first = try #require(firstOutput.combinedOutput)
		let second = try #require(secondOutput.combinedOutput)
		#expect(first == second, "Combined output drifted with input order:\n--- first ---\n\(first)\n--- second ---\n\(second)")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_combinedOutput_writesParseErrorStub_whenSourcesContainUnexpectedSwiftNodes() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init(dep: Dep) {
				        self.dep = dep
				    }

				    :::brokenSyntax

				    @Instantiated let dep: Dep
				}

				@Instantiable
				public final class Dep: Instantiable {
				    public init() {}
				}
				""",
			],
			buildCombinedOutput: true,
			filesToDelete: &filesToDelete,
			skipCompileVerification: true,
		)

		let combined = try #require(output.combinedOutput)
		// Normalize the fixture's absolute-path line so the
		// comparison is portable across runs.
		let normalized = combined.replacing(#/\t[^\n]+?\.swift/#, with: "\t<FIXTURE_PATH>/Root.swift")
		#expect(normalized == """
