	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_combinedOutput_listsDependentModuleFilesWithErrorsInModuleInfoPathOrder_whenManyDependentModulesHaveSyntaxErrors() async throws {
		// Dependent module info is read in parallel. With eight modules, an order taken from the reads
		// finishing, or from iterating a set of their paths, matches path order in about one run in 40,000.
		var dependentModuleOutputs = [(fileName: String, output: TestOutput)]()
		for index in 1...8 {
			try await dependentModuleOutputs.append((fileName: "Broken\(index).swift", output: executeSafeDIToolTest(
				swiftFileContent: [
					"""
					@Instantiable
					public final class Broken\(index): Instantiable {
					    public init() {}

					    :::brokenSyntax
					}
					""",
				],
				filesToDelete: &filesToDelete,
				skipCompileVerification: true,
			)))
		}
		let dependentModuleOutputsInPathOrder = dependentModuleOutputs.sorted { $0.output.moduleInfoOutputPath < $1.output.moduleInfoOutputPath }

		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init() {}
				}
				""",
			],
			// Listed in the reverse of path order, which the generated code does not follow.
			dependentModuleInfoPaths: dependentModuleOutputsInPathOrder.reversed().map(\.output.moduleInfoOutputPath),
			buildCombinedOutput: true,
			filesToDelete: &filesToDelete,
			skipCompileVerification: true,
		)

		let filesWithErrors = dependentModuleOutputsInPathOrder.map { $0.output.fixtures[$0.fileName] }
		#expect(output.combinedOutput == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#error(\"\"\"
		SafeDI could not generate code because these files have syntax errors. Fix them and build again:
			\(filesWithErrors.joined(separator: "\n\t"))
		\"\"\")
		""", "Unexpected combined output: \(output.combinedOutput ?? "")")
	}

