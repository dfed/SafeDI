	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_combinedOutput_emitsLocalMockOnlyOnce_whenTypeIsInBothGenerateMockAndAdditionalMocksToGenerate() async throws {
		// A local type declared with `generateMock: true` that is
		// *also* listed in `additionalMocksToGenerate` would otherwise
		// be emitted twice in combined mode — once via the per-source
		// loop and once via the per-type loop — producing duplicate
		// `extension` blocks that fail to compile.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				#SafeDIConfiguration(
				    additionalMocksToGenerate: [
				        "LocalService",
				    ]
				)
				""",
				"""
				@Instantiable(isRoot: true, generateMock: true)
				public struct Root: Instantiable {
				    public init(service: LocalService) {
				        self.service = service
				    }
				    @Instantiated let service: LocalService
				}
				""",
				"""
				@Instantiable(generateMock: true)
				public struct LocalService: Instantiable {
				    public init() {}
				}
				""",
			],
			buildCombinedOutput: true,
			filesToDelete: &filesToDelete,
		)

		// Per-source loop iterates source files alphabetically:
		// `LocalService.swift` < `Root.swift`, so LocalService's mock
		// is emitted first. The `additionalMocksToGenerate` loop then
		// skips `LocalService` because the per-source loop already
		// emitted it — exactly one extension per type.
		#expect(output.combinedOutput == """
