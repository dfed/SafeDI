		// The Tuist plugin, at this release and earlier ones, hands `generate --combined-output` paths relative to
		// `$SRCROOT` while Xcode hands the compiler absolute paths, and Tuist shares its build cache across
		// machines. A `#sourceLocation` directive naming the relative path would warn, so each alias names its
		// declaration in a comment, and neither output holds a path specific to the machine.
		let output = try await executeSafeDIToolTest(
