	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_manifest_throwsValidationError_whenDependencyTreeGenerationContainsDuplicateInputFilePath() async throws {
		// Manifest JSON is user-supplied; a duplicate `inputFilePath`
		// must surface as a recoverable `ValidationError` rather than a
		// `Dictionary(uniqueKeysWithValues:)` runtime trap.
		let tempDir = FileManager.default.temporaryDirectory
			.appendingPathComponent("SafeDIToolDuplicateManifestTest-\(UUID().uuidString)", isDirectory: true)
		try FileManager.default.createDirectory(at: tempDir, withIntermediateDirectories: true)
		filesToDelete.append(tempDir)

		let sourceURL = tempDir.appendingPathComponent("Root.swift")
		try """
		@Instantiable(isRoot: true)
		public struct Root: Instantiable {
		    public init() {}
		}
		""".write(to: sourceURL, atomically: true, encoding: .utf8)

		let csvURL = tempDir.appendingPathComponent("sources.csv")
		try sourceURL.path.write(to: csvURL, atomically: true, encoding: .utf8)

		let outputURL = tempDir.appendingPathComponent("Root+SafeDI.swift")
		let manifest = SafeDIToolManifest(
			dependencyTreeGeneration: [
				.init(inputFilePath: sourceURL.path, outputFilePath: outputURL.path),
				.init(inputFilePath: sourceURL.path, outputFilePath: outputURL.path),
			],
		)
		let manifestURL = tempDir.appendingPathComponent("manifest.json")
		try JSONEncoder().encode(manifest).write(to: manifestURL)

		let tool = try Generate.parse([
			csvURL.path,
			"--swift-manifest", manifestURL.path,
		])

		await assertThrowsError(
			containing: "Manifest contains duplicate dependencyTreeGeneration inputFilePath",
		) {
			try await tool.run()
		}
	}

