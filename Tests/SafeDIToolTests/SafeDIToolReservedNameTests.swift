@testable import SafeDITool

/// Why `safeDIOverrides` and the constructed type names in `ReservedName` are reserved, and why the other names
/// generated code introduces need not be.
///
/// The `@Instantiable` macro rejects a reserved name, so a fixture that declares one cannot be compiled: the tests that
/// show a collision run SafeDITool on such a fixture and compile the generated code alongside `expandedFixture`, the
/// same declarations without the macro attributes, which is what the macros expand them to once nothing is reported.
struct SafeDIToolReservedNameTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_failsToCompile_whenForwardedPropertyIsNamedSafeDIOverrides() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(generateMock: true)
				public struct Root: Instantiable {
				    public init(safeDIOverrides: String, child: Child) {
				        self.safeDIOverrides = safeDIOverrides
				        self.child = child
				    }

				    @Forwarded let safeDIOverrides: String
				    @Instantiated let child: Child
				}
				""",
				"""
				@Instantiable
				public struct Child: Instantiable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
			skipCompileVerification: true,
		)

		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            child: (() -> Child)? = nil
		        ) {
		            self.child = child
		        }

		        let child: (() -> Child)?
		    }

		    static func mock(
		        safeDIOverrides: String,
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        let child = if let safeDIBuilder = safeDIOverrides.child { safeDIBuilder() } else { Child() }
		        return Root(safeDIOverrides: safeDIOverrides, child: child)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")
		try expectCompilationFailure(
			of: output,
			alongside: """
			public struct Root: Instantiable {
			    public init(safeDIOverrides: String, child: Child) {
			        self.safeDIOverrides = safeDIOverrides
			        self.child = child
			    }

			    let safeDIOverrides: String
			    let child: Child

			    public typealias ForwardedProperties = String
			}

			public struct Child: Instantiable {
			    public init() {}
			}
			""",
			reporting: "invalid redeclaration of 'safeDIOverrides'",
		)
	}

	@Test(arguments: ConstructedTypeCollision.all)
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func dependencyTree_failsToCompile_whenPropertyIsNamedForConstructedType(_ collision: ConstructedTypeCollision) async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true)
				public struct Root: Instantiable {
				    public init(\(collision.typeName): Service, serviceWrapper: \(collision.wrapperType)) {
				        self.\(collision.typeName) = \(collision.typeName)
				        self.serviceWrapper = serviceWrapper
				    }

				    @Instantiated let \(collision.typeName): Service
				    @Instantiated\(collision.attributeArguments) let serviceWrapper: \(collision.wrapperType)
				}
				""",
				"""
				public protocol ServiceProtocol: Sendable {}

				@Instantiable(fulfillingAdditionalTypes: [ServiceProtocol.self])
				public struct Service: Instantiable, ServiceProtocol {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
			skipCompileVerification: true,
		)

		#expect(output.dependencyTreeFiles["Root+SafeDI.swift"] == collision.expectedOutput, "Unexpected output \(output.dependencyTreeFiles["Root+SafeDI.swift"] ?? "")")
		try expectCompilationFailure(
			of: output,
			alongside: """
			public struct Root: Instantiable {
			    public init(\(collision.typeName): Service, serviceWrapper: \(collision.wrapperType)) {
			        self.\(collision.typeName) = \(collision.typeName)
			        self.serviceWrapper = serviceWrapper
			    }

			    let \(collision.typeName): Service
			    let serviceWrapper: \(collision.wrapperType)
			}

			public protocol ServiceProtocol: Sendable {}

			public struct Service: Instantiable, ServiceProtocol {
			    public init() {}
			}
			""",
			reporting: "cannot specialize non-generic type 'Service'",
		)
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_compiles_whenWrappedOnlyIfAvailableOverrideIsNamedInstance() async throws {
		// The closure that wraps an `onlyIfAvailable` override names its parameter `instance`, and uses nothing else
		// that a dependency named `instance` could shadow.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(generateMock: true)
				public final class Screen: Instantiable {
				    public init(home: Home) {
				        fatalError("SafeDI doesn't inspect the initializer body")
				    }

				    @Instantiated let home: Home
				}
				""",
				"""
				@Instantiable
				public final class Home: Instantiable {
				    public init(instance: LazilyInstantiated<Analytics>?) {
				        fatalError("SafeDI doesn't inspect the initializer body")
				    }

				    @Received(onlyIfAvailable: true) let instance: LazilyInstantiated<Analytics>?
				}
				""",
				"""
				@Instantiable
				public final class Analytics: Instantiable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.mockFiles["Screen+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Screen {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            home: ((LazilyInstantiated<Analytics>?) -> Home)? = nil,
		            instance: Analytics? = nil
		        ) {
		            self.home = home
		            self.instance = instance
		        }

		        let home: ((LazilyInstantiated<Analytics>?) -> Home)?
		        let instance: Analytics?
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Screen {
		        let instance: Analytics? = safeDIOverrides.instance
		        let instance_lazilyInstantiated = instance.map { instance in LazilyInstantiated<Analytics> { instance } }
		        let home = if let safeDIBuilder = safeDIOverrides.home { safeDIBuilder(instance_lazilyInstantiated) } else { Home(instance: instance_lazilyInstantiated) }
		        return Screen(home: home)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Screen+SafeDIMock.swift"] ?? "")")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_compiles_whenPropertiesAreNamedForGeneratedMembers() async throws {
		// `SafeDIOverrides`, `SafeDIMockConfiguration`, `ForwardedProperties`, and `mock` are members SafeDI generates in
		// the types it extends. A property of the same name does not collide with them, and generated code never names
		// them where a property's binding could shadow them.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(generateMock: true)
				public struct Root: Instantiable {
				    public init(SafeDIOverrides: Child, mock: Leaf, formBuilder: Instantiator<Form>) {
				        self.SafeDIOverrides = SafeDIOverrides
				        self.mock = mock
				        self.formBuilder = formBuilder
				    }

				    @Instantiated let SafeDIOverrides: Child
				    @Instantiated let mock: Leaf
				    @Instantiated let formBuilder: Instantiator<Form>
				}
				""",
				"""
				@Instantiable
				public struct Child: Instantiable {
				    public init(SafeDIMockConfiguration: Leaf) {
				        self.SafeDIMockConfiguration = SafeDIMockConfiguration
				    }

				    @Instantiated let SafeDIMockConfiguration: Leaf
				}
				""",
				"""
				@Instantiable
				public struct Form: Instantiable {
				    public init(ForwardedProperties: String) {
				        self.ForwardedProperties = ForwardedProperties
				    }

				    @Forwarded let ForwardedProperties: String
				}
				""",
				"""
				@Instantiable
				public struct Leaf: Instantiable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            SafeDIOverrides: Child.SafeDIMockConfiguration = .init(),
		            mock: (() -> Leaf)? = nil,
		            formBuilder: ((String) -> Form)? = nil
		        ) {
		            self.SafeDIOverrides = SafeDIOverrides
		            self.mock = mock
		            self.formBuilder = formBuilder
		        }

		        let SafeDIOverrides: Child.SafeDIMockConfiguration
		        let mock: (() -> Leaf)?
		        let formBuilder: ((String) -> Form)?
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        func __safeDI_SafeDIOverrides() -> Child {
		            let SafeDIMockConfiguration = if let safeDIBuilder = safeDIOverrides.SafeDIOverrides.SafeDIMockConfiguration { safeDIBuilder() } else { Leaf() }
		            return if let safeDIBuilder = safeDIOverrides.SafeDIOverrides.safeDIBuilder { safeDIBuilder(SafeDIMockConfiguration) } else { Child(SafeDIMockConfiguration: SafeDIMockConfiguration) }
		        }
		        let SafeDIOverrides: Child = __safeDI_SafeDIOverrides()
		        let mock = if let safeDIBuilder = safeDIOverrides.mock { safeDIBuilder() } else { Leaf() }
		        func __safeDI_formBuilder(ForwardedProperties: String) -> Form {
		            if let safeDIBuilder = safeDIOverrides.formBuilder { safeDIBuilder(ForwardedProperties) } else { Form(ForwardedProperties: ForwardedProperties) }
		        }
		        let formBuilder = Instantiator<Form> {
		            __safeDI_formBuilder(ForwardedProperties: $0)
		        }
		        return Root(SafeDIOverrides: SafeDIOverrides, mock: mock, formBuilder: formBuilder)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")
		#expect(output.mockConfigurationFile == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Child {
		    /// Configuration for how this type is constructed within a mock tree.
		    struct SafeDIMockConfiguration {
		        init(
		            SafeDIMockConfiguration: (() -> Leaf)? = nil,
		            _ safeDIBuilder: ((Leaf) -> Child)? = nil
		        ) {
		            self.SafeDIMockConfiguration = SafeDIMockConfiguration
		            self.safeDIBuilder = safeDIBuilder
		        }

		        let SafeDIMockConfiguration: (() -> Leaf)?
		        /// Overrides how this type is constructed. Parameters match the type’s initializer or custom mock method. When `nil`, the default generated construction function is used.
		        let safeDIBuilder: ((Leaf) -> Child)?
		    }
		}
		#endif

		""", "Unexpected output \(output.mockConfigurationFile ?? "")")
	}

