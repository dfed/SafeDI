	// MARK: Private

	private var filesToDelete: [URL]

	/// Compiles the code SafeDITool generated in `output` alongside `expandedFixture`, and expects the compile to fail
	/// with a diagnostic containing `diagnostic`. Does nothing when compile verification is disabled.
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	private mutating func expectCompilationFailure(
		of output: borrowing TestOutput,
		alongside expandedFixture: String,
		reporting diagnostic: String,
		sourceLocation: SourceLocation = #_sourceLocation,
	) throws {
		guard compileVerificationIsEnabled else { return }
		let artifacts = try #require(SafeDIBuildArtifactLocator.locate(), sourceLocation: sourceLocation)
		let fixtureFile = FileManager.default.temporaryDirectory.appendingPathComponent("ExpandedFixture-\(UUID().uuidString).swift")
		try expandedFixture.write(to: fixtureFile, atomically: true, encoding: .utf8)
		filesToDelete.append(fixtureFile)
		let staged = try stageCompileSources(
			inputSwiftFiles: [fixtureFile],
			generatedFiles: output.generatedFiles ?? [:],
			filesToDelete: &filesToDelete,
		)
		let fixtureResult = try compileSwift(
			sources: staged.inputFiles,
			outputDirectory: staged.directory,
			artifacts: artifacts,
		)
		#expect(fixtureResult.exitCode == 0, "The expanded fixture must compile on its own: \(fixtureResult.stderr)", sourceLocation: sourceLocation)
		let result = try compileSwift(
			sources: staged.inputFiles + staged.generatedFiles,
			outputDirectory: staged.directory,
			artifacts: artifacts,
		)
		#expect(result.exitCode != 0, sourceLocation: sourceLocation)
		#expect(result.stderr.contains(diagnostic), "Unexpected compiler output \(result.stderr)", sourceLocation: sourceLocation)
	}
