@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

struct SafeDIToolCombinedOutputMockFileTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_splitCombinedOutputMocks_writesTreesToCombinedFileAndEachMockWholeToFileItsTypeNamePicks() async throws {
		let outputs = try await generateSplitting(
			swiftFileContentByName: [
				"Root": """
				@Instantiable(isRoot: true, generateMock: true)
				public struct Root: Instantiable {
				    public init(first: First, second: Second) {
				        self.first = first
				        self.second = second
				    }
				    @Instantiated let first: First
				    @Instantiated let second: Second
				}
				""",
				"First": """
				@Instantiable(generateMock: true)
				public struct First: Instantiable {
				    public init() {}
				}
				""",
				"Second": """
				@Instantiable(generateMock: true)
				public struct Second: Instantiable {
				    public init() {}
				}
				""",
			],
		)

		#expect(outputs.combined == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public init() {
		        let first = First()
		        let second = Second()
		        self.init(first: first, second: second)
		    }
		}
		""")
		#expect(outputs.mockFilesHoldingCodeByNumber == [
			30: """
			// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
			// Any modifications made to this file will be overwritten on subsequent builds.
			// Please refrain from editing this file directly.

			#if DEBUG
			extension Second {
			    static func mock() -> Second {
			        Second()
			    }
			}
			#endif
			""",
			2: """
			// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
			// Any modifications made to this file will be overwritten on subsequent builds.
			// Please refrain from editing this file directly.

			#if DEBUG
			extension First {
			    static func mock() -> First {
			        First()
			    }
			}
			#endif
			""",
			6: """
			// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
			// Any modifications made to this file will be overwritten on subsequent builds.
			// Please refrain from editing this file directly.

			#if DEBUG
			extension Root {
			    /// Overrides for the mock dependency tree.
			    struct SafeDIOverrides {
			        init(
			            first: (() -> First)? = nil,
			            second: (() -> Second)? = nil
			        ) {
			            __safeDI_storage = __safeDI_Storage(
			                first: first,
			                second: second
			            )
			        }

			        var first: (() -> First)? { __safeDI_storage.first }
			        var second: (() -> Second)? { __safeDI_storage.second }

			        private let __safeDI_storage: __safeDI_Storage

			        private final class __safeDI_Storage {
			            init(
			                first: (() -> First)?,
			                second: (() -> Second)?
			            ) {
			                self.first = first
			                self.second = second
			            }

			            let first: (() -> First)?
			            let second: (() -> Second)?
			        }
			    }

			    static func mock(
			        safeDIOverrides: SafeDIOverrides = .init()
			    ) -> Root {
			        let first = if let safeDIBuilder = safeDIOverrides.first { safeDIBuilder() } else { First() }
			        let second = if let safeDIBuilder = safeDIOverrides.second { safeDIBuilder() } else { Second() }
			        return Root(first: first, second: second)
			    }
			}
			#endif
			""",
		])
		#expect(outputs.headerOnlyMockFileCount == 29)
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_splitCombinedOutputMocks_writesOnlyHeaderToEveryOtherMockFile() async throws {
		let outputs = try await generateSplitting(
			swiftFileContentByName: [
				"Root": """
				@Instantiable(isRoot: true)
				public struct Root: Instantiable {
				    public init(first: First) {
				        self.first = first
				    }
				    @Instantiated let first: First
				}
				""",
				"First": """
				@Instantiable(generateMock: true)
				public struct First: Instantiable {
				    public init() {}
				}
				""",
			],
		)

		#expect(outputs.combined == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public init() {
		        let first = First()
		        self.init(first: first)
		    }
		}
		""")
		#expect(outputs.mockFilesHoldingCodeByNumber == [
			2: """
			// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
			// Any modifications made to this file will be overwritten on subsequent builds.
			// Please refrain from editing this file directly.

			#if DEBUG
			extension First {
			    static func mock() -> First {
			        First()
			    }
			}
			#endif
			""",
		])
		#expect(outputs.headerOnlyMockFileCount == 31)
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_splitCombinedOutputMocks_writesParseErrorStubToEveryFile_whenSourcesContainUnexpectedSwiftNodes() async throws {
		let outputs = try await generateSplittingIntoFiles(
			swiftFileContentByName: [
				"Root": """
				@Instantiable(isRoot: true, generateMock: true)
				public final class Root: Instantiable {
				    public init() {}

				    :::brokenSyntax
				}
				""",
			],
		)

		let normalized = outputs.map { $0.replacing(#/\t[^\n]+?\.swift/#, with: "\t<FIXTURE_PATH>/Root.swift") }
		let stub = """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#error(\"\"\"
		SafeDI could not generate code because these files have syntax errors. Fix them and build again:
			<FIXTURE_PATH>/Root.swift
		\"\"\")
		"""
		#expect(normalized == Array(repeating: stub, count: 33), "Unexpected outputs: \(normalized.joined(separator: "\n----\n"))")
	}

