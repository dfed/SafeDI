	// MARK: Private

	private var filesToDelete: [URL]

	/// Runs `generate` over one file per entry of `swiftFileContentByName`, named `<name>.swift`, splitting the mocks, and
	/// returns the combined output and, by number, each mock file that holds more than its header. Each mock file is listed
	/// by its number alone since 32 of them hold the header only in most tests; the header-only ones are counted.
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	private mutating func generateSplitting(swiftFileContentByName: [String: String]) async throws -> (combined: String, mockFilesHoldingCodeByNumber: [Int: String], headerOnlyMockFileCount: Int) {
		let files = try await generateSplittingIntoFiles(swiftFileContentByName: swiftFileContentByName)
		let headerOnly = """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.


		"""
		var mockFilesHoldingCodeByNumber = [Int: String]()
		var headerOnlyMockFileCount = 0
		for (index, file) in files.dropFirst().enumerated() {
			if file == headerOnly {
				headerOnlyMockFileCount += 1
			} else {
				mockFilesHoldingCodeByNumber[index + 1] = file
			}
		}
		return (combined: files[0], mockFilesHoldingCodeByNumber: mockFilesHoldingCodeByNumber, headerOnlyMockFileCount: headerOnlyMockFileCount)
	}

	/// Runs `generate` over one file per entry of `swiftFileContentByName`, named `<name>.swift`, splitting the mocks, and
	/// returns the combined output followed by each of the 32 mock files, in order.
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	private mutating func generateSplittingIntoFiles(swiftFileContentByName: [String: String]) async throws -> [String] {
		let sourceDirectory = TestTemporaryDirectory.root
			.appendingPathComponent("SafeDIToolMockFileTest-\(UUID().uuidString)", isDirectory: true)
		try FileManager.default.createDirectory(at: sourceDirectory, withIntermediateDirectories: true)
		filesToDelete.append(sourceDirectory)
		for (name, content) in swiftFileContentByName {
			try content.write(to: sourceDirectory.appendingPathComponent("\(name).swift"), atomically: true, encoding: .utf8)
		}
		let outputDirectory = TestTemporaryDirectory.root
			.appendingPathComponent("SafeDIToolMockFileOutput-\(UUID().uuidString)", isDirectory: true)
		try FileManager.default.createDirectory(at: outputDirectory, withIntermediateDirectories: true)
		filesToDelete.append(outputDirectory)
		let combinedOutput = outputDirectory.appendingPathComponent("Generated.swift")

		let tool = try Generate.parse([
			"--include", sourceDirectory.path,
			"--combined-output", combinedOutput.path,
			"--split-combined-output-mocks",
		])
		try await tool.run()

		let outputPaths = [combinedOutput] + (1...32).map { outputDirectory.appendingPathComponent("Generated_Mocks\($0).swift") }
		#expect(try FileManager.default.contentsOfDirectory(atPath: outputDirectory.path).sorted() == outputPaths.map(\.lastPathComponent).sorted())
		return try outputPaths.map { try String(contentsOf: $0, encoding: .utf8) }
	}
}
