	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func query_reportsErasedReceiveAsUnfulfilled_whenTheConcreteTypeErasedDeclaresForwardedProperties() async throws {
		let output = try await executeSafeDIToolQuery(
			typeName: "Feature",
			modules: [
				QueryTestModule("FeatureModule", [
					"""
					@Instantiable
					public final class Feature: Instantiable {
					    public init(editor: AnyEditor) {
					        self.editor = editor
					    }
					    @Received private let editor: AnyEditor
					}
					""",
				]),
				QueryTestModule("EditorModule", [
					"""
					public protocol EditorProtocol {}

					public struct AnyEditor: EditorProtocol {
					    public init(_ editor: some EditorProtocol) {}
					}
					""",
					"""
					@Instantiable
					public final class DefaultEditor: EditorProtocol, Instantiable {
					    public init(draft: Draft) {
					        self.draft = draft
					    }
					    @Forwarded private let draft: Draft
					}
					""",
					"""
					@Instantiable
					public final class EditorHub: Instantiable {
					    public init(editor: AnyEditor) {
					        self.editor = editor
					    }
					    @Instantiated(fulfilledByType: "DefaultEditor", erasedToConcreteExistential: true) private let editor: AnyEditor
					}
					""",
				]),
			],
			filesToDelete: &filesToDelete,
		)

		#expect(output.result.modules.map(\.name) == ["FeatureModule"])
		#expect(output.result.unfulfilledDependencies == [
			TypeReport.UnfulfilledDependency(
				label: "editor",
				type: "AnyEditor",
				reasonKind: .typeHasForwardedProperties,
				reason: "`DefaultEditor` declares @Forwarded properties (`draft: Draft`), so only an `Instantiator` handed their values can build it.",
			),
		])
	}

