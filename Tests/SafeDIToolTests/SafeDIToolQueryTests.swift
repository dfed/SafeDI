	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func query_reportsForwardedParameterAsDefaulted_whenHandWrittenMockOfMockedTypeDefaultsIt() async throws {
		let output = try await executeSafeDIToolQuery(
			typeName: "Feature",
			modules: [
				QueryTestModule("FeatureModule", [
					"""
					@Instantiable(generateMock: true, customMockName: "preview")
					public final class Feature: Instantiable {
					    public init(user: User) {
					        self.user = user
					    }
					    @Forwarded private let user: User

					    public static func preview(user: User = User()) -> Feature {
					        Feature(user: user)
					    }
					}
					""",
				]),
			],
			filesToDelete: &filesToDelete,
		)

		#expect(output.result.forwardedParameters == [
			TypeReport.ForwardedParameter(label: "user", type: "User", defaultExpression: nil),
		])
		#expect(output.result.modules == [
			output.module("FeatureModule", [
				output.instantiable("Feature", in: "FeatureModule"),
			]),
		])
		#expect(output.result.mock?.forwardedParameters == [
			TypeReport.ForwardedParameter(label: "user", type: "User", defaultExpression: "User()"),
		])
		#expect(output.result.mock?.modules == [
			output.module("FeatureModule", [
				output.instantiable("Feature", in: "FeatureModule"),
				output.handWrittenMock("Feature", "preview", in: "FeatureModule"),
			]),
		])
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func query_reportsInstantiatedDependencyAsUnfulfilled_whenNoDeclarationFulfillsItsType() async throws {
		let output = try await executeSafeDIToolQuery(
			typeName: "Feature",
			modules: [
				QueryTestModule("FeatureModule", [
					"""
					@Instantiable
					public final class Feature: Instantiable {
					    public init(widget: Widget, service: Service) {
					        self.widget = widget
					        self.service = service
					    }
					    @Instantiated private let widget: Widget
					    @Instantiated private let service: Service
					}
					""",
					"""
					@Instantiable
					public final class Service: Instantiable {
					    public init(gauge: Instantiator<Gauge>) {
					        self.gauge = gauge
					    }
					    @Instantiated private let gauge: Instantiator<Gauge>
					}
					""",
				]),
			],
			filesToDelete: &filesToDelete,
		)

		// `Widget` and `Gauge` have no `@Instantiable` declaration, so the project provides them, as a root would reject them.
		#expect(output.result.unfulfilledDependencies == [
			TypeReport.UnfulfilledDependency(label: "widget", type: "Widget", reasonKind: .noInstantiableFulfillsType, reason: "No @Instantiable declaration fulfills `Widget`."),
			TypeReport.UnfulfilledDependency(label: "gauge", type: "Instantiator<Gauge>", reasonKind: .noInstantiableFulfillsType, reason: "No @Instantiable declaration fulfills `Gauge`."),
		])
	}

