	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_writesConvenienceExtensionOnRootOfTree_whenRootLazilyInstantiatesPropertyWithItsOwnSubtree() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init(clock: Clock, analytics: LazilyInstantiated<Analytics>) {
				        fatalError("SafeDI doesn't inspect the initializer body")
				    }

				    @Instantiated let clock: Clock
				    @Instantiated let analytics: LazilyInstantiated<Analytics>
				}
				""",
				"""
				@Instantiable
				public final class Clock: Instantiable {
				    public init() {}
				}
				""",
				"""
				@Instantiable
				public final class Analytics: Instantiable {
				    public init(clock: Clock, uploader: Uploader) {
				        fatalError("SafeDI doesn't inspect the initializer body")
				    }

				    @Received let clock: Clock
				    @Instantiated let uploader: Uploader
				}
				""",
				"""
				@Instantiable
				public final class Uploader: Instantiable {
				    public init(clock: Clock) {
				        fatalError("SafeDI doesn't inspect the initializer body")
				    }

				    @Received let clock: Clock
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(try #require(output.generatedFiles?["Root+SafeDI.swift"]) == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public convenience init() {
		        let clock = Clock()
		        func __safeDI_analytics() -> Analytics {
		            let uploader = Uploader(clock: clock)
		            return Analytics(clock: clock, uploader: uploader)
		        }
		        let analytics = LazilyInstantiated<Analytics>(__safeDI_analytics)
		        self.init(clock: clock, analytics: analytics)
		    }
		}
		""")
	}

