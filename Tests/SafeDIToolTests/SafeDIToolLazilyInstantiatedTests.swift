	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_writesConvenienceExtensionOnRootOfTree_passesNilToOnlyIfAvailableReceiver_whenReceiverReceivesOptionalLazilyInstantiatedPropertyThatBuildsIt() async throws {
		// B, built inside `a: LazilyInstantiated<A>?`, receives that exact property only if available. It is
		// validated as its constant twin `a: A?`, which B is passed `nil` for, so B gets `nil` here too.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init(a: LazilyInstantiated<A>?) { self.a = a }
				    @Instantiated let a: LazilyInstantiated<A>?
				}
				""",
				"""
				@Instantiable
				public final class A: Instantiable {
				    public init(b: B) { self.b = b }
				    @Instantiated let b: B
				}
				""",
				"""
				@Instantiable
				public final class B: Instantiable {
				    public init(a: LazilyInstantiated<A>?) { self.a = a }
				    @Received(onlyIfAvailable: true) let a: LazilyInstantiated<A>?
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(try #require(output.generatedFiles?["Root+SafeDI.swift"]) == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public convenience init() {
		        func __safeDI_a() -> A {
		            let b = B(a: nil)
		            return A(b: b)
		        }
		        let a = LazilyInstantiated<A>(__safeDI_a)
		        self.init(a: a)
		    }
		}
		""")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_writesConvenienceExtensionOnRootOfTree_omitsOnlyIfAvailableAliasAndPassesNil_whenReceiverAliasesLazilyInstantiatedPropertyThatBuildsIt() async throws {
		// B, built inside `a: LazilyInstantiated<A>`, aliases `a` only if available. `a` is still being built, so the
		// alias is not bound and B gets `nil`, as it does for the constant twin `a: A`.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init(a: LazilyInstantiated<A>) { self.a = a }
				    @Instantiated let a: LazilyInstantiated<A>
				}
				""",
				"""
				@Instantiable
				public final class A: Instantiable {
				    public init(b: B) { self.b = b }
				    @Instantiated let b: B
				}
				""",
				"""
				@Instantiable
				public final class B: Instantiable {
				    public init(renamedA: LazilyInstantiated<A>?) { self.renamedA = renamedA }
				    @Received(fulfilledByDependencyNamed: "a", ofType: LazilyInstantiated<A>.self, onlyIfAvailable: true) let renamedA: LazilyInstantiated<A>?
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(try #require(output.generatedFiles?["Root+SafeDI.swift"]) == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public convenience init() {
		        func __safeDI_a() -> A {
		            func __safeDI_b() -> B {
		                // Did not create `renamedA: LazilyInstantiated<A>?` because `a: LazilyInstantiated<A>` is unavailable.
		                return B(renamedA: nil)
		            }
		            let b: B = __safeDI_b()
		            return A(b: b)
		        }
		        let a = LazilyInstantiated<A>(__safeDI_a)
		        self.init(a: a)
		    }
		}
		""")
	}

