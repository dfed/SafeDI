/// A `@Sendable` builder function that generated code declares inside an initializer or a `mock()` on a global actor is
/// on that actor too, unless it says otherwise, and the compiler rejects a synchronous `@Sendable` local function on an
/// actor. In a module whose declarations default to the main actor, every generated initializer of a type nothing else
/// isolates is on the main actor; in any module, so is one of a type declared `@MainActor`, or bound to it through
/// `generatedInitializerAttributes` or `mockAttributes`. So every such function is declared `@Sendable nonisolated`,
/// which changes nothing where the function compiles without it.
struct SafeDIToolSendableBuilderDefaultIsolationTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test(arguments: ModuleDefaultIsolation.allCases)
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_declaresSendableBuilderFunctionsNonisolated_whenMainActorRootBuildsSendableWrappers(isolation: ModuleDefaultIsolation) async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@MainActor
				@Instantiable(isRoot: true, generateMock: true)
				public final class Hub: Instantiable {
				    public init(
				        detailBuilder: SendableInstantiator<Detail>,
				        lazyPart: SendableLazilyInstantiated<Part>,
				        forwardingBuilder: SendableInstantiator<Forwarding>,
				        erasedBuilder: SendableErasedInstantiator<String, any Named>
				    ) {
				        self.detailBuilder = detailBuilder
				        self.lazyPart = lazyPart
				        self.forwardingBuilder = forwardingBuilder
				        self.erasedBuilder = erasedBuilder
				    }

				    @Instantiated let detailBuilder: SendableInstantiator<Detail>
				    @Instantiated let lazyPart: SendableLazilyInstantiated<Part>
				    @Instantiated let forwardingBuilder: SendableInstantiator<Forwarding>
				    @Instantiated(fulfilledByType: "Forwarding") let erasedBuilder: SendableErasedInstantiator<String, any Named>
				}
				""",
				"""
				nonisolated public protocol Named {}
				""",
				"""
				@Instantiable
				public final class Forwarding: Instantiable, Named {
				    public init(name: String, part: Part) {
				        self.name = name
				        self.part = part
				    }

				    @Forwarded let name: String
				    @Instantiated let part: Part
				}
				""",
				"""
				@Instantiable
				public final class Detail: Instantiable {
				    public init(part: Part, partBuilder: Instantiator<Part>, sendablePartBuilder: SendableInstantiator<Part>, count: Int = 3) {
				        self.part = part
				        self.partBuilder = partBuilder
				        self.sendablePartBuilder = sendablePartBuilder
				    }

				    @Instantiated let part: Part
				    @Instantiated let partBuilder: Instantiator<Part>
				    @Instantiated let sendablePartBuilder: SendableInstantiator<Part>
				}
				""",
				"""
				@Instantiable
				public final class Part: Instantiable, Sendable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
			verificationCompilerSettings: isolation.compilerSettings,
		)

		#expect(output.generatedFiles?["Hub+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Hub {
		    public convenience init() {
		        @Sendable nonisolated func __safeDI_detailBuilder() -> Detail {
		            let part = Part()
		            func __safeDI_partBuilder() -> Part {
		                Part()
		            }
		            let partBuilder = Instantiator<Part>(__safeDI_partBuilder)
		            @Sendable nonisolated func __safeDI_sendablePartBuilder() -> Part {
		                Part()
		            }
		            let sendablePartBuilder = SendableInstantiator<Part>(__safeDI_sendablePartBuilder)
		            return Detail(part: part, partBuilder: partBuilder, sendablePartBuilder: sendablePartBuilder)
		        }
		        let detailBuilder = SendableInstantiator<Detail>(__safeDI_detailBuilder)
		        @Sendable nonisolated func __safeDI_lazyPart() -> Part {
		            Part()
		        }
		        let lazyPart = SendableLazilyInstantiated<Part>(__safeDI_lazyPart)
		        @Sendable nonisolated func __safeDI_forwardingBuilder(name: String) -> Forwarding {
		            let part = Part()
		            return Forwarding(name: name, part: part)
		        }
		        let forwardingBuilder = SendableInstantiator<Forwarding> {
		            __safeDI_forwardingBuilder(name: $0)
		        }
		        @Sendable nonisolated func __safeDI_erasedBuilder(name: String) -> Forwarding {
		            let part = Part()
		            return Forwarding(name: name, part: part)
		        }
		        let erasedBuilder = SendableErasedInstantiator<String, any Named> {
		            __safeDI_erasedBuilder(name: $0)
		        }
		        self.init(detailBuilder: detailBuilder, lazyPart: lazyPart, forwardingBuilder: forwardingBuilder, erasedBuilder: erasedBuilder)
		    }
		}
		""")
		#expect(output.generatedFiles?["Hub+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Hub {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            detailBuilder: Detail.SafeDIMockConfiguration = .init(),
		            lazyPart: (@Sendable () -> Part)? = nil,
		            forwardingBuilder: Forwarding.SafeDIMockConfiguration = .init(),
		            erasedBuilder: Forwarding.SafeDIMockConfiguration = .init()
		        ) {
		            self.detailBuilder = detailBuilder
		            self.lazyPart = lazyPart
		            self.forwardingBuilder = forwardingBuilder
		            self.erasedBuilder = erasedBuilder
		        }

		        private(set) var detailBuilder: Detail.SafeDIMockConfiguration
		        private(set) var lazyPart: (@Sendable () -> Part)?
		        private(set) var forwardingBuilder: Forwarding.SafeDIMockConfiguration
		        private(set) var erasedBuilder: Forwarding.SafeDIMockConfiguration
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Hub {
		        let __safeDI_detailBuilder__detailBuilder_part_safeDIBuilder = safeDIOverrides.detailBuilder.part
		        let __safeDI_detailBuilder__detailBuilder_partBuilder_safeDIBuilder = safeDIOverrides.detailBuilder.partBuilder
		        let __safeDI_detailBuilder__detailBuilder_sendablePartBuilder_safeDIBuilder = safeDIOverrides.detailBuilder.sendablePartBuilder
		        let __safeDI_detailBuilder__detailBuilder_count = safeDIOverrides.detailBuilder.count
		        let __safeDI_detailBuilder__safeDIBuilder = safeDIOverrides.detailBuilder.safeDIBuilder
		        @Sendable nonisolated func __safeDI_detailBuilder() -> Detail {
		            let part = if let safeDIBuilder = __safeDI_detailBuilder__detailBuilder_part_safeDIBuilder { safeDIBuilder() } else { Part() }
		            func __safeDI_partBuilder() -> Part {
		                if let safeDIBuilder = __safeDI_detailBuilder__detailBuilder_partBuilder_safeDIBuilder { safeDIBuilder() } else { Part() }
		            }
		            let partBuilder = Instantiator<Part>(__safeDI_partBuilder)
		            @Sendable nonisolated func __safeDI_sendablePartBuilder() -> Part {
		                if let safeDIBuilder = __safeDI_detailBuilder__detailBuilder_sendablePartBuilder_safeDIBuilder { safeDIBuilder() } else { Part() }
		            }
		            let sendablePartBuilder = SendableInstantiator<Part>(__safeDI_sendablePartBuilder)
		            return if let safeDIBuilder = __safeDI_detailBuilder__safeDIBuilder { safeDIBuilder(part, partBuilder, sendablePartBuilder, __safeDI_detailBuilder__detailBuilder_count()) } else { Detail(part: part, partBuilder: partBuilder, sendablePartBuilder: sendablePartBuilder, count: __safeDI_detailBuilder__detailBuilder_count()) }
		        }
		        let detailBuilder = SendableInstantiator<Detail>(__safeDI_detailBuilder)
		        let __safeDI_lazyPart__safeDIBuilder = safeDIOverrides.lazyPart
		        @Sendable nonisolated func __safeDI_lazyPart() -> Part {
		            if let safeDIBuilder = __safeDI_lazyPart__safeDIBuilder { safeDIBuilder() } else { Part() }
		        }
		        let lazyPart = SendableLazilyInstantiated<Part>(__safeDI_lazyPart)
		        let __safeDI_forwardingBuilder__forwardingBuilder_part_safeDIBuilder = safeDIOverrides.forwardingBuilder.part
		        let __safeDI_forwardingBuilder__safeDIBuilder = safeDIOverrides.forwardingBuilder.safeDIBuilder
		        @Sendable nonisolated func __safeDI_forwardingBuilder(name: String) -> Forwarding {
		            let part = if let safeDIBuilder = __safeDI_forwardingBuilder__forwardingBuilder_part_safeDIBuilder { safeDIBuilder() } else { Part() }
		            return if let safeDIBuilder = __safeDI_forwardingBuilder__safeDIBuilder { safeDIBuilder(name, part) } else { Forwarding(name: name, part: part) }
		        }
		        let forwardingBuilder = SendableInstantiator<Forwarding> {
		            __safeDI_forwardingBuilder(name: $0)
		        }
		        let __safeDI_erasedBuilder__erasedBuilder_part_safeDIBuilder = safeDIOverrides.erasedBuilder.part
		        let __safeDI_erasedBuilder__safeDIBuilder = safeDIOverrides.erasedBuilder.safeDIBuilder
		        @Sendable nonisolated func __safeDI_erasedBuilder(name: String) -> any Named {
		            let part = if let safeDIBuilder = __safeDI_erasedBuilder__erasedBuilder_part_safeDIBuilder { safeDIBuilder() } else { Part() }
		            return if let safeDIBuilder = __safeDI_erasedBuilder__safeDIBuilder { safeDIBuilder(name, part) } else { Forwarding(name: name, part: part) }
		        }
		        let erasedBuilder = SendableErasedInstantiator<String, any Named> {
		            __safeDI_erasedBuilder(name: $0)
		        }
		        return Hub(detailBuilder: detailBuilder, lazyPart: lazyPart, forwardingBuilder: forwardingBuilder, erasedBuilder: erasedBuilder)
		    }
		}
		#endif
		""")
	}

	@Test(arguments: ModuleDefaultIsolation.allCases)
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_declaresSendableBuilderFunctionsNonisolated_whenRootIsOnMainActorOnlyThroughAttributes(isolation: ModuleDefaultIsolation) async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true, generatedInitializerAttributes: "@MainActor", mockAttributes: "@MainActor", generateMock: true)
				public final class AttributeHub: Instantiable {
				    public init(detailBuilder: SendableInstantiator<Detail>) {
				        self.detailBuilder = detailBuilder
				    }

				    @Instantiated let detailBuilder: SendableInstantiator<Detail>
				}
				""",
				"""
				@Instantiable
				public final class Detail: Instantiable {
				    public init(part: Part) {
				        self.part = part
				    }

				    @Instantiated let part: Part
				}
				""",
				"""
				@Instantiable
				public final class Part: Instantiable, Sendable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
			verificationCompilerSettings: isolation.compilerSettings,
		)

		#expect(output.generatedFiles?["AttributeHub+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension AttributeHub {
		    @MainActor public convenience init() {
		        @Sendable nonisolated func __safeDI_detailBuilder() -> Detail {
		            let part = Part()
		            return Detail(part: part)
		        }
		        let detailBuilder = SendableInstantiator<Detail>(__safeDI_detailBuilder)
		        self.init(detailBuilder: detailBuilder)
		    }
		}
		""")
		#expect(output.generatedFiles?["AttributeHub+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension AttributeHub {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            detailBuilder: Detail.SafeDIMockConfiguration? = nil
		        ) {
		            self.detailBuilder = detailBuilder
		        }

		        private(set) var detailBuilder: Detail.SafeDIMockConfiguration?
		    }

		    @MainActor static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> AttributeHub {
		        let __safeDI_detailBuilder__configuration = safeDIOverrides.detailBuilder ?? .init()
		        let __safeDI_detailBuilder__detailBuilder_part_safeDIBuilder = __safeDI_detailBuilder__configuration.part
		        let __safeDI_detailBuilder__safeDIBuilder = __safeDI_detailBuilder__configuration.safeDIBuilder
		        @Sendable nonisolated func __safeDI_detailBuilder() -> Detail {
		            let part = if let safeDIBuilder = __safeDI_detailBuilder__detailBuilder_part_safeDIBuilder { safeDIBuilder() } else { Part() }
		            return if let safeDIBuilder = __safeDI_detailBuilder__safeDIBuilder { safeDIBuilder(part) } else { Detail(part: part) }
		        }
		        let detailBuilder = SendableInstantiator<Detail>(__safeDI_detailBuilder)
		        return AttributeHub(detailBuilder: detailBuilder)
		    }
		}
		#endif
		""")
	}

	@Test(arguments: ModuleDefaultIsolation.allCases)
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_declaresSendableBuilderFunctionsNonisolated_whenMainActorRootClosesCycleThroughSendableInstantiators(isolation: ModuleDefaultIsolation) async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@MainActor
				@Instantiable(isRoot: true, generateMock: true)
				public final class CycleHub: Instantiable {
				    public init(session: Session, screenBuilder: SendableInstantiator<Screen>) {
				        self.session = session
				        self.screenBuilder = screenBuilder
				    }

				    @Instantiated let session: Session
				    @Instantiated let screenBuilder: SendableInstantiator<Screen>
				}
				""",
				"""
				@Instantiable
				public final class Screen: Instantiable, Sendable {
				    public init(session: Session, stepBuilder: SendableInstantiator<Step>) {
				        self.session = session
				        self.stepBuilder = stepBuilder
				    }

				    @Received let session: Session
				    @Instantiated let stepBuilder: SendableInstantiator<Step>
				}
				""",
				"""
				@Instantiable
				public final class Step: Instantiable, Sendable {
				    public init(session: Session, screenBuilder: SendableInstantiator<Screen>) {
				        self.session = session
				        self.screenBuilder = screenBuilder
				    }

				    @Instantiated let session: Session
				    @Instantiated let screenBuilder: SendableInstantiator<Screen>
				}
				""",
				"""
				@Instantiable
				public final class Session: Instantiable, Sendable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
			verificationCompilerSettings: isolation.compilerSettings,
		)

		#expect(output.generatedFiles?["CycleHub+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension CycleHub {
		    public convenience init() {
		        let session = Session()
		        @Sendable nonisolated func __safeDI_screenBuilder(session: Session) -> Screen {
		            @Sendable nonisolated func __safeDI_stepBuilder() -> Step {
		                let session = Session()
		                let screenBuilder = SendableInstantiator<Screen> {
		                    __safeDI_screenBuilder(session: session)
		                }
		                return Step(session: session, screenBuilder: screenBuilder)
		            }
		            let stepBuilder = SendableInstantiator<Step>(__safeDI_stepBuilder)
		            return Screen(session: session, stepBuilder: stepBuilder)
		        }
		        let screenBuilder = SendableInstantiator<Screen> {
		            __safeDI_screenBuilder(session: session)
		        }
		        self.init(session: session, screenBuilder: screenBuilder)
		    }
		}
		""")
		#expect(output.generatedFiles?["CycleHub+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension CycleHub {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            session: (() -> Session)? = nil,
		            screenBuilder: Screen.SafeDIMockConfiguration = .init()
		        ) {
		            self.session = session
		            self.screenBuilder = screenBuilder
		        }

		        private(set) var session: (() -> Session)?
		        private(set) var screenBuilder: Screen.SafeDIMockConfiguration
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> CycleHub {
		        let session = if let safeDIBuilder = safeDIOverrides.session { safeDIBuilder() } else { Session() }
		        let __safeDI_screenBuilder__screenBuilder_stepBuilder_safeDIBuilder = safeDIOverrides.screenBuilder.stepBuilder.safeDIBuilder
		        let __safeDI_screenBuilder__screenBuilder_stepBuilder_session_safeDIBuilder = safeDIOverrides.screenBuilder.stepBuilder.session
		        let __safeDI_screenBuilder__safeDIBuilder = safeDIOverrides.screenBuilder.safeDIBuilder
		        @Sendable nonisolated func __safeDI_screenBuilder(session: Session) -> Screen {
		            @Sendable nonisolated func __safeDI_stepBuilder() -> Step {
		                let session = if let safeDIBuilder = __safeDI_screenBuilder__screenBuilder_stepBuilder_session_safeDIBuilder { safeDIBuilder() } else { Session() }
		                let screenBuilder = SendableInstantiator<Screen> {
		                    __safeDI_screenBuilder(session: session)
		                }
		                return if let safeDIBuilder = __safeDI_screenBuilder__screenBuilder_stepBuilder_safeDIBuilder { safeDIBuilder(session, screenBuilder) } else { Step(session: session, screenBuilder: screenBuilder) }
		            }
		            let stepBuilder = SendableInstantiator<Step>(__safeDI_stepBuilder)
		            return if let safeDIBuilder = __safeDI_screenBuilder__safeDIBuilder { safeDIBuilder(session, stepBuilder) } else { Screen(session: session, stepBuilder: stepBuilder) }
		        }
		        let screenBuilder = SendableInstantiator<Screen> {
		            __safeDI_screenBuilder(session: session)
		        }
		        return CycleHub(session: session, screenBuilder: screenBuilder)
		    }
		}
		#endif
		""")
	}

	@Test(arguments: ModuleDefaultIsolation.allCases)
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_declaresSendableBuilderFunctionsNonisolated_whenRootIsNonisolated(isolation: ModuleDefaultIsolation) async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true)
				public final class PlainHub: Instantiable {
				    public init(detailBuilder: SendableInstantiator<Detail>) {
				        self.detailBuilder = detailBuilder
				    }

				    @Instantiated let detailBuilder: SendableInstantiator<Detail>
				}
				""",
				"""
				@Instantiable
				public final class Detail: Instantiable {
				    public init(count: Int = 3) {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
			verificationCompilerSettings: isolation.compilerSettings,
		)

		#expect(output.generatedFiles?["PlainHub+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension PlainHub {
		    public convenience init() {
		        @Sendable nonisolated func __safeDI_detailBuilder() -> Detail {
		            Detail()
		        }
		        let detailBuilder = SendableInstantiator<Detail>(__safeDI_detailBuilder)
		        self.init(detailBuilder: detailBuilder)
		    }
		}
		""")
	}

