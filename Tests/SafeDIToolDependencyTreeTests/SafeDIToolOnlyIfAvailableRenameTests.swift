/// An `onlyIfAvailable` rename is always declared: bound to its dependency where the nearest declaration of the
/// dependency's label provides a form the rename reads – the dependency, or its optional form – and is not being built,
/// and `nil` otherwise. The declaring type and every type beneath it read the rename, `nil` included, never a declaration
/// of its label farther up.
struct SafeDIToolOnlyIfAvailableRenameTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_bindsOnlyIfAvailableAliasFromOptionalFormOfItsDependency_whenEnclosingTypeForwardsThatForm() async throws {
		// `Holder` forwards `x: X?` and `Root` instantiates `x: X` farther out. `Child`'s alias of `x: X` reads
		// `Holder`'s `x: X?`, the nearest declaration of its label, as an `onlyIfAvailable` receive of `x: X?` reads `x: X`, and
		// requires nothing of `Root`'s `x`, so `X` is built after `holderBuilder` and handed it.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable public final class Child: Instantiable {
				    @Received(fulfilledByDependencyNamed: "x", ofType: X.self, onlyIfAvailable: true) let ax: X?
				    @Instantiated let grand: Grand
				    public init(ax: X?, grand: Grand) { self.ax = ax; self.grand = grand }
				}
				""",
				"""
				@Instantiable public final class Grand: Instantiable {
				    @Received let ax: X?
				    public init(ax: X?) { self.ax = ax }
				}
				""",
				"""
				@Instantiable public final class Holder: Instantiable {
				    @Forwarded let x: X?
				    @Instantiated let child: Child
				    public init(x: X?, child: Child) { self.x = x; self.child = child }
				}
				""",
				"""
				@Instantiable(isRoot: true) public final class Root: Instantiable {
				    @Instantiated let x: X
				    @Instantiated let holderBuilder: Instantiator<Holder>
				    public init(x: X, holderBuilder: Instantiator<Holder>) { self.x = x; self.holderBuilder = holderBuilder }
				}
				""",
				"""
				@Instantiable public final class X: Instantiable {
				    @Received(onlyIfAvailable: true) let holderBuilder: Instantiator<Holder>?
				    public init(holderBuilder: Instantiator<Holder>?) { self.holderBuilder = holderBuilder }
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.generatedFiles == [
			"Root+SafeDI.swift": """
			// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
			// Any modifications made to this file will be overwritten on subsequent builds.
			// Please refrain from editing this file directly.

			extension Root {
			    public convenience init() {
			        func __safeDI_holderBuilder(x: X?) -> Holder {
			            func __safeDI_child() -> Child {
			                #sourceLocation(file: "\(output.fixtures["Child.swift"])", line: 2)
			                let ax: X? = x
			                #sourceLocation()
			                let grand = Grand(ax: ax)
			                return Child(ax: ax, grand: grand)
			            }
			            let child: Child = __safeDI_child()
			            return Holder(x: x, child: child)
			        }
			        let holderBuilder = Instantiator<Holder> {
			            __safeDI_holderBuilder(x: $0)
			        }
			        let x = X(holderBuilder: holderBuilder)
			        self.init(x: x, holderBuilder: holderBuilder)
			    }
			}
			""",
		])
	}

