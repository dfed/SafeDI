import Foundation
import SafeDICore
import Testing
@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

/// SafeDI's macros and wrappers spelled with SafeDI's module name (`@SafeDI.Instantiable`, `SafeDI.Instantiator<T>`) are
/// read as their bare spellings are, by `scan` and by `generate`, and the compiler expands the macros so spelled.
struct SafeDIToolQualifiedSpellingTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_generatesRoot_whenMacrosAndWrappersAreQualifiedBySafeDI() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [],
			swiftFileContentByFilePath: SafeDIToolQualifiedSpellingFixtures.fixtures(rootArguments: "isRoot: true"),
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.generatedFiles?["Root+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public init() {
		        let session = Session()
		        func __safeDI_screenBuilder() -> Screen {
		            Screen(session: session)
		        }
		        let screenBuilder = Instantiator<Screen>(__safeDI_screenBuilder)
		        @Sendable nonisolated func __safeDI_sendableScreenBuilder() -> Screen {
		            Screen(session: session)
		        }
		        let sendableScreenBuilder = SendableInstantiator<Screen>(__safeDI_sendableScreenBuilder)
		        func __safeDI_profileBuilder(user: User) -> Profile {
		            Profile(user: user)
		        }
		        let profileBuilder = ErasedInstantiator<User, AnyObject> {
		            __safeDI_profileBuilder(user: $0)
		        }
		        @Sendable nonisolated func __safeDI_sendableProfileBuilder(user: User) -> Profile {
		            Profile(user: user)
		        }
		        let sendableProfileBuilder = SendableErasedInstantiator<User, Profile> {
		            __safeDI_sendableProfileBuilder(user: $0)
		        }
		        func __safeDI_settings() -> Settings {
		            Settings()
		        }
		        let settings = LazilyInstantiated<Settings>(__safeDI_settings)
		        @Sendable nonisolated func __safeDI_sendableSettings() -> Settings {
		            Settings()
		        }
		        let sendableSettings = SendableLazilyInstantiated<Settings>(__safeDI_sendableSettings)
		        self.init(session: session, screenBuilder: screenBuilder, sendableScreenBuilder: sendableScreenBuilder, profileBuilder: profileBuilder, sendableProfileBuilder: sendableProfileBuilder, settings: settings, sendableSettings: sendableSettings)
		    }
		}
		""")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_generatesModuleTree_whenMacrosAndWrappersAreQualifiedBySafeDI() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [],
			swiftFileContentByFilePath: SafeDIToolQualifiedSpellingFixtures.fixtures(rootArguments: "generateDependencyTree: true"),
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.generatedFiles?["Root+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    /// Code you write and code SafeDI generates can both call this initializer.
		    public init() {
		        let session = Session()
		        @inline(never) func __safeDI_screenBuilder() -> Screen {
		            Screen(session: session)
		        }
		        let screenBuilder = Instantiator<Screen>(__safeDI_screenBuilder)
		        @inline(never) @Sendable nonisolated func __safeDI_sendableScreenBuilder() -> Screen {
		            Screen(session: session)
		        }
		        let sendableScreenBuilder = SendableInstantiator<Screen>(__safeDI_sendableScreenBuilder)
		        @inline(never) func __safeDI_profileBuilder(user: User) -> Profile {
		            Profile(user: user)
		        }
		        let profileBuilder = ErasedInstantiator<User, AnyObject> {
		            __safeDI_profileBuilder(user: $0)
		        }
		        @inline(never) @Sendable nonisolated func __safeDI_sendableProfileBuilder(user: User) -> Profile {
		            Profile(user: user)
		        }
		        let sendableProfileBuilder = SendableErasedInstantiator<User, Profile> {
		            __safeDI_sendableProfileBuilder(user: $0)
		        }
		        @inline(never) func __safeDI_settings() -> Settings {
		            Settings()
		        }
		        let settings = LazilyInstantiated<Settings>(__safeDI_settings)
		        @inline(never) @Sendable nonisolated func __safeDI_sendableSettings() -> Settings {
		            Settings()
		        }
		        let sendableSettings = SendableLazilyInstantiated<Settings>(__safeDI_sendableSettings)
		        self.init(session: session, screenBuilder: screenBuilder, sendableScreenBuilder: sendableScreenBuilder, profileBuilder: profileBuilder, sendableProfileBuilder: sendableProfileBuilder, settings: settings, sendableSettings: sendableSettings)
		    }
		}

		extension Root {
		    public enum __safeDI_Root_CBF29CE484222325 {}
		}
		""")
	}

	// MARK: Private

	private var filesToDelete = [URL]()
}
