import Foundation
import SafeDICore
import Testing
@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

/// SafeDI's macros and wrappers spelled with SafeDI's module name (`@SafeDI.Instantiable`, `SafeDI.Instantiator<T>`) are
/// read as their bare spellings are, by `scan` and by `generate`, and the compiler expands the macros so spelled.
struct SafeDIToolQualifiedSpellingTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_generatesDependencyTree_whenMacrosAndWrappersAreQualifiedBySafeDI() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [],
			swiftFileContentByFilePath: [
				"Root.swift": """
				@SafeDI.Instantiable(isRoot: true)
				public struct Root: Instantiable {
				    public init(session: Session, screenBuilder: SafeDI.Instantiator<Screen>, profileBuilder: SafeDI.ErasedInstantiator<User, AnyObject>, settings: SafeDI.LazilyInstantiated<Settings>) {
				        self.session = session
				        self.screenBuilder = screenBuilder
				        self.profileBuilder = profileBuilder
				        self.settings = settings
				    }

				    @SafeDI.Instantiated let session: Session
				    @SafeDI.Instantiated let screenBuilder: SafeDI.Instantiator<Screen>
				    @SafeDI.Instantiated(fulfilledByType: "Profile") let profileBuilder: SafeDI.ErasedInstantiator<User, AnyObject>
				    @SafeDI.Instantiated let settings: SafeDI.LazilyInstantiated<Settings>
				}
				""",
				"Screen.swift": """
				@SafeDI.Instantiable
				public final class Screen: Instantiable {
				    public init(session: Session) {
				        self.session = session
				    }

				    @SafeDI.Received let session: Session
				}
				""",
				"Profile.swift": """
				public struct User {}

				@SafeDI.Instantiable
				public final class Profile: Instantiable {
				    public init(user: User) {
				        self.user = user
				    }

				    @SafeDI.Forwarded let user: User
				}
				""",
				"Session.swift": """
				@SafeDI.Instantiable
				public final class Session: Instantiable {
				    public init() {}
				}
				""",
				"Settings.swift": """
				@SafeDI.Instantiable
				public final class Settings: Instantiable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.generatedFiles?["Root+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public init() {
		        let session = Session()
		        func __safeDI_screenBuilder() -> Screen {
		            Screen(session: session)
		        }
		        let screenBuilder = Instantiator<Screen>(__safeDI_screenBuilder)
		        func __safeDI_profileBuilder(user: User) -> Profile {
		            Profile(user: user)
		        }
		        let profileBuilder = ErasedInstantiator<User, AnyObject> {
		            __safeDI_profileBuilder(user: $0)
		        }
		        func __safeDI_settings() -> Settings {
		            Settings()
		        }
		        let settings = LazilyInstantiated<Settings>(__safeDI_settings)
		        self.init(session: session, screenBuilder: screenBuilder, profileBuilder: profileBuilder, settings: settings)
		    }
		}
		""")
	}

	// MARK: Private

	private var filesToDelete = [URL]()
}
