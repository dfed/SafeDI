import Foundation
import SafeDICore
import Testing
@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

/// When a binding spells its property's type: each form of property has its own rule, and the rules differ for a type
/// declared in an extension (`BindingDeclaration.AnnotationRule`).
struct SafeDIToolBindingAnnotationTests: ~Copyable {
	// MARK: Initialization

	init() {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_annotatesBindingsByTheirFormsRules_whenRootHoldsEveryFormOfTwoTypes() async throws {
		// `Thing` is declared in an extension, `Plain` is not, and builds `leaf`. A constant and an instantiator of `Thing`
		// spell its type, a lazy wrapper of it does not. Of `Plain`'s, only the constant does, since it calls a builder
		// function.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable(isRoot: true)
				public struct Root: Instantiable {
				    public init(thing: Thing, thingBuilder: Instantiator<Thing>, lazyThing: LazilyInstantiated<Thing>, plain: Plain, plainBuilder: Instantiator<Plain>, lazyPlain: LazilyInstantiated<Plain>) {
				        self.thing = thing
				        self.thingBuilder = thingBuilder
				        self.lazyThing = lazyThing
				        self.plain = plain
				        self.plainBuilder = plainBuilder
				        self.lazyPlain = lazyPlain
				    }

				    @Instantiated let thing: Thing
				    @Instantiated let thingBuilder: Instantiator<Thing>
				    @Instantiated let lazyThing: LazilyInstantiated<Thing>
				    @Instantiated let plain: Plain
				    @Instantiated let plainBuilder: Instantiator<Plain>
				    @Instantiated let lazyPlain: LazilyInstantiated<Plain>
				}
				""",
				"""
				public struct Thing {}

				@Instantiable
				extension Thing: Instantiable {
				    public static func instantiate() -> Thing {
				        Thing()
				    }
				}
				""",
				"""
				@Instantiable
				public struct Plain: Instantiable {
				    public init(leaf: Leaf) {
				        self.leaf = leaf
				    }

				    @Instantiated let leaf: Leaf
				}
				""",
				"""
				@Instantiable
				public struct Leaf: Instantiable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		let generated: String? = output.generatedFiles?["Root+SafeDI.swift"]
		#expect(generated == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public init() {
		        let thing: Thing = Thing.instantiate()
		        func __safeDI_thingBuilder() -> Thing {
		            Thing.instantiate()
		        }
		        let thingBuilder: Instantiator<Thing> = Instantiator<Thing>(__safeDI_thingBuilder)
		        let lazyThing = LazilyInstantiated<Thing>(__safeDI_thingBuilder)
		        func __safeDI_plain() -> Plain {
		            let leaf = Leaf()
		            return Plain(leaf: leaf)
		        }
		        let plain: Plain = __safeDI_plain()
		        let plainBuilder = Instantiator<Plain>(__safeDI_plain)
		        let lazyPlain = LazilyInstantiated<Plain>(__safeDI_plain)
		        self.init(thing: thing, thingBuilder: thingBuilder, lazyThing: lazyThing, plain: plain, plainBuilder: plainBuilder, lazyPlain: lazyPlain)
		    }
		}
		""")
	}

	// MARK: Private

	private var filesToDelete: [URL]
}
