/// An `@Instantiated(onlyIfAvailable: true)` property is instantiated where a production declaration the module reads
/// fulfills its type, and is `nil` where none does. Either way it is the nearest declaration of its label for the types
/// beneath it.
struct SafeDIToolInstantiatedOnlyIfAvailableTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_instantiatesDependency_whenProductionDeclarationFulfillsItsType() async throws {
		// `DefaultAnalytics` fulfills `any Analytics`, so `Screen` builds it and the types beneath receive it.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable public final class Screen: Instantiable {
				    @Instantiated(onlyIfAvailable: true) let analytics: (any Analytics)?
				    @Instantiated let child: Child
				    public init(analytics: (any Analytics)?, child: Child) { self.analytics = analytics; self.child = child }
				}
				""",
				"""
				@Instantiable public final class Child: Instantiable {
				    @Received let analytics: (any Analytics)?
				    @Instantiated let grandchild: Grandchild
				    public init(analytics: (any Analytics)?, grandchild: Grandchild) { self.analytics = analytics; self.grandchild = grandchild }
				}
				""",
				"""
				@Instantiable public final class Grandchild: Instantiable {
				    @Received(onlyIfAvailable: true) let analytics: (any Analytics)?
				    public init(analytics: (any Analytics)?) { self.analytics = analytics }
				}
				""",
				"""
				@Instantiable(isRoot: true) public final class Root: Instantiable {
				    @Instantiated let screen: Screen
				    public init(screen: Screen) { self.screen = screen }
				}
				""",
				"""
				public protocol Analytics {}

				@Instantiable(fulfillingAdditionalTypes: [(any Analytics).self]) public final class DefaultAnalytics: Instantiable, Analytics {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.generatedFiles == [
			"Root+SafeDI.swift": """
			// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
			// Any modifications made to this file will be overwritten on subsequent builds.
			// Please refrain from editing this file directly.

			extension Root {
			    public convenience init() {
			        func __safeDI_child(analytics: (any Analytics)?) -> Child {
			            let grandchild = Grandchild(analytics: analytics)
			            return Child(analytics: analytics, grandchild: grandchild)
			        }
			        func __safeDI_screen() -> Screen {
			            let analytics: (any Analytics)? = DefaultAnalytics()
			            let child: Child = __safeDI_child(analytics: analytics)
			            return Screen(analytics: analytics, child: child)
			        }
			        let screen: Screen = __safeDI_screen()
			        self.init(screen: screen)
			    }
			}
			""",
		])
	}

