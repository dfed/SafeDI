import Foundation
import SafeDICore
import Testing
@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

/// Advice an error gives is checked before it is given: the receive's own checks run again with the advised declaration
/// in place, on the failure path only, so following the advice never only moves the error to another check.
struct SafeDIToolValidatedAdviceTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests – a declaration the advice adds is hidden beneath a mocked type

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_advisesRelabelingHidingDeclaration_whenMockedTypeDeclaresReceivedLabelWithAnotherType() async {
		// `T3`’s mock builds `T5` beneath `t4: T1`, so `@Instantiated let t4: T0` on `Root` alone would leave `T5`’s
		// receive hidden in `T3`’s mock. The advice names the relabel too.
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["T5.swift"]):7:5: error: @Received property `t4: T0` is not @Instantiated or @Forwarded in chain: Root -> T5. Declare `@Instantiated let t4: T0` on `Root` or on another type in the chain, and give `t4: T1` on `T3` a different label, to fix.
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: Self.mockedHiderFiles(),
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_generatesTreeAndMock_whenRootDeclaresAdvisedPropertyAndMockedTypeRelabelsHidingDeclaration() async throws {
		// The advice above, applied as written.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: Self.mockedHiderFiles(rootDeclaresT4: true, mockedTypeLabel: "t1"),
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.dependencyTreeFiles == ["Root+SafeDI.swift": """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public convenience init() {
		        let t4 = T0()
		        let t5 = T5(t4: t4)
		        self.init(t4: t4, t5: t5)
		    }
		}
		"""])
		#expect(output.mockFiles == ["T3+SafeDIMock.swift": """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension T3 {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            t1: (() -> T1)? = nil,
		            t4: (() -> T0)? = nil,
		            t5: ((T0) -> T5)? = nil
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                t1: t1,
		                t4: t4,
		                t5: t5
		            )
		        }

		        var t1: (() -> T1)? { __safeDI_storage.t1 }
		        var t4: (() -> T0)? { __safeDI_storage.t4 }
		        var t5: ((T0) -> T5)? { __safeDI_storage.t5 }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                t1: (() -> T1)?,
		                t4: (() -> T0)?,
		                t5: ((T0) -> T5)?
		            ) {
		                self.t1 = t1
		                self.t4 = t4
		                self.t5 = t5
		            }

		            let t1: (() -> T1)?
		            let t4: (() -> T0)?
		            let t5: ((T0) -> T5)?
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> T3 {
		        let t1 = if let safeDIBuilder = safeDIOverrides.t1 { safeDIBuilder() } else { T1() }
		        let t4 = if let safeDIBuilder = safeDIOverrides.t4 { safeDIBuilder() } else { T0() }
		        let t5 = if let safeDIBuilder = safeDIOverrides.t5 { safeDIBuilder(t4) } else { T5(t4: t4) }
		        return T3(t1: t1, t5: t5)
		    }
		}
		#endif
		"""])
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_advisesOnlyDeclaration_whenMockedTypeDeclaresReceivedLabelWithSameType() async {
		// `T3`’s `t4: T0` provides `T5`’s receive in `T3`’s mock, so nothing hides the advised declaration: the advice is
		// today’s.
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["T5.swift"]):7:5: error: @Received property `t4: T0` is not @Instantiated or @Forwarded in chain: Root -> T5. Declare `@Instantiated let t4: T0` on `Root` or on another type in the chain to fix.
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: Self.mockedHiderFiles(mockedTypeDeclaration: "t4: T0"),
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_advisesRelabelingHidingDeclaration_whenReceiveOfOptionalIsAdvisedOnlyIfAvailable() async {
		// The required `t4: T0?` gets the advice to declare `t4: T0` and receive it only if available; `T3`’s `t4: T1`
		// hides that receive in `T3`’s mock too.
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["T5.swift"]):7:5: error: @Received property `t4: T0?` is not @Instantiated or @Forwarded in chain: Root -> T5. Declare `@Instantiated let t4: T0` on `Root` or on another type in the chain, give `t4: T1` on `T3` a different label, and add `onlyIfAvailable: true` to this property’s `@Received`, which then accepts the non-optional form, to fix.
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: Self.mockedHiderFiles(receive: "t4: T0?"),
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

	// MARK: Tests – a suggestion that closes a cycle

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_suggestsReceivingOnlyIfAvailable_whenSuggestedRequiredReceiveClosesCycleInMock() async {
		// Received as required, `t0: T1?` is still being built when `T1`’s mock builds `T1`, and so is `t0: T1` declared on
		// `Root`. Only a receive only if available passes every check, and it takes two edits, so no fix-it.
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["T1.swift"]):7:5: error: @Received property `t0: T1` is not @Instantiated or @Forwarded in chain: Root -> Instantiator<T2> -> T1. Did you mean `t0: T1?`, received with `onlyIfAvailable: true`? Received as required, it is still being built when the mock of `T1` builds `T1`.
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: Self.selfReceivingFiles(receive: "t0: T1"),
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_generatesTreeAndMock_whenReceiveTakesSuggestedFormOnlyIfAvailable() async throws {
		// The suggestion above, applied as written.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: Self.selfReceivingFiles(receive: "t0: T1?", onlyIfAvailable: true),
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.dependencyTreeFiles == ["Root+SafeDI.swift": """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public convenience init() {
		        func __safeDI_t2Builder(t0: T1?) -> T2 {
		            let t1 = T1(t0: t0)
		            return T2(t0: t0, t1: t1)
		        }
		        let t2Builder = Instantiator<T2> {
		            __safeDI_t2Builder(t0: $0)
		        }
		        self.init(t2Builder: t2Builder)
		    }
		}
		"""])
		#expect(output.mockFiles == ["T1+SafeDIMock.swift": """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension T1 {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            t0: T1? = nil
		        ) {
		            self.t0 = t0
		        }

		        let t0: T1?
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> T1 {
		        let t0: T1? = safeDIOverrides.t0
		        return T1(t0: t0)
		    }
		}
		#endif
		"""])
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_suggestsOptionalForm_whenSuggestedReceiveIsOfAnotherType() async {
		// `T1` receives `t0: T4`, not its own type, so receiving `T2`’s `t0: T4?` closes no cycle: the suggestion and its
		// fix-it are today’s.
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["T1.swift"]):7:5: error: @Received property `t0: T4` is not @Instantiated or @Forwarded in chain: Root -> Instantiator<T2> -> T1. Did you mean `t0: T4?`?
				\(fixtures["T1.swift"]):7:23-7:25: fixit: T4?
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: Self.selfReceivingFiles(receive: "t0: T4", forwarded: "t0: T4?"),
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

	// MARK: Private

	private var filesToDelete: [URL]

	/// `Root` instantiates `T5`, which receives `receive`; `T3`, whose mock is generated, instantiates `mockedTypeDeclaration`
	/// (under `mockedTypeLabel` when given) and `T5`.
	private static func mockedHiderFiles(
		rootDeclaresT4: Bool = false,
		mockedTypeDeclaration: String = "t4: T1",
		mockedTypeLabel: String? = nil,
		receive: String = "t4: T0",
	) -> [String] {
		let hider = mockedTypeLabel.map { label in "\(label): " + mockedTypeDeclaration.split(separator: ":")[1].trimmingCharacters(in: .whitespaces) } ?? mockedTypeDeclaration
		return [
			rootDeclaresT4
				? """
			@Instantiable(isRoot: true)
			public final class Root: Instantiable {
			    public init(t4: T0, t5: T5) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Instantiated let t4: T0
			    @Instantiated let t5: T5
			}
			"""
				: """
			@Instantiable(isRoot: true)
			public final class Root: Instantiable {
			    public init(t5: T5) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Instantiated let t5: T5
			}
			""",
			"""
			@Instantiable(generateMock: true)
			public final class T3: Instantiable {
			    public init(\(hider), t5: T5) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Instantiated let \(hider)
			    @Instantiated let t5: T5
			}
			""",
			"""
			@Instantiable
			public final class T5: Instantiable {
			    public init(\(receive)) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Received let \(receive)
			}
			""",
			"""
			@Instantiable
			public final class T0: Instantiable {
			    public init() {}
			}

			@Instantiable
			public final class T1: Instantiable {
			    public init() {}
			}
			""",
		]
	}

	/// `Root` builds `T2` through an `Instantiator`; `T2` forwards `forwarded` and instantiates `T1`, whose mock is
	/// generated and which receives `receive`.
	private static func selfReceivingFiles(receive: String, onlyIfAvailable: Bool = false, forwarded: String = "t0: T1?") -> [String] {
		let received = onlyIfAvailable ? "@Received(onlyIfAvailable: true)" : "@Received"
		return [
			"""
			@Instantiable(isRoot: true)
			public final class Root: Instantiable {
			    public init(t2Builder: Instantiator<T2>) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Instantiated let t2Builder: Instantiator<T2>
			}
			""",
			"""
			@Instantiable
			public final class T2: Instantiable {
			    public init(\(forwarded), t1: T1) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Forwarded let \(forwarded)
			    @Instantiated let t1: T1
			}
			""",
			"""
			@Instantiable(generateMock: true)
			public final class T1: Instantiable {
			    public init(\(receive)) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    \(received) let \(receive)
			}
			""",
			"""
			@Instantiable
			public final class T4: Instantiable {
			    public init() {}
			}
			""",
		]
	}
}
