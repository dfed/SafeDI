	/// `Root` instantiates `T5`, which receives `receive`; `T3`, whose mock is generated, instantiates `mockedTypeDeclaration`
	/// (under `mockedTypeLabel` when given) and `T5`.
	private static func mockedHiderFiles(
		rootDeclaresT4: Bool = false,
		mockedTypeDeclaration: String = "t4: T1",
		mockedTypeLabel: String? = nil,
		receive: String = "t4: T0",
	) -> [String] {
		let hider = mockedTypeLabel.map { label in "\(label): " + mockedTypeDeclaration.split(separator: ":")[1].trimmingCharacters(in: .whitespaces) } ?? mockedTypeDeclaration
		return [
			rootDeclaresT4
				? """
				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init(t4: T0, t5: T5) {
				        fatalError("SafeDI doesn't inspect the initializer body")
				    }

				    @Instantiated let t4: T0
				    @Instantiated let t5: T5
				}
				"""
				: """
				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init(t5: T5) {
				        fatalError("SafeDI doesn't inspect the initializer body")
				    }

				    @Instantiated let t5: T5
				}
				""",
			"""
			@Instantiable(generateMock: true)
			public final class T3: Instantiable {
			    public init(\(hider), t5: T5) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Instantiated let \(hider)
			    @Instantiated let t5: T5
			}
			""",
			"""
			@Instantiable
			public final class T5: Instantiable {
			    public init(\(receive)) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Received let \(receive)
			}
			""",
			"""
			@Instantiable
			public final class T0: Instantiable {
			    public init() {}
			}

			@Instantiable
			public final class T1: Instantiable {
			    public init() {}
			}
			""",
		]
	}

	/// `Root` builds `T2` through an `Instantiator`; `T2` forwards `forwarded` and instantiates `T1`, whose mock is
	/// generated and which receives `receive`.
	private static func selfReceivingFiles(receive: String, onlyIfAvailable: Bool = false, forwarded: String = "t0: T1?") -> [String] {
		let received = onlyIfAvailable ? "@Received(onlyIfAvailable: true)" : "@Received"
		return [
			"""
			@Instantiable(isRoot: true)
			public final class Root: Instantiable {
			    public init(t2Builder: Instantiator<T2>) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Instantiated let t2Builder: Instantiator<T2>
			}
			""",
			"""
			@Instantiable
			public final class T2: Instantiable {
			    public init(\(forwarded), t1: T1) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Forwarded let \(forwarded)
			    @Instantiated let t1: T1
			}
			""",
			"""
			@Instantiable(generateMock: true)
			public final class T1: Instantiable {
			    public init(\(receive)) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    \(received) let \(receive)
			}
			""",
			"""
			@Instantiable
			public final class T4: Instantiable {
			    public init() {}
			}
			""",
		]
	}

	/// `Root` instantiates `boundary`, a `Sendable` wrapper of `T1` or a plain one; `T1` instantiates `T3`; `receiver`
	/// declares `t2Builder: Instantiator<T2>` with `receiverAttribute`. With `rootDeclaresSendableT2Builder`, `Root`
	/// declares `t2Builder: SendableInstantiator<T2>` and the receiver receives that form. With
	/// `t2ReceivesT4BuilderFromT1`, `T1` instantiates `t4Builder: Instantiator<T4>` and `T2` receives it.
	private static func sendableBoundaryFiles(
		boundary: String,
		receiver: String,
		receiverAttribute: String = "@Received",
		rootDeclaresSendableT2Builder: Bool = false,
		t2ReceivesT4BuilderFromT1: Bool = false,
	) -> [String] {
		let t2Builder = rootDeclaresSendableT2Builder ? "t2Builder: SendableInstantiator<T2>" : "t2Builder: Instantiator<T2>"
		let receiverDeclaration = "\(receiverAttribute) let \(t2Builder)"
		let t1Declarations = (receiver == "T1" ? [receiverDeclaration] : ["@Instantiated let t3: T3"])
			+ (t2ReceivesT4BuilderFromT1 ? ["@Instantiated let t4Builder: Instantiator<T4>"] : [])
		return [
			seamFixtureType(named: "Root", isRoot: true, declarations: ["@Instantiated let \(boundary)"] + (rootDeclaresSendableT2Builder ? ["@Instantiated let \(t2Builder)"] : [])),
			seamFixtureType(named: "T1", declarations: t1Declarations),
			seamFixtureType(named: "T3", declarations: receiver == "T3" ? [receiverDeclaration] : []),
			seamFixtureType(named: "T2", declarations: t2ReceivesT4BuilderFromT1 ? ["@Received let t4Builder: Instantiator<T4>"] : []),
		] + (t2ReceivesT4BuilderFromT1 ? [seamFixtureType(named: "T4", declarations: [])] : [])
	}

	/// `Root` instantiates `t2: T2`, which declares `t2Receive`; `T0` declares `t0Receive`.
	private static func coordinatorFiles(t2Receive: String? = "@Received let t0Builder: Instantiator<T0>", t0Receive: String?) -> [String] {
		[
			seamFixtureType(named: "Root", isRoot: true, declarations: ["@Instantiated let t2: T2"]),
			seamFixtureType(named: "T2", declarations: t2Receive.map { [$0] } ?? []),
			seamFixtureType(named: "T0", declarations: t0Receive.map { [$0] } ?? []),
		]
	}

	/// `Root` declares `rootDeclaration` and instantiates `Seam`, a seam that declares `seamDeclaration` and instantiates
	/// `Child`, which requires `user: User`.
	private static func seamFormsFiles(rootDeclaration: String, seamDeclaration: String) -> [String] {
		[
			seamFixtureType(named: "Root", isRoot: true, declarations: [rootDeclaration, "@Instantiated let seam: Seam"]),
			seamFixtureType(named: "Seam", isSeam: true, declarations: [seamDeclaration, "@Instantiated let child: Child"]),
			seamFixtureType(named: "Child", declarations: ["@Received let user: User"]),
			seamFixtureType(named: "User", declarations: []),
		]
	}
