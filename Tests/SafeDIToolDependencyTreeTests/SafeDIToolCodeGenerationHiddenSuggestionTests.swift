import Foundation
import SafeDICore
import Testing
@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

/// The suggestions of the error at a receive no declaration fulfills leave out a property a closer declaration of its label,
/// of another type, hides: receiving it would only move the error to a hidden receive.
struct SafeDIToolCodeGenerationHiddenSuggestionTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_suggestsOnlyClosestDeclarationOfLabel_whenFartherDeclarationOfLabelIsHiddenByForwardedOptional() async {
		// `Root`’s `user: User` is hidden below `Host`, which forwards `user: User?`, so only `Host`’s is suggested, with the
		// fix-it that receives it.
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["Summary.swift"]):7:5: error: @Received property `user: LazilyInstantiated<User>` is not @Instantiated or @Forwarded in chain: Root -> Instantiator<Host> -> Summary. Did you mean `user: User?`?
				\(fixtures["Summary.swift"]):7:25-7:49: fixit: User?
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: Self.forwardingHostFiles(summaryReceive: "user: LazilyInstantiated<User>"),
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_suggestsOnlyClosestDeclarationOfType_whenFartherDeclarationOfTypeIsHiddenByForwardedOptional() async {
		// The neighbour with another label: `viewer: User?` matches both by type, and `Root`’s `user: User` is hidden below
		// `Host`, so only `Host`’s is suggested, with the fix-it that renames the receive.
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["Summary.swift"]):7:5: error: @Received property `viewer: User?` is not @Instantiated or @Forwarded in chain: Root -> Instantiator<Host> -> Summary. Did you mean `user: User?`?
				\(fixtures["Summary.swift"]):7:19-7:25: fixit: user
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: Self.forwardingHostFiles(summaryReceive: "viewer: User?"),
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_generatesTree_whenReceiveTakesSuggestedClosestDeclaration() async throws {
		// The remedy both errors above suggest: `Summary` receives `Host`’s `user: User?`.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: Self.forwardingHostFiles(summaryReceive: "user: User?"),
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.dependencyTreeFiles == ["Root+SafeDI.swift": """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public convenience init() {
		        let user = User()
		        func __safeDI_hostBuilder(user: User?) -> Host {
		            let summary = Summary(user: user)
		            return Host(user: user, summary: summary)
		        }
		        let hostBuilder = Instantiator<Host> {
		            __safeDI_hostBuilder(user: $0)
		        }
		        self.init(user: user, hostBuilder: hostBuilder)
		    }
		}
		"""])
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_suggestsInstantiatedDeclaration_whenEveryNearMatchIsHidden() async {
		// `Root`’s `user: User` is the only near-match of `viewer: User`, and `Host`’s `user: Session` hides it, so the error
		// suggests declaring the property instead.
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["Summary.swift"]):7:5: error: @Received property `viewer: User` is not @Instantiated or @Forwarded in chain: Root -> Instantiator<Host> -> Summary. Declare `@Instantiated let viewer: User` on `Root` or on another type in the chain to fix.
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: Self.forwardingHostFiles(hostForward: "user: Session", summaryReceive: "viewer: User"),
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_generatesTree_whenRootDeclaresSuggestedInstantiatedProperty() async throws {
		// The remedy the error above states: `Root` declares `@Instantiated let viewer: User`.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: Self.forwardingHostFiles(rootDeclaresViewer: true, hostForward: "user: Session", summaryReceive: "viewer: User"),
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.dependencyTreeFiles == ["Root+SafeDI.swift": """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public convenience init() {
		        let user = User()
		        let viewer = User()
		        func __safeDI_hostBuilder(user: Session) -> Host {
		            let summary = Summary(viewer: viewer)
		            return Host(user: user, summary: summary)
		        }
		        let hostBuilder = Instantiator<Host> {
		            __safeDI_hostBuilder(user: $0)
		        }
		        self.init(user: user, viewer: viewer, hostBuilder: hostBuilder)
		    }
		}
		"""])
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_suggestsFartherDeclaration_whenClosestDeclarationIsLazilyInstantiatedWrapperOfIt() async {
		// `Host`’s `user: LazilyInstantiated<User>` offers `user: User` by value, so `Root`’s `user: User` is not hidden:
		// receiving it reads `Host`’s instance.
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["Summary.swift"]):7:5: error: @Received property `user: Session` is not @Instantiated or @Forwarded in chain: Root -> Host -> Summary. Did you mean one of `user: LazilyInstantiated<User>`, `user: User`?
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: [
					"""
					@Instantiable(isRoot: true)
					public final class Root: Instantiable {
					    public init(user: User, host: Host) {
					        fatalError("SafeDI doesn't inspect the initializer body")
					    }

					    @Instantiated let user: User
					    @Instantiated let host: Host
					}
					""",
					"""
					@Instantiable
					public final class User: Instantiable {
					    public init() {}
					}

					public final class Session {}
					""",
					"""
					@Instantiable
					public final class Host: Instantiable {
					    public init(user: LazilyInstantiated<User>, summary: Summary) {
					        fatalError("SafeDI doesn't inspect the initializer body")
					    }

					    @Instantiated let user: LazilyInstantiated<User>
					    @Instantiated let summary: Summary
					}
					""",
					"""
					@Instantiable
					public final class Summary: Instantiable {
					    public init(user: Session) {
					        fatalError("SafeDI doesn't inspect the initializer body")
					    }

					    @Received let user: Session
					}
					""",
				],
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_suggestsOnlyAlias_whenAliasKeepingLabelHidesFartherDeclaration() async {
		// The seed shape with an alias: `Detail` renames `token` to `auth: Value?` only if available, which hides `Left`’s
		// `auth: Value`, so only the alias is suggested, with the fix-it that renames the receive.
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["Reader.swift"]):7:5: error: @Received property `token: Value?` is not @Instantiated or @Forwarded in chain: Root -> Left -> Detail -> Reader. Did you mean `auth: Value?`?
				\(fixtures["Reader.swift"]):7:19-7:24: fixit: auth
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: Self.aliasingDetailFiles(readerReceive: "token: Value?"),
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_generatesTree_whenReceiveTakesSuggestedAlias() async throws {
		// The remedy the error above suggests: `Reader` receives `Detail`’s alias, which is `nil`, since nothing above
		// `Detail` declares `token`.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: Self.aliasingDetailFiles(readerReceive: "auth: Value?"),
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.dependencyTreeFiles == ["Root+SafeDI.swift": """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public convenience init() {
		        func __safeDI_detail() -> Detail {
		            let auth: Value? = nil // Declared as Detail.auth
		            let reader = Reader(auth: auth)
		            return Detail(auth: auth, reader: reader)
		        }
		        func __safeDI_left() -> Left {
		            let auth = Value()
		            let detail: Detail = __safeDI_detail()
		            return Left(auth: auth, detail: detail)
		        }
		        let left: Left = __safeDI_left()
		        self.init(left: left)
		    }
		}
		"""])
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_leavesOutPropertyBeingBuilt_whenItsSiblingsNumberMoreThanThirtyTwo() async {
		// `Root` makes forty properties receivable, enough that the walk keeps the changes beneath it apart from them;
		// `Detail` is built inside `screen`, so `screen: Screen`, which shares the receive’s label, is no suggestion.
		await assertThrowsError(
			diagnostics: { fixtures in
				"""
				\(fixtures["Detail.swift"]):7:5: error: @Received property `screen: Screens` is not @Instantiated or @Forwarded in chain: Root -> Screen -> Detail. Did you mean `screens: Screens`?
				\(fixtures["Detail.swift"]):7:19-7:25: fixit: screens
				"""
			},
		) {
			try await executeSafeDIToolTest(
				swiftFileContent: Self.screenFilesWithFortySiblings,
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
	}

	// MARK: Private

	private var filesToDelete: [URL]

	/// `Root` instantiates `screen: Screen`, `screens: Screens` and forty services; `Screen` instantiates `Detail`, which
	/// receives `screen: Screens`.
	private static var screenFilesWithFortySiblings: [String] {
		let services = (0..<40).map { "service\($0): Service\($0)" }
		return [
			"""
			@Instantiable(isRoot: true)
			public final class Root: Instantiable {
			    public init(screen: Screen, screens: Screens, \(services.joined(separator: ", "))) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Instantiated let screen: Screen
			    @Instantiated let screens: Screens
			\(services.map { "    @Instantiated let \($0)" }.joined(separator: "\n"))
			}
			""",
			"""
			@Instantiable
			public final class Screen: Instantiable {
			    public init(detail: Detail) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Instantiated let detail: Detail
			}
			""",
			"""
			@Instantiable
			public final class Detail: Instantiable {
			    public init(screen: Screens) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Received let screen: Screens
			}
			""",
			"""
			@Instantiable
			public final class Screens: Instantiable {
			    public init() {}
			}
			""",
		] + (0..<40).map {
			"""
			@Instantiable
			public final class Service\($0): Instantiable {
			    public init() {}
			}
			"""
		}
	}

	/// `Root` instantiates `user: User` and builds `Host` through an `Instantiator`; `Host` forwards `hostForward` and
	/// instantiates `Summary`, which receives `summaryReceive`.
	private static func forwardingHostFiles(rootDeclaresViewer: Bool = false, hostForward: String = "user: User?", summaryReceive: String) -> [String] {
		[
			rootDeclaresViewer
				? """
				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init(user: User, viewer: User, hostBuilder: Instantiator<Host>) {
				        fatalError("SafeDI doesn't inspect the initializer body")
				    }

				    @Instantiated let user: User
				    @Instantiated let viewer: User
				    @Instantiated let hostBuilder: Instantiator<Host>
				}
				"""
				: """
				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init(user: User, hostBuilder: Instantiator<Host>) {
				        fatalError("SafeDI doesn't inspect the initializer body")
				    }

				    @Instantiated let user: User
				    @Instantiated let hostBuilder: Instantiator<Host>
				}
				""",
			"""
			@Instantiable
			public final class User: Instantiable {
			    public init() {}
			}

			public final class Session {}
			""",
			"""
			@Instantiable
			public final class Host: Instantiable {
			    public init(\(hostForward), summary: Summary) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Forwarded let \(hostForward)
			    @Instantiated let summary: Summary
			}
			""",
			"""
			@Instantiable
			public final class Summary: Instantiable {
			    public init(\(summaryReceive)) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Received let \(summaryReceive)
			}
			""",
		]
	}

	/// `Root` instantiates `Left`, which instantiates `auth: Value` and `Detail`; `Detail` renames `token` to
	/// `auth: Value?` only if available and instantiates `Reader`, which receives `readerReceive`.
	private static func aliasingDetailFiles(readerReceive: String) -> [String] {
		[
			"""
			@Instantiable(isRoot: true)
			public final class Root: Instantiable {
			    public init(left: Left) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Instantiated let left: Left
			}
			""",
			"""
			@Instantiable
			public final class Left: Instantiable {
			    public init(auth: Value, detail: Detail) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Instantiated let auth: Value
			    @Instantiated let detail: Detail
			}
			""",
			"""
			@Instantiable
			public final class Detail: Instantiable {
			    public init(auth: Value?, reader: Reader) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Received(fulfilledByDependencyNamed: "token", ofType: Value.self, onlyIfAvailable: true) let auth: Value?
			    @Instantiated let reader: Reader
			}
			""",
			"""
			@Instantiable
			public final class Value: Instantiable {
			    public init() {}
			}
			""",
			"""
			@Instantiable
			public final class Reader: Instantiable {
			    public init(\(readerReceive)) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Received let \(readerReceive)
			}
			""",
		]
	}
}
