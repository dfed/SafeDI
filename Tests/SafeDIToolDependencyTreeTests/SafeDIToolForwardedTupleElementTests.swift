/// A built type of a forwarded tuple, declared in another module than the type whose mock receives its erased instantiator.
struct ForwardedTupleBuiltTypeInOtherModule: CustomTestStringConvertible, Sendable {
	let packageOfBuiltType: String
	let builtTypeFixture: String

	var testDescription: String {
		"\(packageOfBuiltType): \(builtTypeFixture)"
	}
}

/// An `ErasedInstantiator`'s first generic argument, spelled as the tuple of the `@Forwarded` properties of the type it
/// builds, whose elements' types are not one bare name. The graph fuzzer draws the other spellings of an element
/// (`GraphFuzzerForwardedTupleElement`).
struct SafeDIToolForwardedTupleElementTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_generatesErasedInstantiatorAndMock_whenForwardedTupleHasOptionalElement() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				public class Screen {
				    public init() {}
				}

				@Instantiable
				public final class Child: Screen, Instantiable {
				    public init(count: Int?, title: String) {
				        self.count = count
				        self.title = title
				        super.init()
				    }

				    @Forwarded let count: Int?
				    @Forwarded let title: String
				}
				""",
				"""
				@Instantiable(isRoot: true, generateMock: true)
				public final class Root: Instantiable {
				    public init(childBuilder: ErasedInstantiator<(count: Int?, title: String), Screen>) {
				        self.childBuilder = childBuilder
				    }

				    @Instantiated(fulfilledByType: "Child") let childBuilder: ErasedInstantiator<(count: Int?, title: String), Screen>
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.dependencyTreeFiles["Root+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public convenience init() {
		        func __safeDI_childBuilder(count: Int?, title: String) -> Child {
		            Child(count: count, title: title)
		        }
		        let childBuilder = ErasedInstantiator<(count: Int?, title: String), Screen> {
		            __safeDI_childBuilder(count: $0.count, title: $0.title)
		        }
		        self.init(childBuilder: childBuilder)
		    }
		}
		""", "Unexpected output \(output.dependencyTreeFiles["Root+SafeDI.swift"] ?? "")")

		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            childBuilder: ((Int?, String) -> Screen)? = nil
		        ) {
		            self.childBuilder = childBuilder
		        }

		        let childBuilder: ((Int?, String) -> Screen)?
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        func __safeDI_childBuilder(count: Int?, title: String) -> Screen {
		            if let safeDIBuilder = safeDIOverrides.childBuilder { safeDIBuilder(count, title) } else { Child(count: count, title: title) }
		        }
		        let childBuilder = ErasedInstantiator<(count: Int?, title: String), Screen> {
		            __safeDI_childBuilder(count: $0.count, title: $0.title)
		        }
		        return Root(childBuilder: childBuilder)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")
	}

	/// The types a tree holds around a `Receiver` whose mock takes the erased instantiator it receives. Nothing builds the
	/// instantiator but `Holder`'s creator, which hands it over: `Child` is built in no tree.
	private static let forwardedTupleReceiverFixtures = [
		"""
		@Instantiable(generateMock: true)
		public final class Receiver: Instantiable {
		    public init(childBuilder: ErasedInstantiator<(count: Int?, names: [String]), Child>) {
		        self.childBuilder = childBuilder
		    }

		    @Received let childBuilder: ErasedInstantiator<(count: Int?, names: [String]), Child>
		}
		""",
		"""
		@Instantiable
		public final class Holder: Instantiable {
		    public init(childBuilder: ErasedInstantiator<(count: Int?, names: [String]), Child>, receiver: Receiver) {
		        self.childBuilder = childBuilder
		        self.receiver = receiver
		    }

		    @Forwarded let childBuilder: ErasedInstantiator<(count: Int?, names: [String]), Child>
		    @Instantiated let receiver: Receiver
		}
		""",
		"""
		@Instantiable(isRoot: true)
		public final class Root: Instantiable {
		    public init(holderBuilder: Instantiator<Holder>) {
		        self.holderBuilder = holderBuilder
		    }

		    @Instantiated let holderBuilder: Instantiator<Holder>
		}
		""",
	]

	/// The mock of `forwardedTupleReceiverFixtures`' `Receiver`, as a module whose mock builds no `Child` generates it.
	private static let forwardedTupleReceiverMock = """
	#if DEBUG
	extension Receiver {
	    static func mock(
	        childBuilder: ErasedInstantiator<(count: Int?, names: [String]), Child>
	    ) -> Receiver {
	        return Receiver(childBuilder: childBuilder)
	    }
	}
	#endif
	"""

