	@Test(arguments: MultiModuleIntegration.allCases, [
		ForwardedTupleBuiltTypeInOtherModule(
			packageOfBuiltType: "Pipeline",
			builtTypeFixture: """
			@Instantiable
			public final class Child: Instantiable {
			    init(count: Int?, names: [String]) {
			        self.count = count
			        self.names = names
			    }

			    @Forwarded let count: Int?
			    @Forwarded let names: [String]
			}
			""",
		),
		ForwardedTupleBuiltTypeInOtherModule(
			packageOfBuiltType: "OtherPipeline",
			builtTypeFixture: """
			@Instantiable
			public final class Child: Instantiable {
			    package init(count: Int?, names: [String]) {
			        self.count = count
			        self.names = names
			    }

			    @Forwarded let count: Int?
			    @Forwarded let names: [String]
			}
			""",
		),
		ForwardedTupleBuiltTypeInOtherModule(
			packageOfBuiltType: "Pipeline",
			builtTypeFixture: """
			@Instantiable
			public final class Child: Instantiable {
			    public init(count: Int?, names: [String], leaf: Leaf) {
			        self.count = count
			        self.names = names
			        self.leaf = leaf
			    }

			    @Forwarded let count: Int?
			    @Forwarded let names: [String]
			    @Instantiated let leaf: Leaf
			}

			@Instantiable
			public final class Leaf: Instantiable {
			    init() {}
			}
			""",
		),
	])
	mutating func multiModuleTest_generatesMockTakingErasedInstantiator_whenMockedModuleCannotConstructBuiltTypeTree(integration: MultiModuleIntegration, builtType: ForwardedTupleBuiltTypeInOtherModule) async throws {
		let output = try await executeSafeDIToolMultiModuleTest(
			modules: [
				ModuleFixture(
					name: "Core",
					packageName: builtType.packageOfBuiltType,
					swiftFileContent: [builtType.builtTypeFixture],
				),
				ModuleFixture(
					name: "App",
					packageName: "Pipeline",
					swiftFileContent: Self.forwardedTupleReceiverFixtures.map { "import Core\n\n\($0)" },
					dependencies: ["Core"],
				),
			],
			integration: integration,
			filesToDelete: &filesToDelete,
		)

		let generatedFiles = try #require(output.modules["App"]).generatedFiles
		let header = generatedFileHeader + """
		#if canImport(Core)
		import Core
		#endif


		"""
		switch integration {
		case .moduleInfo:
			#expect(generatedFiles["App.swift"] == header + """
			extension Root {
			    public convenience init() {
			        func __safeDI_holderBuilder(childBuilder: ErasedInstantiator<(count: Int?, names: [String]), Child>) -> Holder {
			            let receiver = Receiver(childBuilder: childBuilder)
			            return Holder(childBuilder: childBuilder, receiver: receiver)
			        }
			        let holderBuilder = Instantiator<Holder> {
			            __safeDI_holderBuilder(childBuilder: $0)
			        }
			        self.init(holderBuilder: holderBuilder)
			    }
			}


			""" + Self.forwardedTupleReceiverMock, "Unexpected output \(generatedFiles["App.swift"] ?? "")")
		case .swiftPackagePlugin:
			#expect(generatedFiles["Receiver+SafeDIMock.swift"] == header + Self.forwardedTupleReceiverMock, "Unexpected output \(generatedFiles)")
		}
		guard compileVerificationIsEnabled else { return }
		let compilation = try #require(output.compilation)
		#expect(compilation.failure == nil)
	}

