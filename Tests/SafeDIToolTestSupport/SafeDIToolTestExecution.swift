/// What every generated file starts with, ending with the blank line that precedes its imports or code.
let generatedFileHeader = """
// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
// Any modifications made to this file will be overwritten on subsequent builds.
// Please refrain from editing this file directly.

""" + "\n"

/// The mock configuration file of a module whose mocks configure nothing and whose files import nothing.
let emptyMockConfigurationFileOutput = generatedFileHeader

/// The last sentence of an error about a type no `@Instantiable` declaration fulfills, in a run that cannot tell which
/// modules it could have read: how the Xcode project plugin, or a run by hand, reads the target that declares one.
func fulfillingDeclarationInTargetNotReadRemedy(for typeName: String) -> String {
	"If a declaration that fulfills `\(typeName)` is in another target, add that target’s folder to `additionalDirectoriesToInclude` in this target’s `#SafeDIConfiguration`, or, in a SafeDITool run by hand, list the `.safedi` file of its module in the file you pass to `--dependent-module-info-file-path`."
}

/// The last sentences of an error about a type no `@Instantiable` declaration fulfills, at a file that may import a module
/// the run read nothing of: how `integration` reads the module that declares one.
func fulfillingDeclarationInModuleNotReadRemedy(for typeName: String, integration: MultiModuleIntegration) -> String {
	switch integration {
	case .moduleInfo:
		"If a declaration that fulfills `\(typeName)` is in another module, run SafeDI on that module and list it among this module’s SafeDI dependencies: under Bazel, declare it with `safedi_swift_library` (or a `safedi_compile` rule) and list its `<name>_safedi` target in this target’s `safedi_deps`; under Tuist, give its target `SafeDI.preCompileScript` and list it in the `dependencies:` of this target’s `SafeDI.preCompileScript`; in a custom build, list its `.safedi` file in the file you pass to `--dependent-module-info-file-path`."
	case .swiftPackagePlugin:
		"If a declaration that fulfills `\(typeName)` is in another target, add that target to this target’s `dependencies` in `Package.swift`: SafeDI reads only the targets this target depends on. For a target of a package fetched from a URL, add the package’s checkout directory to `additionalDirectoriesToInclude` in a `#SafeDIConfiguration` instead."
	}
}

/// The last remedy of an error about a type no `@Instantiable` declaration a seam's caller can see fulfills: what each
/// integration does to read the module that declares one.
let fulfillingDeclarationInAnotherModuleRemedy = "or, if such a declaration is in another module, make that module one SafeDI reads for this target: add its target to this target's `dependencies` in `Package.swift`, declare that module with `safedi_swift_library` (or a `safedi_compile` rule) and list its `<name>_safedi` target in this target's `safedi_deps` under Bazel, or give its target `SafeDI.preCompileScript` and list its module in the `dependencies:` of this target's `SafeDI.preCompileScript` under Tuist."

@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
func executeSafeDIToolTest(
	swiftFileContent: [String],
	swiftFileContentByFilePath: [String: String] = [:],
	additionalDirectorySwiftFileContent: [String] = [],
	dependentModuleInfoPaths: [String] = [],
	additionalImportedModules: [String] = [],
	buildSwiftOutputDirectory: Bool = false,
	pluginInvocation: PluginInvocation? = nil,
	buildDOTFileOutput: Bool = false,
	buildCombinedOutput: Bool = false,
	filesToDelete: inout [URL],
	includeFolders: [String] = [],
	skipCompileVerification: Bool = false,
	inputPathsRelativeToCurrentDirectory: Bool = false,
	compilerReceivesInputPathsUnchanged: Bool = false,
	activeCompilationConditions: [String] = [],
	buildSettingArguments: [String] = [],
	moduleMembershipArguments: [String] = [],
	pluginTargetGraph: ((_ inputSwiftFilePaths: [String]) -> PluginTargetGraph)? = nil,
	verificationCompilationConditions: [String]? = nil,
	verificationCompilerSettings: VerificationCompilerSettings = VerificationCompilerSettings(),
	swiftFileContentAfterScan: [String]? = nil,
) async throws -> TestOutput {
	await ProcessSlots.shared.takePlaceInLine(for: Test.current?.id)
	// Create additional directory first so its path can be substituted into target file content.
	var additionalDirectoryFiles = [URL]()
	var additionalFixtureDirectory: URL?
	if !additionalDirectorySwiftFileContent.isEmpty {
		let additionalDirectory = URL.temporaryFile
		try FileManager.default.createDirectory(at: additionalDirectory, withIntermediateDirectories: true)
		additionalFixtureDirectory = additionalDirectory
		additionalDirectoryFiles = try createSwiftFixtureFiles(
			from: additionalDirectorySwiftFileContent,
			in: additionalDirectory,
		)
	}

	let swiftFileCSV = URL.temporaryFile
	let swiftFixtureDirectory = switch pluginInvocation {
	case .scanDuringGenerate:
		// The plugin's paths are relative to the project root, which is `generate`'s working directory.
		URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
			.appendingPathComponent(".build")
			.appendingPathComponent("SafeDIToolTestFixtures")
			.appendingPathComponent(UUID().uuidString)
	case .scanWhilePlanning, nil:
		TestFixtureLocation.parentDirectory?.appendingPathComponent(UUID().uuidString) ?? URL.temporaryFile
	}
	try FileManager.default.createDirectory(at: swiftFixtureDirectory, withIntermediateDirectories: true)

	// Replace directory placeholders in target file content with real paths.
	func resolvingDirectoryPlaceholders(in content: String) -> String {
		var resolved = content.replacingOccurrences(
			of: "$TARGET_DIRECTORY",
			with: swiftFixtureDirectory.path,
		)
		if let additionalFixtureDirectory {
			resolved = resolved.replacingOccurrences(
				of: "$ADDITIONAL_DIRECTORY",
				with: additionalFixtureDirectory.path,
			)
		}
		return resolved
	}
	let resolvedSwiftFileContent = swiftFileContent.map(resolvingDirectoryPlaceholders(in:))

	let contentNamedSwiftFiles = try createSwiftFixtureFiles(
		from: resolvedSwiftFileContent,
		in: swiftFixtureDirectory,
	)
	let pathNamedSwiftFiles = try createSwiftFixtureFiles(
		atFilePaths: swiftFileContentByFilePath,
		in: swiftFixtureDirectory,
		alongside: contentNamedSwiftFiles,
	)
	let swiftFiles = contentNamedSwiftFiles + pathNamedSwiftFiles
	let fixtureDirectoryRelativePaths = swiftFiles.map { String($0.path.dropFirst(swiftFixtureDirectory.path.count + 1)) }
	// The project root as the build system reports it to a build tool plugin that has `generate --output-directory`
	// scan for itself: `generate`'s working directory, which holds the fixture directory.
	let reportedProjectRootPath: String? = switch pluginInvocation {
	case .scanDuringGenerate(reportsFixtureDirectoryThroughSymbolicLink: false):
		FileManager.default.currentDirectoryPath
	case .scanDuringGenerate(reportsFixtureDirectoryThroughSymbolicLink: true):
		// The way Xcode reports a project under `/tmp`, which resolves to `/private/tmp`.
		try symbolicLink(to: URL(fileURLWithPath: FileManager.default.currentDirectoryPath), filesToDelete: &filesToDelete).path
	case .scanWhilePlanning, nil:
		nil
	}
	// The fixture directory as the build system reports it to a build tool plugin, and spells it to the compiler.
	let reportedFixtureDirectoryPath: String? = switch pluginInvocation {
	case .scanWhilePlanning(reportsFixtureDirectoryThroughSymbolicLink: false):
		// With its symbolic links resolved, a leading `/private` included.
		try realPath(of: swiftFixtureDirectory)
	case .scanWhilePlanning(reportsFixtureDirectoryThroughSymbolicLink: true):
		// The way Xcode reports a project under `/tmp`, which resolves to `/private/tmp`.
		try symbolicLink(to: swiftFixtureDirectory, filesToDelete: &filesToDelete).path
	case .scanDuringGenerate:
		try "\(#require(reportedProjectRootPath))/\(currentDirectoryRelativePath(to: swiftFixtureDirectory))"
	case nil:
		nil
	}
	// Build systems like Bazel hand the tool paths relative to its working
	// directory; mirror that by computing paths relative to the test process's
	// current directory, which leaves the process-global directory untouched.
	let inputSwiftFilePaths = switch pluginInvocation {
	case .scanWhilePlanning:
		fixtureDirectoryRelativePaths
	case .scanDuringGenerate:
		swiftFiles.map(currentDirectoryRelativePath(to:))
	case nil:
		if inputPathsRelativeToCurrentDirectory {
			swiftFiles.map(currentDirectoryRelativePath(to:))
		} else {
			swiftFiles.map(\.relativePath)
		}
	}
	// The paths the build system hands the compiler when a plugin runs the tool, and otherwise the absolute paths.
	let compilerSwiftFilePaths = if let reportedFixtureDirectoryPath {
		fixtureDirectoryRelativePaths.map { "\(reportedFixtureDirectoryPath)/\($0)" }
	} else {
		swiftFiles.map(\.path)
	}
	try inputSwiftFilePaths
		.joined(separator: ",")
		.write(to: swiftFileCSV, atomically: true, encoding: .utf8)
	if let pluginTargetGraph {
		// As the SafeDIGenerator plugin writes it beside its CSV, spelling each file as the CSV does.
		let targetGraphFile = URL(fileURLWithPath: swiftFileCSV.path + PluginTargetGraph.fileNameSuffix)
		try JSONEncoder().encode(pluginTargetGraph(inputSwiftFilePaths)).write(to: targetGraphFile)
		filesToDelete.append(targetGraphFile)
	}

	let dependentModuleInfoFileCSV = URL.temporaryFile
	try dependentModuleInfoPaths
		.joined(separator: ",")
		.write(to: dependentModuleInfoFileCSV, atomically: true, encoding: .utf8)

	// A module info file names the module it describes, so the run writes one only when the test names its module.
	let moduleInfoOutput: URL? = moduleMembershipArguments.contains("--module-name") ? URL.temporaryFile.appendingPathExtension("safedi") : nil
	let outputDirectory = TestTemporaryDirectory.root.appendingPathComponent(UUID().uuidString)
	let manifestFile = URL.temporaryFile.appendingPathExtension("json")
	let dotTreeOutput = URL.temporaryFile.appendingPathExtension("dot")
	let combinedOutput = URL.temporaryFile.appendingPathExtension("swift")

	// Build the StubFileFinder. When additional directory files exist, make it
	// directory-aware so it returns only files under the enumerated root.
	let fileFinder = if !additionalDirectoryFiles.isEmpty {
		StubFileFinder(filesByDirectory: [
			swiftFixtureDirectory: swiftFiles,
			additionalFixtureDirectory!: additionalDirectoryFiles,
		])
	} else {
		StubFileFinder(files: swiftFiles)
	}

	return try await SafeDITool.$fileFinder.withValue(fileFinder) {
		// Build the manifest by scanning for roots using the Scan subcommand.
		var manifestPath: String?
		switch pluginInvocation {
		case .scanWhilePlanning:
			try FileManager.default.createDirectory(at: outputDirectory, withIntermediateDirectories: true)
			try await performScanCheckingCache(
				inputSourcesFile: swiftFileCSV.relativePath,
				projectFilePaths: try ProjectFilePaths(projectRoot: #require(reportedFixtureDirectoryPath)),
				outputDirectory: outputDirectory.path,
				manifestFile: manifestFile.relativePath,
				mockScopedFiles: compilerSwiftFilePaths,
				activeCompilationConditions: Set(activeCompilationConditions),
				filesToDelete: &filesToDelete,
			)
			manifestPath = manifestFile.relativePath
		case .scanDuringGenerate:
			// `generate --output-directory` scans for itself.
			try FileManager.default.createDirectory(at: outputDirectory, withIntermediateDirectories: true)
		case nil:
			break
		}
		if buildSwiftOutputDirectory {
			try FileManager.default.createDirectory(at: outputDirectory, withIntermediateDirectories: true)
			let projectRoot = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)

			// Write the input sources CSV for the scan command.
			let allScanFiles = swiftFiles + additionalDirectoryFiles
			let scanCSV = URL.temporaryFile
			try allScanFiles
				.map(\.relativePath)
				.joined(separator: ",")
				.write(to: scanCSV, atomically: true, encoding: .utf8)

			try await performScanCheckingCache(
				inputSourcesFile: scanCSV.relativePath,
				projectFilePaths: ProjectFilePaths(projectRoot: projectRoot.path),
				outputDirectory: outputDirectory.path,
				manifestFile: manifestFile.relativePath,
				mockScopedFiles: swiftFiles.map(\.relativePath),
				activeCompilationConditions: Set(activeCompilationConditions),
				filesToDelete: &filesToDelete,
			)
			manifestPath = manifestFile.relativePath

			filesToDelete.append(scanCSV)

			if let swiftFileContentAfterScan {
				// Rewrite each fixture but restore the modification time scan recorded, so the freshness check
				// cannot see the edit and `generate` reads the new content only when it parses afresh for
				// another reason: the generated code shows whether `generate` reused scan's parse.
				for (fileURL, content) in zip(contentNamedSwiftFiles, swiftFileContentAfterScan) {
					let scannedModificationTime = try FileModificationTime(ofItemAtPath: fileURL.path)
					try resolvingDirectoryPlaceholders(in: content).write(to: fileURL, atomically: true, encoding: .utf8)
					try scannedModificationTime.apply(toItemAtPath: fileURL.path)
				}
			}
		}

		var generateArguments = [swiftFileCSV.relativePath]
		for folder in includeFolders {
			generateArguments += ["--include", folder]
		}
		for module in additionalImportedModules {
			generateArguments += ["--additional-imported-modules", module]
		}
		if let moduleInfoOutput {
			generateArguments += ["--module-info-output", moduleInfoOutput.relativePath]
		}
		if !dependentModuleInfoPaths.isEmpty {
			generateArguments += ["--dependent-module-info-file-path", dependentModuleInfoFileCSV.relativePath]
		}
		if let manifestPath {
			// The manifest carries the conditions scan was given, which is how the
			// SPM plugin's generate invocation receives them.
			generateArguments += ["--swift-manifest", manifestPath]
		} else {
			if case .scanDuringGenerate = pluginInvocation {
				// A build tool plugin names the target's own files with the absolute paths the build system reported,
				// and the project root as the build system reported it.
				generateArguments += try ["--output-directory", outputDirectory.path, "--project-root", #require(reportedProjectRootPath), "--mock-scoped-files"] + compilerSwiftFilePaths
			}
			for condition in activeCompilationConditions {
				generateArguments += ["--active-compilation-conditions", condition]
			}
		}
		generateArguments += buildSettingArguments
		generateArguments += moduleMembershipArguments
		if buildDOTFileOutput {
			generateArguments += ["--dot-file-output", dotTreeOutput.relativePath]
		}
		if buildCombinedOutput {
			generateArguments += ["--combined-output", combinedOutput.relativePath]
		}
		if compilerReceivesInputPathsUnchanged {
			generateArguments += ["--compiler-receives-input-paths-unchanged"]
		}
		let tool = try Generate.parse(generateArguments)
		// Call `generate()` rather than `run()`: `run()` prints located errors in compiler format and
		// rethrows them as an `ExitCode`, which would hide the error from the assertion helpers.
		let fixtures = FixturePaths(
			fileNames: contentNamedSwiftFiles.map(\.lastPathComponent) + swiftFileContentByFilePath.keys.sorted() + additionalDirectoryFiles.map { "AdditionalDirectory/\($0.lastPathComponent)" },
			paths: inputSwiftFilePaths + additionalDirectoryFiles.map(\.path),
			compilerPaths: compilerSwiftFilePaths + additionalDirectoryFiles.map(\.path),
		)
		let generateOutput: Generate.Output
		do {
			// Every place's levels must hold its scope struct's fields (`SeamPlaceLevels.pathStructMismatches`).
			generateOutput = try await SeamPlaceLevels.$observer.withValue(SeamPlaceLevels.checkingPathStructs(handingOn: SeamPlaceLevels.observer)) {
				try await tool.generate()
			}
		} catch {
			throw SafeDIToolTestError(underlyingError: error, fixtures: fixtures)
		}

		filesToDelete.append(swiftFileCSV)
		filesToDelete.append(swiftFixtureDirectory)
		if let moduleInfoOutput {
			filesToDelete.append(moduleInfoOutput)
		}
		if let additionalFixtureDirectory {
			filesToDelete.append(additionalFixtureDirectory)
		}
		if buildSwiftOutputDirectory || pluginInvocation != nil {
			filesToDelete.append(outputDirectory)
		}
		if manifestPath != nil {
			filesToDelete.append(manifestFile)
		}
		if buildDOTFileOutput {
			filesToDelete.append(dotTreeOutput)
		}
		if buildCombinedOutput {
			filesToDelete.append(combinedOutput)
		}

		// Read generated files from the output directory.
		let generatedFiles: [String: String]? = if buildSwiftOutputDirectory || pluginInvocation != nil {
			{
				guard let fileNames = try? FileManager.default.contentsOfDirectory(atPath: outputDirectory.relativePath) else { return [:] }
				var result = [String: String]()
				for fileName in fileNames where fileName.hasSuffix(".swift") {
					let filePath = (outputDirectory.relativePath as NSString).appendingPathComponent(fileName)
					result[fileName] = try? String(contentsOfFile: filePath, encoding: .utf8)
				}
				return result
			}()
		} else {
			nil
		}
		if let generatedFiles {
			// Every output the manifest plans is a file of its own. Two names a volume holds as one file, such as
			// names that differ only in letter case on macOS's default volume, would leave one file holding the
			// code written last, which compiles the file listing alone cannot notice.
			let manifest = try JSONDecoder().decode(
				SafeDIToolManifest.self,
				from: Data(contentsOf: URL(fileURLWithPath: manifestPath ?? outputDirectory.appendingPathComponent("SafeDIManifest.json").path)),
			)
			let plannedOutputFilePaths = (manifest.dependencyTreeGeneration + manifest.mockGeneration).map(\.outputFilePath)
				+ (manifest.mockConfigurationOutputFilePath.map { [$0] } ?? [])
			#expect(generatedFiles.keys.sorted() == plannedOutputFilePaths.map { ($0 as NSString).lastPathComponent }.sorted())
		}

		let moduleInfoFile = try moduleInfoOutput.map { try ModuleInfoFile(moduleInfoData: Data(contentsOf: $0)) }
		if let generatedFiles, !generatedFiles.isEmpty, !skipCompileVerification {
			try await verifyGeneratedCodeCompiles(
				inputSwiftFiles: swiftFiles,
				additionalDirectorySwiftFiles: additionalDirectoryFiles,
				generatedFiles: generatedFiles,
				activeCompilationConditions: verificationCompilationConditions ?? activeCompilationConditions,
				// Without a configuration, mocks are wrapped in `#if DEBUG`, which the verifier always defines.
				mockConditionalCompilation: generateOutput.module.configurations.first?.mockConditionalCompilation,
				compilerSettings: verificationCompilerSettings,
				filesToDelete: &filesToDelete,
			)
		}

		return try TestOutput(
			moduleInfoFile: moduleInfoFile,
			moduleInfoOutputPath: moduleInfoOutput?.relativePath,
			fixtures: fixtures,
			warnings: generateOutput.warnings,
			generateOutput: generateOutput,
			generatedFiles: generatedFiles,
			dotTree: buildDOTFileOutput ? String(data: Data(contentsOf: dotTreeOutput), encoding: .utf8) : nil,
			combinedOutput: buildCombinedOutput
				? String(data: Data(contentsOf: combinedOutput), encoding: .utf8)
				: nil,
		)
	}
}

@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
struct TestOutput {
	/// The module info file `generate` wrote, which it writes only for a test that names its module.
	let moduleInfoFile: ModuleInfoFile?
	/// The module `moduleInfoFile` describes.
	var moduleInfo: ModuleInfo? {
		moduleInfoFile?.module
	}

	let moduleInfoOutputPath: String?
	/// The fixture files written for `swiftFileContent`, looked up by file name.
	let fixtures: FixturePaths
	/// The non-fatal diagnostics `generate` reported, which `run()` prints to standard error.
	let warnings: [SourceDiagnostic]
	/// What `generate` read and reported.
	let generateOutput: Generate.Output
	let generatedFiles: [String: String]?
	let dotTree: String?
	let combinedOutput: String?

	/// The path of the module info `generate` wrote, which a test that names its module hands to another run.
	var writtenModuleInfoOutputPath: String {
		get throws {
			try #require(moduleInfoOutputPath)
		}
	}

	/// The module info `generate` wrote, for a test that names its module.
	var writtenModuleInfo: ModuleInfo {
		get throws {
			try #require(moduleInfo)
		}
	}

	var dependencyTreeFiles: [String: String] {
		generatedFiles?.filter { $0.key.hasSuffix("+SafeDI.swift") } ?? [:]
	}

	var mockFiles: [String: String] {
		generatedFiles?.filter { $0.key.hasSuffix("+SafeDIMock.swift") } ?? [:]
	}

	var mockConfigurationFile: String? {
		generatedFiles?["SafeDIMockConfiguration.swift"]
	}
}

/// Runs `scan` as `performScan` does, and checks that its cache, written beside `manifestFile`, reads back
/// exactly what scan wrote, so a field the binary coder drops fails whichever tests give that field a value.
/// Every harness fixture that runs scan goes through here; a test that calls `performScan` itself checks what
/// it needs. The cache is registered in `filesToDelete` before it is read, once, however many scans share it.
@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
@discardableResult
func performScanCheckingCache(
	inputSourcesFile: String,
	projectFilePaths: ProjectFilePaths,
	outputDirectory: String,
	manifestFile: String,
	mockScopedFiles: [String],
	activeCompilationConditions: Set<String>,
	filesToDelete: inout [URL],
	sourceLocation: SourceLocation = #_sourceLocation,
) async throws -> CachedScannedModuleInfo {
	let scannedModuleInfo = try await performScan(
		inputSourcesFile: inputSourcesFile,
		projectFilePaths: projectFilePaths,
		outputDirectory: outputDirectory,
		manifestFile: manifestFile,
		mockScopedFiles: mockScopedFiles,
		activeCompilationConditions: activeCompilationConditions,
	)
	let scanCacheURL = scannedModuleInfoURL(forManifestPath: manifestFile)
	if !filesToDelete.contains(scanCacheURL) {
		filesToDelete.append(scanCacheURL)
	}
	let scanCache = try Data(contentsOf: scanCacheURL)
	#expect(
		try reflectedDescription(of: CachedScannedModuleInfo(scanCacheData: scanCache)) == reflectedDescription(of: scannedModuleInfo),
		sourceLocation: sourceLocation,
	)
	return scannedModuleInfo
}

/// Where `executeSafeDIToolTest` and `executeSafeDIToolMultiModuleTest` create a fixture's directory.
enum TestFixtureLocation {
	/// The directory to create each fixture directory in instead of the temporary directory, or `nil` for the temporary
	/// directory. A test binds it to place fixtures under a path that holds text an oracle must not rewrite, as a CI
	/// runner's temporary directory may (`/var/folders/h5/t85nd…/T` holds `t8`, a label the rename oracle reverses).
	@TaskLocal static var parentDirectory: URL?
}

extension URL {
	fileprivate static var temporaryFile: URL {
		TestTemporaryDirectory.uniquePath()
	}
}

struct StubFileFinder: FileFinder {
	/// Creates a file finder that returns the same files regardless of which directory is enumerated.
	init(files: [URL]) {
		filesByDirectory = nil
		fallbackFiles = files
	}

	/// Creates a directory-aware file finder that returns only files under the enumerated root.
	init(filesByDirectory: [URL: [URL]]) {
		self.filesByDirectory = filesByDirectory
		fallbackFiles = []
	}

	func enumerator(
		at url: URL,
		includingPropertiesForKeys _: [URLResourceKey]?,
		options _: FileManager.DirectoryEnumerationOptions,
		errorHandler _: ((URL, any Error) -> Bool)?,
	) -> FileManager.DirectoryEnumerator? {
		let matchedFiles: [URL]
		if let filesByDirectory {
			let standardizedPath = url.standardizedFileURL.path
			matchedFiles = filesByDirectory.first(where: { directory, _ in
				directory.standardizedFileURL.path == standardizedPath
			})?.value ?? []
		} else {
			matchedFiles = fallbackFiles
		}
		return StubDirectoryEnumerator(files: matchedFiles)
	}

	final class StubDirectoryEnumerator: FileManager.DirectoryEnumerator {
		init(files: [URL]) {
			self.files = files
				// Also include a random file in the glob.
				+ [URL.temporaryFile]
		}

		override func nextObject() -> Any? {
			if files.isEmpty {
				nil
			} else {
				files.removeFirst()
			}
		}

		var files: [URL]
	}

	private let filesByDirectory: [URL: [URL]]?
	private let fallbackFiles: [URL]
}

/// The fixture files `executeSafeDIToolTest` wrote for `swiftFileContent`, looked up by file name.
///
/// Each file is named after the `@Instantiable` type its snippet declares (falling back to the first
/// declared type, then to `File`, with `_2`, `_3`… suffixes for repeats), so a test names the file it means
/// rather than relying on the order of its snippets. A file from `swiftFileContentByFilePath` is looked up by
/// the path it was given there, such as `Module/SafeDIConfiguration.swift`, and a file from
/// `additionalDirectorySwiftFileContent` under `AdditionalDirectory/`, by the path the tool found it at. Paths are exactly as they were written to the CSV
/// the tool read: absolute by default, relative to the current directory when the test passed
/// `inputPathsRelativeToCurrentDirectory: true` or `.scanDuringGenerate`, and relative to the fixture directory
/// when it passed `.scanWhilePlanning`.
struct FixturePaths {
	init(fileNames: [String], paths: [String], compilerPaths: [String]) {
		pathsByFileName = Dictionary(uniqueKeysWithValues: zip(fileNames, paths))
		compilerPathsByFileName = Dictionary(uniqueKeysWithValues: zip(fileNames, compilerPaths))
	}

	/// The path of the named fixture. A name the harness did not write records an issue listing the
	/// files it did write and returns a sentinel, so the assertion fails readably instead of crashing.
	subscript(fileName: String, sourceLocation sourceLocation: SourceLocation = #_sourceLocation) -> String {
		path(of: fileName, in: pathsByFileName, sourceLocation: sourceLocation)
	}

	/// The path of the named fixture, or `nil` when the harness wrote no fixture of that name.
	func writtenPath(of fileName: String) -> String? {
		pathsByFileName[fileName]
	}

	/// The path a build system hands the compiler for the named fixture when a build tool plugin runs the tool:
	/// absolute, beginning with the fixture directory as the build system reports it. `run()` prints a diagnostic at
	/// this path, but a diagnostic `generate()` returns cites the path the file was parsed under: this path normalized
	/// (`NormalizedFilePath(compilerPath(of:)).path`) when the fixture directory is reported resolved. On Apple
	/// platforms the two differ whenever the fixture directory lies under `/private/var` or `/private/tmp`, from which
	/// normalizing drops `/private`. That is always the case for `.scanWhilePlanning`, whose fixtures are in the
	/// temporary directory, and for `.scanDuringGenerate` it happens in a checkout under `/private/tmp`.
	func compilerPath(of fileName: String, sourceLocation: SourceLocation = #_sourceLocation) -> String {
		path(of: fileName, in: compilerPathsByFileName, sourceLocation: sourceLocation)
	}

	private let pathsByFileName: [String: String]
	private let compilerPathsByFileName: [String: String]

	private func path(of fileName: String, in pathsByFileName: [String: String], sourceLocation: SourceLocation) -> String {
		if let path = pathsByFileName[fileName] {
			return path
		} else {
			Issue.record(
				"No fixture named \(fileName). The harness wrote: \(pathsByFileName.keys.sorted().joined(separator: ", "))",
				sourceLocation: sourceLocation,
			)
			return "<missing fixture \(fileName)>"
		}
	}
}

/// How a build tool plugin runs the tool, for a test that mirrors one. Either way the plugin hands the tool
/// paths relative to a project root, and the build system hands the compiler the absolute paths it reported
/// to the plugin.
enum PluginInvocation {
	/// The plugin runs `scan` while it plans the build, handing it the project root as the build system reports
	/// it – with its symbolic links resolved, or through a symbolic link to the fixture directory – and `generate`
	/// reuses the parse `scan` cached.
	case scanWhilePlanning(reportsFixtureDirectoryThroughSymbolicLink: Bool)
	/// The plugin cannot run `scan` while it plans the build, so `generate --output-directory` scans for itself,
	/// reading paths relative to the project root, its working directory, which `--project-root` names as the build
	/// system reports it – directly, or through a symbolic link – and naming the target's files with
	/// `--mock-scoped-files` under that spelling of the root.
	case scanDuringGenerate(reportsFixtureDirectoryThroughSymbolicLink: Bool)
}

/// A new symbolic link to `destination`, which `filesToDelete` removes.
private func symbolicLink(to destination: URL, filesToDelete: inout [URL]) throws -> URL {
	let link = URL.temporaryFile
	try FileManager.default.createSymbolicLink(at: link, withDestinationURL: destination)
	filesToDelete.append(link)
	return link
}

/// `url`'s path with every symbolic link resolved, as `realpath(3)` resolves it. Foundation's
/// `resolvingSymlinksInPath()` would remove a leading `/private` instead.
func realPath(of url: URL) throws -> String {
	guard let resolvedPath = realpath(url.path, nil) else {
		throw CocoaError(.fileNoSuchFile)
	}
	defer { free(resolvedPath) }
	return String(cString: resolvedPath)
}

/// An error thrown by `executeSafeDIToolTest` when `generate` fails. Carries the fixture file paths exactly as
/// the tool read them so diagnostics that cite those paths can be asserted in full.
struct SafeDIToolTestError: Error, CustomStringConvertible {
	let underlyingError: any Error
	let fixtures: FixturePaths

	var description: String {
		"\(underlyingError)"
	}
}

func assertThrowsError(
	_ errorDescription: String,
	sourceLocation: SourceLocation = #_sourceLocation,
	block: () async throws -> some Sendable,
) async {
	do {
		_ = try await block()
		Issue.record("Did not throw error!", sourceLocation: sourceLocation)
	} catch {
		#expect(errorDescription == "\(error)", sourceLocation: sourceLocation)
	}
}

/// Asserts that `block` throws an error whose description – the compiler-formatted diagnostics for a
/// `SourceLocatedError` – exactly matches `expectedDiagnostics`, which is given the fixture files the
/// tool read so it can cite their paths in `<path>:<line>:<column>` locations.
func assertThrowsError(
	diagnostics expectedDiagnostics: (_ fixtures: FixturePaths) -> String,
	sourceLocation: SourceLocation = #_sourceLocation,
	block: () async throws -> some Sendable,
) async {
	do {
		_ = try await block()
		Issue.record("Did not throw error!", sourceLocation: sourceLocation)
	} catch let error as SafeDIToolTestError {
		#expect(expectedDiagnostics(error.fixtures) == "\(error.underlyingError)", sourceLocation: sourceLocation)
	} catch {
		Issue.record("Threw an error that does not carry fixture paths: \(error)", sourceLocation: sourceLocation)
	}
}

/// Variant of `assertThrowsError` that checks for a substring of the
/// thrown error's description. Use when the error surfaces through a
/// Foundation-level `NSError` whose string includes a per-run tmpdir
/// path — the stable part (e.g. "couldn't be opened") is still a
/// meaningful assertion, while the exact string isn't testable.
func assertThrowsError(
	containing substring: String,
	sourceLocation: SourceLocation = #_sourceLocation,
	block: () async throws -> some Sendable,
) async {
	do {
		_ = try await block()
		Issue.record("Did not throw error!", sourceLocation: sourceLocation)
	} catch {
		let description = "\(error)"
		#expect(
			description.contains(substring),
			"Expected error description to contain \"\(substring)\" but got: \(description)",
			sourceLocation: sourceLocation,
		)
	}
}

/// Writes each of `swiftFileContentByFilePath`'s contents at its path, relative to `directory`, creating
/// intermediate directories. Use it when a test depends on a file's name, such as `SafeDIConfiguration.swift`.
/// Paths are written in sorted order so the input order does not depend on dictionary iteration.
func createSwiftFixtureFiles(
	atFilePaths swiftFileContentByFilePath: [String: String],
	in directory: URL,
	alongside contentNamedSwiftFiles: [URL],
) throws -> [URL] {
	try swiftFileContentByFilePath.keys.sorted().map { filePath in
		let fileURL = directory.appendingPathComponent(filePath)
		if contentNamedSwiftFiles.contains(fileURL) {
			Issue.record("Fixture \(filePath) collides with a fixture named from its content")
		}
		try FileManager.default.createDirectory(at: fileURL.deletingLastPathComponent(), withIntermediateDirectories: true)
		try swiftFileContentByFilePath[filePath, default: ""].write(to: fileURL, atomically: true, encoding: .utf8)
		return fileURL
	}
}

/// Expresses `target` relative to the current directory using `..` components,
/// e.g. `../../tmp/Fixtures/Root.swift`, the way a build system would. The components are counted from the working
/// directory as `getcwd(3)` spells it, which is how a relative path is resolved, so the result names `target` wherever
/// the checkout lives, including under `/private/tmp`, whose normalized spelling drops a component.
func currentDirectoryRelativePath(to target: URL) -> String {
	let currentDirectoryComponents = URL(fileURLWithPath: FileManager.default.currentDirectoryPath).pathComponents
	let targetComponents = target.pathComponents
	let sharedComponentCount = zip(currentDirectoryComponents, targetComponents).prefix { $0 == $1 }.count
	let ascents = Array(repeating: "..", count: currentDirectoryComponents.count - sharedComponentCount)
	return (ascents + targetComponents[sharedComponentCount...]).joined(separator: "/")
}

@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
func createSwiftFixtureFiles(
	from swiftFileContent: [String],
	in directory: URL,
) throws -> [URL] {
	let instantiableRegex = try Regex(#"@Instantiable(?:\s*\([^)]*\))?"#)
	let instantiableTypeRegex = try Regex(#"(?:class|struct|actor|enum)\s+(\w+)"#)
	let firstTypeRegex = try Regex(#"(?:class|struct|actor|enum|protocol)\s+(\w+)"#)
	var fileNameCounts = [String: Int]()

	return try swiftFileContent.map { content in
		let baseName: String
		if let instantiableMatch = content.firstMatch(of: instantiableRegex) {
			let contentAfterInstantiable = content[instantiableMatch.range.upperBound...]
			if let typeMatch = contentAfterInstantiable.firstMatch(of: instantiableTypeRegex),
			   let nameRange = typeMatch.output[1].range
			{
				baseName = String(contentAfterInstantiable[nameRange])
			} else if let match = content.firstMatch(of: firstTypeRegex),
			          let nameRange = match.output[1].range
			{
				baseName = String(content[nameRange])
			} else {
				baseName = "File"
			}
		} else if let match = content.firstMatch(of: firstTypeRegex),
		          let nameRange = match.output[1].range
		{
			baseName = String(content[nameRange])
		} else {
			baseName = "File"
		}
		fileNameCounts[baseName, default: 0] += 1
		let fileNameSuffix = fileNameCounts[baseName, default: 1] == 1 ? "" : "_\(fileNameCounts[baseName, default: 1])"
		let fileURL = directory.appendingPathComponent("\(baseName)\(fileNameSuffix).swift")
		try content.write(to: fileURL, atomically: true, encoding: .utf8)
		return fileURL
	}
}
