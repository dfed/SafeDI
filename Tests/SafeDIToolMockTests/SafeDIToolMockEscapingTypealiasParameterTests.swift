/// A dependency whose type is a typealias of a function type, which the type's initializer declares `@escaping`: every
/// function generated code declares with a parameter of that type declares it `@escaping` too, or the value could not be
/// passed to the initializer. Each test compiles the fixture with the code generated from it.
struct SafeDIToolMockEscapingTypealiasParameterTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_declaresBuilderAndMockParametersEscaping_whenForwardedTypealiasOfClosureIsDeclaredEscaping() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				Self.onTapSource,
				"""
				@Instantiable(isRoot: true, generateMock: true)
				public struct Root: Instantiable {
				    public init(screenBuilder: Instantiator<Screen>) { self.screenBuilder = screenBuilder }
				    @Instantiated let screenBuilder: Instantiator<Screen>
				}
				""",
				"""
				@Instantiable(generateMock: true)
				public final class Screen: Instantiable {
				    public init(onTap: @escaping OnTap) { self.onTap = onTap }
				    @Forwarded let onTap: OnTap
				}
				""",
			],
			swiftFileContentByFilePath: [
				"MockCallSite.swift": """
				#if DEBUG
				func mocks() -> (Root, Screen) {
				    (
				        Root.mock(safeDIOverrides: .init(screenBuilder: { onTap in Screen(onTap: onTap) })),
				        Screen.mock(onTap: { _ in })
				    )
				}
				#endif
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.dependencyTreeFiles.count == 1)
		#expect(output.mockFiles.count == 2)
		#expect(output.dependencyTreeFiles["Root+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public init() {
		        func __safeDI_screenBuilder(onTap: @escaping OnTap) -> Screen {
		            Screen(onTap: onTap)
		        }
		        let screenBuilder = Instantiator<Screen> {
		            __safeDI_screenBuilder(onTap: $0)
		        }
		        self.init(screenBuilder: screenBuilder)
		    }
		}
		""", "Unexpected output \(output.dependencyTreeFiles["Root+SafeDI.swift"] ?? "")")
		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            screenBuilder: ((@escaping OnTap) -> Screen)? = nil
		        ) {
		            self.screenBuilder = screenBuilder
		        }

		        let screenBuilder: ((@escaping OnTap) -> Screen)?
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        func __safeDI_screenBuilder(onTap: @escaping OnTap) -> Screen {
		            if let safeDIBuilder = safeDIOverrides.screenBuilder { safeDIBuilder(onTap) } else { Screen(onTap: onTap) }
		        }
		        let screenBuilder = Instantiator<Screen> {
		            __safeDI_screenBuilder(onTap: $0)
		        }
		        return Root(screenBuilder: screenBuilder)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")
		#expect(output.mockFiles["Screen+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Screen {
		    static func mock(
		        onTap: @escaping OnTap
		    ) -> Screen {
		        return Screen(onTap: onTap)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Screen+SafeDIMock.swift"] ?? "")")
	}

