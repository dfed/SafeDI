	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_laysOutReceivesOfWrapperAsTheWalkWritesThem_whenMockWrapsInstanceItTakes() async throws {
		// `Root` receives `service`, which the mock takes, and binds a wrapper around it that `Banner`, built in place,
		// receives by name.
		let fixture = [
			"""
			@Instantiable(generateMock: true)
			public final class Root: Instantiable {
			    public init(service: Service, banner: Banner) {
			        self.service = service
			        self.banner = banner
			    }

			    @Received let service: Service
			    @Instantiated let banner: Banner
			}
			""",
			"""
			@Instantiable
			public final class Banner: Instantiable {
			    public init(service: LazilyInstantiated<Service>) {
			        self.service = service
			    }

			    @Received let service: LazilyInstantiated<Service>
			}
			""",
			"""
			public final class Service {}
			""",
		]
		let walkOutput = try await executeSafeDIToolTest(swiftFileContent: fixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		let (output, reports) = try await Self.layingOutMockRoots(filesToDelete: &filesToDelete) { filesToDelete in
			try await executeSafeDIToolTest(swiftFileContent: fixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}
		#expect(reports.filter(\.isMockRoot).map(\.isLaidOutFromNodeRecords) == [true])
		#expect(output.mockFiles == walkOutput.mockFiles, "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")\nThe walk writes \(walkOutput.mockFiles["Root+SafeDIMock.swift"] ?? "")")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_buildsTheWalksValues_whenEveryPlaceIsOverriddenAndNodesReadWrapperMockBindsInPlaceInFunctionAndThroughRename() async throws {
		let walkOutput = try await executeSafeDIToolTest(swiftFileContent: [], swiftFileContentByFilePath: Self.valueFixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		let (output, reports) = try await Self.layingOutMockRoots(filesToDelete: &filesToDelete) { filesToDelete in
			try await executeSafeDIToolTest(swiftFileContent: [], swiftFileContentByFilePath: Self.valueFixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}
		#expect(reports.filter(\.isMockRoot).map(\.isLaidOutFromNodeRecords) == [true])
		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            banner: ((LazilyInstantiated<Service>) -> Banner)? = nil,
		            panel: Panel.SafeDIMockConfiguration = .init()
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                banner: banner,
		                panel: panel
		            )
		        }

		        var banner: ((LazilyInstantiated<Service>) -> Banner)? { __safeDI_storage.banner }
		        var panel: Panel.SafeDIMockConfiguration { __safeDI_storage.panel }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                banner: ((LazilyInstantiated<Service>) -> Banner)?,
		                panel: Panel.SafeDIMockConfiguration
		            ) {
		                self.banner = banner
		                self.panel = panel
		            }

		            let banner: ((LazilyInstantiated<Service>) -> Banner)?
		            let panel: Panel.SafeDIMockConfiguration
		        }
		    }

		    static func mock(
		        service: Service,
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        let service_lazilyInstantiated = LazilyInstantiated<Service> { service }
		        let banner = if let safeDIBuilder = safeDIOverrides.banner { safeDIBuilder(service_lazilyInstantiated) } else { Banner(service: service_lazilyInstantiated) }
		        func __safeDI_panel(safeDIOverrides: Panel.SafeDIMockConfiguration) -> Panel {
		            #sourceLocation(file: "\(output.fixtures["Panel.swift"])", line: 9)
		            let renamedService: LazilyInstantiated<Service> = service_lazilyInstantiated
		            #sourceLocation()
		            let badge = if let safeDIBuilder = safeDIOverrides.badge { safeDIBuilder(service_lazilyInstantiated) } else { Badge(service: service_lazilyInstantiated) }
		            return if let safeDIBuilder = safeDIOverrides.safeDIBuilder { safeDIBuilder(renamedService, badge) } else { Panel(renamedService: renamedService, badge: badge) }
		        }
		        let panel: Panel = __safeDI_panel(safeDIOverrides: safeDIOverrides.panel)
		        return Root(service: service, banner: banner, panel: panel)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")
		let overridden = """
		Root.mock(service: marked(Service(), "service"), safeDIOverrides: .init(\
		banner: { marked(Banner(service: $0), "banner") }, \
		panel: .init(\
		badge: { marked(Badge(service: $0), "panel.badge") }, \
		{ marked(Panel(renamedService: $0, badge: $1), "panel") })\
		))
		"""
		let comparison = try await DifferentialValueOracle.compare(
			feature: DifferentialValuePath(fixtureFiles: Self.valueFixture, generatedFiles: #require(output.generatedFiles)),
			knownRight: DifferentialValuePath(fixtureFiles: Self.valueFixture, generatedFiles: #require(walkOutput.generatedFiles)),
			probes: [
				DifferentialValueProbe("Root.mock(service: Service())"),
				DifferentialValueProbe(name: "overridden root", expression: overridden),
			],
			filesToDelete: &filesToDelete,
		)
		// Nothing is compared where compile verification is off.
		guard let comparison else { return }
		#expect(comparison.differences.isEmpty, "\(comparison.report)")
		// Every override was read, and every wrapper wraps the instance the mock was passed.
		for marker in ["service", "banner", "panel.badge", "panel"] {
			#expect(comparison.featureDescription.contains("\"\(marker)\""), "No value is marked \(marker):\n\(comparison.featureDescription)")
		}
	}

