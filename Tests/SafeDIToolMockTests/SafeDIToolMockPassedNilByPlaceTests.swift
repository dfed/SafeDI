/// A type a mock builds in two places, where a required receive of a label pins the declaration one place's receive
/// only if available reads to another form and nothing pins the other's. Production passes the receive `nil` in the
/// pinned place and the declaration above in the other, so the mock decides each place on its own: it passes `nil`
/// where a required receive above the place, on its type, or beneath it pins the declaration, and hands the other place
/// what it binds.
struct SafeDIToolMockPassedNilByPlaceTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_passesNilOnlyToPinnedPlace_whenTypeIsBuiltBeneathRequiredReceiveInPromotedDependencysTreeAndInMockedTypesTree() async throws {
		// `Source`'s required `token: Instantiator<Token>` pins the declaration above `Source`, which production builds above
		// `Screen`, so production passes the `Leaf` beneath `Source` `nil`. Nothing pins the declaration above `Screen` but
		// `Reader`'s `token: Token`, which the `Leaf` beneath `Screen` reads. A mock that judged `Leaf` by its type handed both
		// `Leaf`s the `Token` it builds.
		let fixture = [
			"""
			@Instantiable(generateMock: true)
			public final class Screen: Instantiable {
			    public init(reader: Reader, leaf: Leaf, source: Source) {
			        self.reader = reader
			        self.leaf = leaf
			        self.source = source
			    }

			    @Instantiated let reader: Reader
			    @Instantiated let leaf: Leaf
			    @Received let source: Source
			}
			""",
			"""
			@Instantiable
			public final class Source: Instantiable {
			    public init(token: Instantiator<Token>, leaf: Leaf) {
			        self.token = token
			        self.leaf = leaf
			    }

			    @Received let token: Instantiator<Token>
			    @Instantiated let leaf: Leaf
			}
			""",
			"""
			@Instantiable
			public final class Reader: Instantiable {
			    public init(token: Token) {
			        self.token = token
			    }

			    @Received let token: Token
			}
			""",
			"""
			@Instantiable
			public final class Leaf: Instantiable {
			    public init(token: Token?) {
			        self.token = token
			    }

			    @Received(onlyIfAvailable: true) let token: Token?
			}
			""",
			"""
			@Instantiable
			public final class Token: Instantiable {
			    public init() {}
			}
			""",
			"""
			@Instantiable(isRoot: true)
			public final class Top: Instantiable {
			    public init(token: Instantiator<Token>, source: Source, middle: Middle) {
			        self.token = token
			        self.source = source
			        self.middle = middle
			    }

			    @Instantiated let token: Instantiator<Token>
			    @Instantiated let source: Source
			    @Instantiated let middle: Middle
			}
			""",
			"""
			@Instantiable
			public final class Middle: Instantiable {
			    public init(token: Token, screen: Screen) {
			        self.token = token
			        self.screen = screen
			    }

			    @Instantiated let token: Token
			    @Instantiated let screen: Screen
			}
			""",
		]
