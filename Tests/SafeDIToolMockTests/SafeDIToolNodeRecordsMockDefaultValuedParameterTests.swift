				DifferentialValueProbe("Root.mock()"),
				DifferentialValueProbe("Root.mock().tileBuilder.instantiate(\"first\")"),
				DifferentialValueProbe("Root.mock().panel.tileBuilder.instantiate(\"second\")"),
				DifferentialValueProbe(name: "fields overridden", expression: fieldsOverridden),
				DifferentialValueProbe(name: "fields overridden, tile", expression: "\(fieldsOverridden).tileBuilder.instantiate(\"first\")"),
				DifferentialValueProbe(name: "fields overridden, panel's tile", expression: "\(fieldsOverridden).panel.tileBuilder.instantiate(\"second\")"),
				DifferentialValueProbe(name: "builders overridden", expression: buildersOverridden),
				DifferentialValueProbe(name: "builders overridden, tile", expression: "\(buildersOverridden).tileBuilder.instantiate(\"first\")"),
				DifferentialValueProbe(name: "builders overridden, panel's tile", expression: "\(buildersOverridden).panel.tileBuilder.instantiate(\"second\")"),
			],
			filesToDelete: &filesToDelete,
		)
		// Nothing is compared where compile verification is off.
		guard let comparison else { return }
		#expect(comparison.differences.isEmpty, "\(comparison.report)")
		// Every hand-written mock was called and every builder read: each marks the value it built.
		for marker in ["mocked", "leaf", "panel.leaf", "panel.tileBuilder", "panel", "tileBuilder", "sign", "counter"] {
			#expect(comparison.featureDescription.contains("\"\(marker)\""), "No value is marked \(marker):\n\(comparison.featureDescription)")
		}
		// Every field was read, with no builder and handed to one: each value is one no default gives.
		for value in [11, 12, 13, 14, 15, 121, 122, 123, 124, 125] {
			#expect(comparison.featureDescription.contains(" \(value)\n"), "No value is \(value):\n\(comparison.featureDescription)")
		}
	}

