import Foundation
import Testing
@testable import SafeDICore
@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

/// The family of a mock root's variants (`TypeFactsGraph.familyOfCall(opening:callerFamily:)`): a body built inside a
/// `@Sendable` function reads its override from a local bound before that function, and a body built in plain code reads
/// its parent's configuration, so a mock keys a type reached both ways as two variants.
struct SafeDIToolTypeFactsFamilyTests: ~Copyable {
	// MARK: Initialization

	init() {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_keysVariantPerFamily_whenMockBuildsTypeInPlainFunctionAndInSendableFunction() async throws {
		// `leaf` is one node with two parents: `Plain`, built in a plain `Instantiator`'s function, and `Shared`, built in a
		// `SendableInstantiator`'s `@Sendable` function, where the mock reads `leaf`'s override from the local bound before it.
		let (output, report) = try await mockOutputAndReport(of: Self.twoFamiliesFixture)

		// The mock reads `leaf`'s override from `safeDIOverrides.plainBuilder.leaf` in the plain function and from
		// `__safeDI_sharedBuilder__overrides.leaf` in the `@Sendable` one.
		let leaf = try #require(report.nodes.firstIndex { $0.description.hasPrefix("Leaf as leaf") }, "\(report.world)")
		#expect(variantFamilies(ofNode: leaf, in: report) == ["plain", "sendable"], "\(report.world)")
		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            plainBuilder: Plain.SafeDIMockConfiguration = .init(),
		            sharedBuilder: Shared.SafeDIMockConfiguration = .init()
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                plainBuilder: plainBuilder,
		                sharedBuilder: sharedBuilder
		            )
		        }

		        var plainBuilder: Plain.SafeDIMockConfiguration { __safeDI_storage.plainBuilder }
		        var sharedBuilder: Shared.SafeDIMockConfiguration { __safeDI_storage.sharedBuilder }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                plainBuilder: Plain.SafeDIMockConfiguration,
		                sharedBuilder: Shared.SafeDIMockConfiguration
		            ) {
		                self.plainBuilder = plainBuilder
		                self.sharedBuilder = sharedBuilder
		            }

		            let plainBuilder: Plain.SafeDIMockConfiguration
		            let sharedBuilder: Shared.SafeDIMockConfiguration
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        func __safeDI_plainBuilder() -> Plain {
		            let leaf = if let safeDIBuilder = safeDIOverrides.plainBuilder.leaf { safeDIBuilder() } else { Leaf() }
		            return if let safeDIBuilder = safeDIOverrides.plainBuilder.safeDIBuilder { safeDIBuilder(leaf) } else { Plain(leaf: leaf) }
		        }
		        let plainBuilder = Instantiator<Plain>(__safeDI_plainBuilder)
		        let __safeDI_sharedBuilder__overrides = safeDIOverrides.sharedBuilder
		        @Sendable nonisolated func __safeDI_sharedBuilder() -> Shared {
		            let leaf = if let safeDIBuilder = __safeDI_sharedBuilder__overrides.leaf { safeDIBuilder() } else { Leaf() }
		            return if let safeDIBuilder = __safeDI_sharedBuilder__overrides.safeDIBuilder { safeDIBuilder(leaf) } else { Shared(leaf: leaf) }
		        }
		        let sharedBuilder = SendableInstantiator<Shared>(__safeDI_sharedBuilder)
		        return Root(plainBuilder: plainBuilder, sharedBuilder: sharedBuilder)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_keysEveryVariantBeneathSendableFunctionSendable_whenMockBuildsChildInsideSendableFunction() async throws {
		// Each body beneath the edge that opens `sharedBuilder`'s `@Sendable` function is in the `@Sendable` family, and each
		// body above it is plain.
		let (_, report) = try await mockOutputAndReport(of: Self.twoFamiliesFixture)

		for (index, node) in report.nodes.enumerated() {
			let expected: [String] = if node.description.hasPrefix("Leaf as leaf") {
				["plain", "sendable"]
			} else if node.description.hasPrefix("Shared as sharedBuilder") {
				["sendable"]
			} else {
				["plain"]
			}
			#expect(variantFamilies(ofNode: index, in: report) == expected, "\(node.description): \(report.world)")
		}
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_keysFillsVariantSendable_whenPublicMockFillsPlaceItBuildsInsideSendableFunction() async throws {
		// `Detail`'s public mock builds `api` inside `panelBuilder`'s `@Sendable` function, so `Root`'s mock fills the place in
		// that function: the fill's edge opens it (`TypeFactsFunctionOpened.otherSendableFunction`).
		let modules = [
			ModuleFixture(name: "Feature", packageName: "Shop", swiftFileContent: [
				"public protocol Api: Sendable {}",
				seamFixtureType(named: "Panel", isFinalClass: true, declarations: ["@Instantiated public let api: any Api"], conformances: ", Sendable"),
				seamFixtureType(named: "Detail", isFinalClass: true, declarations: ["@Forwarded public let id: Int", "@Instantiated public let panelBuilder: SendableInstantiator<Panel>"])
					.replacingOccurrences(of: "@Instantiable\n", with: "@Instantiable(generateMock: .public)\n")
					.replacingOccurrences(of: "public init(", with: "init("),
			]),
			ModuleFixture(name: "App", packageName: "Other", swiftFileContent: [
				seamFixtureType(named: "Live", isFinalClass: true, declarations: ["@Received public let id: Int"], conformances: ", Api")
					.replacingOccurrences(of: "@Instantiable\n", with: "@Instantiable(fulfillingAdditionalTypes: [Api.self])\n"),
				seamFixtureType(named: "Root", isFinalClass: true, declarations: ["@Instantiated public let detailBuilder: Instantiator<Detail>"])
					.replacingOccurrences(of: "@Instantiable\n", with: "@Instantiable(generateMock: true)\n"),
			].map { "import Feature\n\n" + $0 }, dependencies: ["Feature"]),
		]
		let report = try await mockReport { filesToDelete in
			_ = try await executeSafeDIToolMultiModuleTest(modules: modules, integration: .moduleInfo, filesToDelete: &filesToDelete)
		}

		let fills = report.nodes.indices.flatMap { index in
			zip(report.nodes[index].edges, report.nodes[index].edgeFacts).filter(\.1.isFill).map { (target: $0.0, opens: $0.1.opens) }
		}
		#expect(fills.map(\.opens) == ["otherSendableFunction"], "\(report.world)")
		for fill in fills {
			#expect(variantFamilies(ofNode: fill.target, in: report) == ["sendable"], "\(report.world)")
		}
	}

	// MARK: Private

	private var filesToDelete: [URL]

	/// `Root` builds `plainBuilder: Instantiator<Plain>` and `sharedBuilder: SendableInstantiator<Shared>`, and both
	/// `Plain` and `Shared` build `leaf: Leaf`.
	private static let twoFamiliesFixture = [
		seamFixtureType(named: "Root", isFinalClass: true, declarations: ["@Instantiated let plainBuilder: Instantiator<Plain>", "@Instantiated let sharedBuilder: SendableInstantiator<Shared>"])
			.replacingOccurrences(of: "@Instantiable\n", with: "@Instantiable(generateMock: true)\n"),
		seamFixtureType(named: "Plain", isFinalClass: true, declarations: ["@Instantiated let leaf: Leaf"]),
		seamFixtureType(named: "Shared", isFinalClass: true, declarations: ["@Instantiated let leaf: Leaf"], conformances: ", Sendable"),
		seamFixtureType(named: "Leaf", isFinalClass: true, declarations: [], conformances: ", Sendable"),
	]

	/// The mock output of `types` and the type facts report of `Root`'s mock world.
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	private func mockOutputAndReport(of types: [String]) async throws -> (output: TestOutput, report: TypeFactsReport) {
		var output: TestOutput?
		let report = try await mockReport { filesToDelete in
			output = try await executeSafeDIToolTest(swiftFileContent: types, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}
		return try (#require(output), report)
	}

	/// The type facts report of `Root`'s mock world, which `run` generates.
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	private func mockReport(_ run: (inout [URL]) async throws -> Void) async throws -> TypeFactsReport {
		let (stream, continuation) = AsyncStream.makeStream(of: TypeFactsReport.self)
		try await ConstructionMemoOracle.$observer.withValue({ _, _, report in continuation.yield(report) }) {
			var filesToDelete = [URL]()
			defer {
				for file in filesToDelete {
					try? FileManager.default.removeItem(at: file)
				}
			}
			try await run(&filesToDelete)
		}
		continuation.finish()
		var reports = [TypeFactsReport]()
		for await report in stream where report.root == "Root" && report.forMockGeneration {
			reports.append(report)
		}
		return try #require(reports.last)
	}

	/// The family of each variant of the node at `node`, in variant order.
	private func variantFamilies(ofNode node: Int, in report: TypeFactsReport) -> [String] {
		report.variantNodes.indices.filter { report.variantNodes[$0] == node }.map { report.variantFamilies[$0] }
	}
}
