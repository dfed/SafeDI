	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_keysEveryVariantBeneathSendableFunctionSendable_whenMockBuildsChildInsideSendableFunction() async throws {
		// Each body beneath the edge that opens `sharedBuilder`'s `@Sendable` function is in the `@Sendable` family, and each
		// body above it is plain.
		let (_, report) = try await mockOutputAndReport(of: Self.twoFamiliesFixture)

		for (index, node) in report.nodes.enumerated() {
			let expected: [String] = if node.description.hasPrefix("Leaf as leaf") {
				["plain", "sendable"]
			} else if node.description.hasPrefix("Shared as sharedBuilder") {
				["sendable"]
			} else {
				["plain"]
			}
			#expect(variantFamilies(ofNode: index, in: report) == expected, "\(node.description): \(report.world)")
		}
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_keysFillsVariantSendable_whenPublicMockFillsPlaceItBuildsInsideSendableFunction() async throws {
		// `Detail`'s public mock builds `api` inside `panelBuilder`'s `@Sendable` function, so `Root`'s mock fills the place in
		// that function: the fill's edge opens it (`TypeFactsFunctionOpened.otherSendableFunction`).
		let modules = [
			ModuleFixture(name: "Feature", packageName: "Shop", swiftFileContent: [
				"public protocol Api: Sendable {}",
				seamFixtureType(named: "Panel", isFinalClass: true, declarations: ["@Instantiated public let api: any Api"], conformances: ", Sendable"),
				seamFixtureType(named: "Detail", isFinalClass: true, declarations: ["@Forwarded public let id: Int", "@Instantiated public let panelBuilder: SendableInstantiator<Panel>"])
					.replacingOccurrences(of: "@Instantiable\n", with: "@Instantiable(generateMock: .public)\n")
					.replacingOccurrences(of: "public init(", with: "init("),
			]),
			ModuleFixture(name: "App", packageName: "Other", swiftFileContent: [
				seamFixtureType(named: "Live", isFinalClass: true, declarations: ["@Received public let id: Int"], conformances: ", Api")
					.replacingOccurrences(of: "@Instantiable\n", with: "@Instantiable(fulfillingAdditionalTypes: [Api.self])\n"),
				seamFixtureType(named: "Root", isFinalClass: true, declarations: ["@Instantiated public let detailBuilder: Instantiator<Detail>"])
					.replacingOccurrences(of: "@Instantiable\n", with: "@Instantiable(generateMock: true)\n"),
			].map { "import Feature\n\n" + $0 }, dependencies: ["Feature"]),
		]
		let report = try await mockReport { filesToDelete in
			_ = try await executeSafeDIToolMultiModuleTest(modules: modules, integration: .moduleInfo, filesToDelete: &filesToDelete)
		}

		let fills = report.nodes.indices.flatMap { index in
			zip(report.nodes[index].edges, report.nodes[index].edgeFacts).filter(\.1.isFill).map { (target: $0.0, opens: $0.1.opens) }
		}
		#expect(fills.map(\.opens) == ["otherSendableFunction"], "\(report.world)")
		for fill in fills {
			#expect(variantFamilies(ofNode: fill.target, in: report) == ["sendable"], "\(report.world)")
		}
	}

