	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_erasesConstructionInsideWrappersFunction_whenWrapperIsErasedToConcreteExistential() async throws {
		// The override returns the erased type, so each function erases the construction it falls back to, as the walk
		// writes it; the configured wrapper's function is handed its overrides (difference 1 of the mock world).
		let fixture = [
			"""
			public protocol Filter {}
			public final class AnyFilter: Filter {
			    public init(_ filter: some Filter) {}
			}
			""",
			"""
			@Instantiable(generateMock: true)
			public final class Root: Instantiable {
			    public init(filter: LazilyInstantiated<AnyFilter>, rules: LazilyInstantiated<AnyFilter>) {
			        self.filter = filter
			        self.rules = rules
			    }

			    @Instantiated(fulfilledByType: "AppFilter", erasedToConcreteExistential: true) let filter: LazilyInstantiated<AnyFilter>
			    @Instantiated(fulfilledByType: "RuleFilter", erasedToConcreteExistential: true) let rules: LazilyInstantiated<AnyFilter>
			}
			""",
			"""
			@Instantiable
			public final class AppFilter: Filter, Instantiable {
			    public init() {}
			}
			""",
			"""
			@Instantiable
			public final class RuleFilter: Filter, Instantiable {
			    public init(ruleSet: RuleSet) {
			        self.ruleSet = ruleSet
			    }

			    @Instantiated let ruleSet: RuleSet
			}
			""",
			"""
			@Instantiable
			public final class RuleSet: Instantiable {
			    public init() {}
			}
			""",
		]
		let (output, reports) = try await Self.layingOutMockRoots(filesToDelete: &filesToDelete) { filesToDelete in
			try await executeSafeDIToolTest(swiftFileContent: fixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}

		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            filter: (() -> AnyFilter)? = nil,
