	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_buildsTheWalksValues_whenEveryPlaceOfTreeOfWrappersIsOverridden() async throws {
		let walkOutput = try await executeSafeDIToolTest(swiftFileContent: [], swiftFileContentByFilePath: Self.valueFixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		let (output, reports) = try await Self.layingOutMockRoots(filesToDelete: &filesToDelete) { filesToDelete in
			try await executeSafeDIToolTest(swiftFileContent: [], swiftFileContentByFilePath: Self.valueFixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}
		#expect(reports.filter(\.isMockRoot).map(\.isLaidOutFromNodeRecords) == [true])
		// The two write other text, so the comparison is of two programs.
		#expect(output.mockFiles["Root+SafeDIMock.swift"] != walkOutput.mockFiles["Root+SafeDIMock.swift"])
		let overridden = """
		Root.mock(safeDIOverrides: .init(\
		session: { marked(Session(), "session") }, \
		reader: { marked(Reader(session: $0), "reader") }, \
		page: .init(\
		logger: { marked(Logger(), "page.logger") }, \
		detail: .init(leaf: { marked(Leaf(logger: $0, session: $1), "page.detail.leaf") }, { marked(Detail(leaf: $0), "page.detail") }), \
		{ marked(Page(logger: $0, detail: $1), "page") }), \
		panelBuilder: .init(cache: { marked(Cache(session: $0), "panelBuilder.cache") }, { marked(Panel(cache: $0), "panelBuilder") }), \
		primary: { marked(Store(), "primary") }, \
		secondary: { marked(Store(), "secondary") }, \
		rules: .init(ruleSet: { marked(Store(), "rules.ruleSet") }, { marked(RuleFilter(ruleSet: $0), "rules") })\
		))
		"""
		// Each probe reads every wrapper's instance, in an order that differs from the order the tree declares them, and
		// whether two reads of one label see one instance.
		func reads(of root: String) -> String {
			"""
			{ let root = \(root); let panel = root.panelBuilder.instantiate(); \
			return [root.page.detail.instance.leaf.marker, root.page.detail.instance.leaf.logger.marker, root.page.logger.instance.marker, \
			root.page.detail.instance.marker, root.page.marker, panel.cache.instance.marker, panel.cache.instance.session.marker, panel.marker, \
			root.reader.session.instance.marker, root.session.instance.marker, root.reader.marker, root.secondary.instance.marker, root.primary.instance.marker, root.rules.instance.marker, (root.rules.instance.rules as! RuleFilter).ruleSet.marker, \
			root.page.detail.instance.leaf.logger === root.page.logger.instance ? "one logger" : "two loggers", \
			root.page.detail.instance.leaf.session === root.session.instance ? "one session" : "two sessions", \
			panel.cache.instance.session === root.session.instance ? "one session" : "two sessions", \
			root.primary.instance === root.secondary.instance ? "one store" : "two stores"] }()
			"""
		}
		let comparison = try await DifferentialValueOracle.compare(
			feature: DifferentialValuePath(fixtureFiles: Self.valueFixture, generatedFiles: #require(output.generatedFiles)),
			knownRight: DifferentialValuePath(fixtureFiles: Self.valueFixture, generatedFiles: #require(walkOutput.generatedFiles)),
			probes: [
				DifferentialValueProbe(name: "built root", expression: reads(of: "Root.mock()")),
				DifferentialValueProbe(name: "overridden root", expression: reads(of: overridden)),
			],
			filesToDelete: &filesToDelete,
		)
		// Nothing is compared where compile verification is off.
		guard let comparison else { return }
		#expect(comparison.differences.isEmpty, "\(comparison.report)")
		// Every override was read: each marks the value its closure built.
		for marker in ["session", "reader", "page.logger", "page.detail.leaf", "page.detail", "page", "panelBuilder.cache", "panelBuilder", "primary", "secondary", "rules.ruleSet", "rules"] {
			#expect(comparison.featureDescription.contains("\"\(marker)\""), "No value is marked \(marker):\n\(comparison.featureDescription)")
		}
	}

