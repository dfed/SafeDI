import Foundation
import SafeDICore
import Testing
@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

/// A calling mock promotes a dependency a called public mock builds when passed `nil` only where it can construct the
/// dependency’s whole tree, the fills of the public mock calls in that tree included, in a build that compiles the
/// generated mocks. `Screen`, in `App`, calls `Cache`’s public mock, which receives `widget`; `Widget` calls `Panel`’s public
/// mock, whose place `App` fills with `MidService`, which instantiates `any Clock`, which only `Meter`, `package` in another
/// package, fulfills. So `App` passes its override, `nil` by default, and `Cache`’s mock builds `widget` in `Mid`, which can construct `Meter`.
struct SafeDIToolCallingMockBuiltWhenNilPromotionTests: ~Copyable {
	// MARK: Initialization

	init() {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try? FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_passesNilForDependencyCalledMockBuildsWhenNil_whenFillOfPublicMockCallInItsTreeConstructsTypeCallingModuleCannotReach() async throws {
		let modules = [
			ModuleFixture(name: "Core", packageName: "pkg", swiftFileContentByFilePath: ["CoreTypes.swift": """
			import SafeDI

			public protocol Clock: AnyObject {}

			@Instantiable(fulfillingAdditionalTypes: [Clock.self])
			package final class Meter: Clock, Instantiable {
			    package init() {}
			}
			"""]),
			ModuleFixture(name: "Up", packageName: "Up", swiftFileContentByFilePath: ["UpTypes.swift": """
			import SafeDI

			public protocol Service: AnyObject {}

			@Instantiable(generateMock: .public)
			public final class Panel: Instantiable {
			    init(service: any Service) { self.service = service }
			    @Instantiated public let service: any Service
			}
			"""]),
			ModuleFixture(name: "Mid", packageName: "pkg", swiftFileContentByFilePath: ["MidTypes.swift": """
			import Core
			import SafeDI
			import Up

			@Instantiable(fulfillingAdditionalTypes: [Service.self])
			public final class MidService: Service, Instantiable {
			    public init(clock: any Clock) { self.clock = clock }
			    @Instantiated let clock: any Clock
			}

			@Instantiable
			public final class Widget: Instantiable {
			    public init(panel: Panel) { self.panel = panel }
			    @Instantiated let panel: Panel
			}

			@Instantiable
			package struct TokenCache: Instantiable {
			    package init() {}
			}

			@Instantiable(generateMock: .public)
			public struct Cache: Instantiable {
			    package init(widget: Widget, tokenCache: TokenCache) {
			        self.widget = widget
			        self.tokenCache = tokenCache
			    }

			    @Received let widget: Widget
			    @Instantiated let tokenCache: TokenCache
			}
			"""], dependencies: ["Core", "Up"]),
			ModuleFixture(name: "App", packageName: "App", swiftFileContentByFilePath: ["AppTypes.swift": """
			import Mid
			import SafeDI

			@Instantiable(generateMock: true)
			public final class Screen: Instantiable {
			    public init(cache: Cache) { self.cache = cache }
			    @Instantiated let cache: Cache
			}
			"""], dependencies: ["Core", "Up", "Mid"], activeCompilationConditions: ["DEBUG"]),
		]
		let output = try await executeSafeDIToolMultiModuleTest(modules: modules, integration: .moduleInfo, filesToDelete: &filesToDelete)

		#expect(output.modules["App"]?.generatedFiles == ["App.swift": """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if canImport(Core)
		import Core
		#endif
		#if canImport(Mid)
		import Mid
		#endif
		#if canImport(SafeDI)
		import SafeDI
		#endif
		#if canImport(Up)
		import Up
		#endif

		#if DEBUG
		extension Screen {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            cache: Cache.SafeDIOverrides = .init(),
		            widget: Widget? = nil
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                cache: cache
		            )
		            self.widget = widget
		        }

		        var cache: Cache.SafeDIOverrides { __safeDI_storage.cache }
		        let widget: Widget?

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                cache: Cache.SafeDIOverrides
		            ) {
		                self.cache = cache
		            }

		            let cache: Cache.SafeDIOverrides
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Screen {
		        let widget: Widget? = safeDIOverrides.widget
		        _ = Cache.__safeDI_Cache_mock_C2F35604B39B78BB.self // If this line does not compile, compile the code SafeDI generates for module Mid into Mid: under Bazel, add Mid’s safedi_compile rule to the srcs of its swift_library; under Tuist, add SafeDI.generatedSource to the sources of its target; in a custom build, compile the file its SafeDITool generate run writes.
		        let cache = Cache.__safeDI_mock(widget: widget, safeDIOverrides: safeDIOverrides.cache)
		        return Screen(cache: cache)
		    }
		}
		#endif
		"""])
	}

	// MARK: Private

	private var filesToDelete: [URL]
}
