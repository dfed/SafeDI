/// An internal mock root whose every node its type's initializer or hand-written mock builds, laid out from the node
/// records of its world (`NodeRecords+MockConstruction.swift`): each node reads its override before it calls its
/// initializer or mock, a function is handed the overrides of the node it builds, or captures `mock()`'s own where
/// only the root's body calls it and no child reads them, and the values equal those the mock's walk builds, with an
/// override at every place.
struct SafeDIToolNodeRecordsMockRootTests: ~Copyable {
	// MARK: Initialization

	init() {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_laysOutNodesAsTheWalkWritesThem_whenEveryNodeIsBuiltInPlace() async throws {
		let fixture = [
			"""
			@Instantiable(generateMock: true)
			public struct Root: Instantiable {
			    public init(shared: Shared, cache: Cache) {
			        self.shared = shared
			        self.cache = cache
			    }

			    @Instantiated let shared: Shared
			    @Instantiated let cache: Cache
			}
			""",
			"""
			@Instantiable
			public struct Shared: Instantiable {
			    public init() {}
			}
			""",
			"""
			@Instantiable
			public struct Cache: Instantiable {
			    public init(shared: Shared) {
			        self.shared = shared
			    }

			    @Received let shared: Shared
			}
			""",
		]
		let walkOutput = try await executeSafeDIToolTest(swiftFileContent: fixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		let (output, reports) = try await Self.layingOutMockRoots(filesToDelete: &filesToDelete) { filesToDelete in
			try await executeSafeDIToolTest(swiftFileContent: fixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}
		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            shared: (() -> Shared)? = nil,
		            cache: ((Shared) -> Cache)? = nil
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                shared: shared,
		                cache: cache
		            )
		        }

		        var shared: (() -> Shared)? { __safeDI_storage.shared }
		        var cache: ((Shared) -> Cache)? { __safeDI_storage.cache }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                shared: (() -> Shared)?,
		                cache: ((Shared) -> Cache)?
		            ) {
		                self.shared = shared
		                self.cache = cache
		            }

		            let shared: (() -> Shared)?
		            let cache: ((Shared) -> Cache)?
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        let shared = if let safeDIBuilder = safeDIOverrides.shared { safeDIBuilder() } else { Shared() }
		        let cache = if let safeDIBuilder = safeDIOverrides.cache { safeDIBuilder(shared) } else { Cache(shared: shared) }
