		}
		let mock = try #require(output.mockFiles["Root+SafeDIMock.swift"])
		#expect(mock == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            left: Left.SafeDIMockConfiguration = .init(),
		            right: Right.SafeDIMockConfiguration = .init()
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                left: left,
		                right: right
		            )
		        }

		        var left: Left.SafeDIMockConfiguration { __safeDI_storage.left }
		        var right: Right.SafeDIMockConfiguration { __safeDI_storage.right }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                left: Left.SafeDIMockConfiguration,
		                right: Right.SafeDIMockConfiguration
		            ) {
		                self.left = left
		                self.right = right
		            }

		            let left: Left.SafeDIMockConfiguration
		            let right: Right.SafeDIMockConfiguration
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        func __safeDI_middle(safeDIOverrides: Middle.SafeDIMockConfiguration) -> Middle {
		            let leaf = if let safeDIBuilder = safeDIOverrides.leaf { safeDIBuilder() } else { Leaf() }
		            return if let safeDIBuilder = safeDIOverrides.safeDIBuilder { safeDIBuilder(leaf) } else { Middle(leaf: leaf) }
		        }
		        func __safeDI_left(safeDIOverrides: Left.SafeDIMockConfiguration) -> Left {
