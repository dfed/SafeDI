	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_importsModuleOfFlatParameterDefault_whenRootIsLeftUnbuilt() async throws {
		let modules = [
			ModuleFixture(name: "Feature", packageName: "Shop", swiftFileContentByFilePath: ["Service.swift": "public protocol Service {}\n"]),
			ModuleFixture(name: "TestSupport", packageName: "Shop", swiftFileContentByFilePath: ["FakeService.swift": """
			import Feature

			@Instantiable(fulfillingAdditionalTypes: [Service.self], mockOnly: true)
			public final class FakeService: Service {
			    public static func mock() -> FakeService { FakeService() }
			}

			"""], dependencies: ["Feature"]),
			ModuleFixture(name: "App", packageName: "Shop", swiftFileContentByFilePath: ["Screen.swift": """
			import Feature
			import TestSupport
			@Instantiable(generateMock: true)
			public final class Screen: Instantiable {
			    public init(service: Service) {
			        self.service = service
			    }
			    @Forwarded let service: Service
			}

			"""], dependencies: ["Feature", "TestSupport"]),
		]
		func generate(leavesTreesUnbuilt: Bool) async throws -> ([String: String], [MockRootTreeSkipReport]) {
			try await observingSkipReports(leavesTreesUnbuilt: leavesTreesUnbuilt) { filesToDelete in
				try await executeSafeDIToolMultiModuleTest(modules: modules, integration: .moduleInfo, filesToDelete: &filesToDelete).modules["App"]?.generatedFiles ?? [:]
			}
		}
		let (generatedFiles, reports) = try await generate(leavesTreesUnbuilt: true)
		#expect(reports == [MockRootTreeSkipReport(root: "Screen", outcome: MockRootTreeSkipReport.leftUnbuilt)])
		#expect(generatedFiles == ["App.swift": """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if canImport(Feature)
		import Feature
		#endif
		#if canImport(TestSupport)
		import TestSupport
		#endif

		#if DEBUG
		extension Screen {
		    static func mock(
		        service: Service = FakeService.mock()
		    ) -> Screen {
		        return Screen(service: service)
		    }
		}
		#endif
		"""], "Unexpected output \(generatedFiles)")
		#expect(try await generatedFiles == generate(leavesTreesUnbuilt: false).0)
	}

