	// MARK: Private

	private var filesToDelete: [URL]

	/// Expects the run over `fixture` to keep `root`'s tree with `outcome`, every other root's report aside, and to generate
	/// the same mocks as a run that leaves no tree unbuilt.
	private mutating func expectTreeKept(of root: String, outcome: String, in fixture: [String]) async throws {
		let (output, reports) = try await layingOutMockRoots(of: fixture)
		#expect(reports.filter { $0.root == root } == [MockRootTreeSkipReport(root: root, outcome: outcome)])
		let (outputWithTrees, _) = try await layingOutMockRoots(of: fixture, leavesTreesUnbuilt: false)
		#expect(output.mockFiles == outputWithTrees.mockFiles)
	}

	/// The output of a run over `fixture` with every internal mock root node records accept laid out from them, and the
	/// report of each mock root, in the order they arrive.
	private mutating func layingOutMockRoots(of fixture: [String], leavesTreesUnbuilt: Bool = true) async throws -> (TestOutput, [MockRootTreeSkipReport]) {
		try await observingSkipReports(leavesTreesUnbuilt: leavesTreesUnbuilt) { filesToDelete in
			try await executeSafeDIToolTest(swiftFileContent: fixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}
	}

	private mutating func observingSkipReports<Output>(leavesTreesUnbuilt: Bool, _ body: (inout [URL]) async throws -> Output) async throws -> (Output, [MockRootTreeSkipReport]) {
		let (stream, continuation) = AsyncStream.makeStream(of: MockRootTreeSkipReport.self)
		let output = try await NodeRecordsObservation.$laysOutMockRoots.withValue(true) {
			try await NodeRecordsObservation.$observer.withValue({ _ in }) {
