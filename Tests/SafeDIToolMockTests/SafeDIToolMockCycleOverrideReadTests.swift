/// Spike evidence (N2), not for merge. The first four tests pin today's mock for each shape in which a type is built
/// again through a cycle. Today a type the closing call re-enters reads the entries of its first place, but the type
/// that closing call reopens reads none: lap 2's `Step` reads lap 1's overrides and lap 2's `Screen` does not. A lazy
/// cycle already reads lap 1's overrides on every lap. Option A (no overrides on later laps) would move the reads each
/// pinned test names; the maintainer chose B.
///
/// The last three are cells for decision 2-3-1-MOCK-CYCLE-LAP-OVERRIDES (option B): a type a cycle builds again reads
/// lap 1's overrides on every lap, so a mock's overrides hold however many times a test goes around the loop. They
/// fail until the generator implements it, which `withKnownIssue` records; the lazy cycle needs no cell, since its
/// pinned output already is B's.
struct SafeDIToolMockCycleOverrideReadTests: ~Copyable {
	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

