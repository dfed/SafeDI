/// An internal mock root whose nodes include ones built in a `@Sendable` function of their own, laid out from the node
/// records of its world (`NodeRecords+MockSendable.swift`): each such function's override is read into a local before
/// it, which the function captures where the root builds it and is handed elsewhere, and the values equal those the
/// mock's walk builds, with an override at every place.
struct SafeDIToolNodeRecordsMockSendableTests: ~Copyable {
	// MARK: Initialization

	init() {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

