	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_bindsEachOverrideBeforeItsSendableFunctionAsTheWalkWritesIt_whenRootBuildsSendableBuilders() async throws {
		let walkOutput = try await executeSafeDIToolTest(swiftFileContent: [], swiftFileContentByFilePath: Self.rootFixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		let (output, reports) = try await Self.layingOutMockRoots(filesToDelete: &filesToDelete) { filesToDelete in
			try await executeSafeDIToolTest(swiftFileContent: [], swiftFileContentByFilePath: Self.rootFixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}
		#expect(reports.filter(\.isMockRoot).map(\.isLaidOutFromNodeRecords) == [true])
		#expect(output.mockFiles["Root+SafeDIMock.swift"] == walkOutput.mockFiles["Root+SafeDIMock.swift"])
		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            shared: (() -> Shared)? = nil,
		            childBuilder: Child.SafeDIMockConfiguration = .init(),
		            namedBuilder: (@Sendable (String) -> Named)? = nil,
		            anyBuilder: (@Sendable () -> LeafProtocol)? = nil
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                shared: shared,
		                childBuilder: childBuilder,
		                namedBuilder: namedBuilder,
		                anyBuilder: anyBuilder
		            )
		        }

		        var shared: (() -> Shared)? { __safeDI_storage.shared }
		        var childBuilder: Child.SafeDIMockConfiguration { __safeDI_storage.childBuilder }
		        var namedBuilder: (@Sendable (String) -> Named)? { __safeDI_storage.namedBuilder }
		        var anyBuilder: (@Sendable () -> LeafProtocol)? { __safeDI_storage.anyBuilder }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                shared: (() -> Shared)?,
		                childBuilder: Child.SafeDIMockConfiguration,
		                namedBuilder: (@Sendable (String) -> Named)?,
		                anyBuilder: (@Sendable () -> LeafProtocol)?
		            ) {
		                self.shared = shared
		                self.childBuilder = childBuilder
		                self.namedBuilder = namedBuilder
		                self.anyBuilder = anyBuilder
		            }

		            let shared: (() -> Shared)?
		            let childBuilder: Child.SafeDIMockConfiguration
		            let namedBuilder: (@Sendable (String) -> Named)?
		            let anyBuilder: (@Sendable () -> LeafProtocol)?
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        let shared = if let safeDIBuilder = safeDIOverrides.shared { safeDIBuilder() } else { Shared() }
		        let __safeDI_childBuilder__overrides = safeDIOverrides.childBuilder
		        @Sendable nonisolated func __safeDI_childBuilder() -> Child {
		            let leaf = if let safeDIBuilder = __safeDI_childBuilder__overrides.leaf { safeDIBuilder() } else { Leaf() }
		            return if let safeDIBuilder = __safeDI_childBuilder__overrides.safeDIBuilder { safeDIBuilder(shared, leaf) } else { Child(shared: shared, leaf: leaf) }
		        }
		        let childBuilder = SendableInstantiator<Child>(__safeDI_childBuilder)
		        let __safeDI_namedBuilder__safeDIBuilder = safeDIOverrides.namedBuilder
		        @Sendable nonisolated func __safeDI_namedBuilder(name: String) -> Named {
		            if let safeDIBuilder = __safeDI_namedBuilder__safeDIBuilder { safeDIBuilder(name) } else { Named(name: name) }
		        }
		        let namedBuilder = SendableInstantiator<Named> {
		            __safeDI_namedBuilder(name: $0)
		        }
		        let __safeDI_anyBuilder__safeDIBuilder = safeDIOverrides.anyBuilder
		        @Sendable nonisolated func __safeDI_anyBuilder() -> LeafProtocol {
		            if let safeDIBuilder = __safeDI_anyBuilder__safeDIBuilder { safeDIBuilder() } else { Leaf() }
		        }
		        let anyBuilder = SendableErasedInstantiator<(), LeafProtocol>(__safeDI_anyBuilder)
		        return Root(shared: shared, childBuilder: childBuilder, namedBuilder: namedBuilder, anyBuilder: anyBuilder)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")
	}

