import Foundation
import SafeDICore
import Testing
@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

/// A value a mock hands a builder closure, takes as a public mock's parameter, or stores behind a `@Sendable`

/// A mock root whose body the production emitter writes through its override hook and naming policy, byte for byte as
/// the mock's own walk wrote it.
struct SafeDIToolMockBodyRoutingTests: ~Copyable {
	// MARK: Initialization

	init() {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_writesBodyThroughProductionEmitter_whenPromotedSiblingsAreNamedApartAndMockedTypeAliasesOne() async throws {
		let (routings, continuation) = AsyncStream.makeStream(of: Bool.self)
		let output = try await MockBodyRouting.$observer.withValue({ continuation.yield($0) }) {
			try await executeSafeDIToolTest(
				swiftFileContent: [
					"""
					@Instantiable(generateMock: true)
					public final class Mocked: Instantiable {
					    public init(x: A, y: B, z: A) {
					        self.x = x
					        self.y = y
					        self.z = z
					    }
					    @Received let x: A
					    @Received let y: B
					    @Received(fulfilledByDependencyNamed: "x", ofType: A.self) let z: A
					}
					""",
					"""
					@Instantiable
					public final class A: Instantiable {
					    public init() {}
					}
					""",
					"""
					@Instantiable
					public final class B: Instantiable {
					    public init(x: C) { self.x = x }
					    @Received let x: C
					}
					""",
					"""
					@Instantiable
					public final class C: Instantiable {
					    public init() {}
					}
					""",
				],
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}

		continuation.finish()
		var routed = [Bool]()
		for await routing in routings {
			routed.append(routing)
		}
		#expect(routed == [true])
		#expect(output.mockFiles["Mocked+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Mocked {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            x_A: (() -> A)? = nil,
		            x_C: (() -> C)? = nil,
		            y: ((C) -> B)? = nil
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                x_A: x_A,
		                x_C: x_C,
		                y: y
		            )
		        }

		        var x_A: (() -> A)? { __safeDI_storage.x_A }
		        var x_C: (() -> C)? { __safeDI_storage.x_C }
		        var y: ((C) -> B)? { __safeDI_storage.y }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                x_A: (() -> A)?,
		                x_C: (() -> C)?,
		                y: ((C) -> B)?
		            ) {
		                self.x_A = x_A
		                self.x_C = x_C
		                self.y = y
		            }

		            let x_A: (() -> A)?
		            let x_C: (() -> C)?
		            let y: ((C) -> B)?
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Mocked {
		        let x_A = if let safeDIBuilder = safeDIOverrides.x_A { safeDIBuilder() } else { A() }
		        #sourceLocation(file: "\(output.fixtures["Mocked.swift"])", line: 10)
		        let z: A = x_A
		        #sourceLocation()
		        let x_C = if let safeDIBuilder = safeDIOverrides.x_C { safeDIBuilder() } else { C() }
		        func __safeDI_y() -> B {
		            let x: C = x_C
		            return if let safeDIBuilder = safeDIOverrides.y { safeDIBuilder(x) } else { B(x: x) }
		        }
		        let y: B = __safeDI_y()
		        return Mocked(x: x_A, y: y, z: z)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Mocked+SafeDIMock.swift"] ?? "")")
	}

	// MARK: Private

	private var filesToDelete: [URL]
}
