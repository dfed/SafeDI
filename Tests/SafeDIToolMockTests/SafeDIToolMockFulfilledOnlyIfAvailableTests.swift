	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_readsEntryFromLocal_whenTypeBuiltInsideSendableFunctionInstantiatesFulfilledTypeOnlyIfAvailable() async throws {
		// `Child` is built inside a `@Sendable` builder function, which reads its overrides from locals bound before it:
		// the entry is read so too.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				public protocol Analytics: Sendable {}
				""",
				"""
				@Instantiable(fulfillingAdditionalTypes: [Analytics.self])
				public final class DefaultAnalytics: Analytics, Instantiable {
				    public init() {}
				}
				""",
				"""
				@Instantiable(generateMock: true)
				public final class Screen: Instantiable, Sendable {
				    public init(childBuilder: SendableInstantiator<Child>) {
				        self.childBuilder = childBuilder
				    }
				    @Instantiated let childBuilder: SendableInstantiator<Child>
				}
				""",
				"""
				@Instantiable
				public final class Child: Instantiable, Sendable {
				    public init(analytics: (any Analytics)?) {
				        self.analytics = analytics
				    }
				    @Instantiated(onlyIfAvailable: true) let analytics: (any Analytics)?
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.mockFiles["Screen+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Screen {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            childBuilder: Child.SafeDIMockConfiguration = .init()
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                childBuilder: childBuilder
		            )
		        }

		        var childBuilder: Child.SafeDIMockConfiguration { __safeDI_storage.childBuilder }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage: Sendable {
		            init(
		                childBuilder: Child.SafeDIMockConfiguration
		            ) {
		                self.childBuilder = childBuilder
		            }

		            let childBuilder: Child.SafeDIMockConfiguration
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Screen {
		        let __safeDI_childBuilder__overrides = safeDIOverrides.childBuilder
		        @Sendable nonisolated func __safeDI_childBuilder() -> Child {
		            let analytics: (any Analytics)? = if __safeDI_childBuilder__overrides.analyticsIsUnavailable { nil } else if let safeDIBuilder = __safeDI_childBuilder__overrides.analytics { safeDIBuilder() } else { DefaultAnalytics() }
