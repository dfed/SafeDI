		        return Screen(childBuilder: childBuilder)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Screen+SafeDIMock.swift"] ?? "")")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_namesEntryApart_whenSiblingIsLabeledAsEntry() async throws {
		// `Screen` instantiates `analyticsIsUnavailable` beside `analytics`, which it instantiates only if available: the
		// entry takes `_`, and the sibling's own entry keeps its label.
