/// A mock of a type whose tree declares `@Instantiated(onlyIfAvailable: true) let analytics: (any Analytics)?`, where a
/// production declaration fulfills `Analytics`. Production builds `analytics`; so does an internal mock, which also takes an
/// entry `analyticsIsUnavailable: Bool = false` beside the property's own, which builds it as `nil`, as production binds it in
/// an app where nothing fulfills the type.
struct SafeDIToolMockFulfilledOnlyIfAvailableTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_takesEntryBuildingPropertyAsNil_whenMockedTypeInstantiatesFulfilledTypeOnlyIfAvailable() async throws {
		// `analytics` is built by value and `logger` with a configuration of its own: each takes an entry beside its own.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				public protocol Analytics {}
				public protocol Logger {}
				""",
				"""
				@Instantiable(fulfillingAdditionalTypes: [Analytics.self])
				public final class DefaultAnalytics: Analytics, Instantiable {
				    public init() {}
				}
				""",
				"""
				@Instantiable(fulfillingAdditionalTypes: [Logger.self])
				public final class DefaultLogger: Logger, Instantiable {
				    public init(store: Store) {
				        self.store = store
				    }
				    @Instantiated let store: Store
				}
				""",
				"""
				@Instantiable(generateMock: true)
				public final class Screen: Instantiable {
				    public init(analytics: (any Analytics)?, logger: (any Logger)?) {
				        self.analytics = analytics
				        self.logger = logger
				    }
				    @Instantiated(onlyIfAvailable: true) let analytics: (any Analytics)?
				    @Instantiated(onlyIfAvailable: true) let logger: (any Logger)?
				}
				""",
				"""
				@Instantiable
				public final class Store: Instantiable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.mockFiles["Screen+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Screen {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            analyticsIsUnavailable: Bool = false,
		            analytics: (() -> any Analytics)? = nil,
		            loggerIsUnavailable: Bool = false,
		            logger: DefaultLogger.SafeDIMockConfiguration = .init()
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                analyticsIsUnavailable: analyticsIsUnavailable,
		                analytics: analytics,
		                loggerIsUnavailable: loggerIsUnavailable,
		                logger: logger
		            )
		        }

		        var analyticsIsUnavailable: Bool { __safeDI_storage.analyticsIsUnavailable }
		        var analytics: (() -> any Analytics)? { __safeDI_storage.analytics }
		        var loggerIsUnavailable: Bool { __safeDI_storage.loggerIsUnavailable }
		        var logger: DefaultLogger.SafeDIMockConfiguration { __safeDI_storage.logger }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                analyticsIsUnavailable: Bool,
		                analytics: (() -> any Analytics)?,
		                loggerIsUnavailable: Bool,
		                logger: DefaultLogger.SafeDIMockConfiguration
		            ) {
		                self.analyticsIsUnavailable = analyticsIsUnavailable
		                self.analytics = analytics
		                self.loggerIsUnavailable = loggerIsUnavailable
		                self.logger = logger
		            }

		            let analyticsIsUnavailable: Bool
		            let analytics: (() -> any Analytics)?
		            let loggerIsUnavailable: Bool
		            let logger: DefaultLogger.SafeDIMockConfiguration
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Screen {
		        let analytics: (any Analytics)? = if safeDIOverrides.analyticsIsUnavailable { nil } else if let safeDIBuilder = safeDIOverrides.analytics { safeDIBuilder() } else { DefaultAnalytics() }
		        func __safeDI_logger() -> any Logger {
		            let store = if let safeDIBuilder = safeDIOverrides.logger.store { safeDIBuilder() } else { Store() }
		            return if let safeDIBuilder = safeDIOverrides.logger.safeDIBuilder { safeDIBuilder(store) } else { DefaultLogger(store: store) }
		        }
		        let logger: (any Logger)? = if safeDIOverrides.loggerIsUnavailable { nil } else { __safeDI_logger() }
		        return Screen(analytics: analytics, logger: logger)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Screen+SafeDIMock.swift"] ?? "")")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_takesEntryInConfiguration_whenTypeInMockedTreeInstantiatesFulfilledTypeOnlyIfAvailable() async throws {
		// `Child`, beneath the mocked `Screen`, instantiates `analytics` only if available, and `Footer`, beneath `Child`,
		// receives it only if available: `Child`'s configuration holds the entry, and `Footer` is passed `nil` when it is set.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				public protocol Analytics {}
				""",
				"""
				@Instantiable(fulfillingAdditionalTypes: [Analytics.self])
				public final class DefaultAnalytics: Analytics, Instantiable {
				    public init() {}
				}
				""",
				"""
				@Instantiable(generateMock: true)
				public final class Screen: Instantiable {
				    public init(child: Child) {
				        self.child = child
				    }
				    @Instantiated let child: Child
				}
				""",
				"""
				@Instantiable
				public final class Child: Instantiable {
				    public init(analytics: (any Analytics)?, footer: Footer) {
				        self.analytics = analytics
				        self.footer = footer
				    }
				    @Instantiated(onlyIfAvailable: true) let analytics: (any Analytics)?
				    @Instantiated let footer: Footer
				}
				""",
				"""
				@Instantiable
				public final class Footer: Instantiable {
				    public init(analytics: (any Analytics)?) {
				        self.analytics = analytics
				    }
				    @Received(onlyIfAvailable: true) let analytics: (any Analytics)?
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.mockFiles["Screen+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Screen {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            child: Child.SafeDIMockConfiguration = .init()
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                child: child
		            )
		        }

		        var child: Child.SafeDIMockConfiguration { __safeDI_storage.child }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                child: Child.SafeDIMockConfiguration
		            ) {
		                self.child = child
		            }

		            let child: Child.SafeDIMockConfiguration
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Screen {
		        func __safeDI_child() -> Child {
		            let analytics: (any Analytics)? = if safeDIOverrides.child.analyticsIsUnavailable { nil } else if let safeDIBuilder = safeDIOverrides.child.analytics { safeDIBuilder() } else { DefaultAnalytics() }
		            let footer = if let safeDIBuilder = safeDIOverrides.child.footer { safeDIBuilder(analytics) } else { Footer(analytics: analytics) }
		            return if let safeDIBuilder = safeDIOverrides.child.safeDIBuilder { safeDIBuilder(analytics, footer) } else { Child(analytics: analytics, footer: footer) }
		        }
		        let child: Child = __safeDI_child()
		        return Screen(child: child)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Screen+SafeDIMock.swift"] ?? "")")
		#expect(output.mockConfigurationFile == """
