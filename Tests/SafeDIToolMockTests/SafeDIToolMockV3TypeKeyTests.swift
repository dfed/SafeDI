/// A `.v3Unstable` mock laid out by the type key: places of one type share one builder function, and each call hands that
/// function the configuration of its own place, `parent.field ?? .init()`, and a value the mock cannot build is made once
/// for each construction.
struct SafeDIToolMockV3TypeKeyTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_passesEachPlaceItsParentsConfiguration_whenTwoPlacesOfOneTypeShareABuilder() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@Instantiable
				public final class Leaf: Instantiable {
				    public init() {}
				}
				""",
				"""
				@Instantiable
				public final class Child: Instantiable {
				    public init(leaf: Leaf, name: String = "child") {
				        self.leaf = leaf
				        self.name = name
				    }

				    @Instantiated let leaf: Leaf
				    let name: String
				}
				""",
				"""
				@Instantiable
				public final class A: Instantiable {
				    public init(child: Child) {
				        self.child = child
				    }

				    @Instantiated let child: Child
				}
				""",
				"""
				@Instantiable
				public final class B: Instantiable {
				    public init(child: Child) {
				        self.child = child
				    }

				    @Instantiated let child: Child
				}
				""",
				"""
				@Instantiable(generateMock: true)
				public final class Root: Instantiable {
				    public init(a: A, b: B) {
				        self.a = a
				        self.b = b
				    }

				    @Instantiated let a: A
				    @Instantiated let b: B
				}
				""",
			],
			swiftFileContentByFilePath: ["SafeDIConfiguration.swift": "#SafeDIConfiguration(apiVersion: .v3Unstable)\n"],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(try #require(output.generatedFiles?["Root+SafeDIMock.swift"]) == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        func __safeDI_child(__safeDI_Child_configuration: Child.SafeDIOverrides) -> Child {
		            let leaf = if let safeDIBuilder = __safeDI_Child_configuration.leaf { safeDIBuilder() } else { Leaf() }
		            return if let safeDIBuilder = __safeDI_Child_configuration.safeDIBuilder { safeDIBuilder(leaf, __safeDI_Child_configuration.name) } else { Child(leaf: leaf, name: __safeDI_Child_configuration.name) }
		        }
		        func __safeDI_a(__safeDI_A_configuration: A.SafeDIOverrides) -> A {
		            let child: Child = __safeDI_child(__safeDI_Child_configuration: Child.SafeDIOverrides.__safeDI_read(__safeDI_A_configuration.child))
		            return if let safeDIBuilder = __safeDI_A_configuration.safeDIBuilder { safeDIBuilder(child) } else { A(child: child) }
		        }
		        let a: A = __safeDI_a(__safeDI_A_configuration: A.SafeDIOverrides.__safeDI_read(safeDIOverrides.a))
		        func __safeDI_b(__safeDI_B_configuration: B.SafeDIOverrides) -> B {
		            let child: Child = __safeDI_child(__safeDI_Child_configuration: Child.SafeDIOverrides.__safeDI_read(__safeDI_B_configuration.child))
		            return if let safeDIBuilder = __safeDI_B_configuration.safeDIBuilder { safeDIBuilder(child) } else { B(child: child) }
		        }
		        let b: B = __safeDI_b(__safeDI_B_configuration: B.SafeDIOverrides.__safeDI_read(safeDIOverrides.b))
		        return if let safeDIBuilder = safeDIOverrides.safeDIBuilder { safeDIBuilder(a, b) } else { Root(a: a, b: b) }
		    }
		}
		#endif

		#if DEBUG
		extension Root {
		    /// Configures `Root` wherever a mock builds it: as the mocked type, inside another mock’s tree, or on a later pass of
		    /// a dependency cycle. A child field left `nil` reads the configuration of the nearest ancestor of the child’s type on its
		    /// path, or that type’s defaults where there is none.
		    struct SafeDIOverrides {
		        init(
		            a: A.SafeDIOverrides? = nil,
		            b: B.SafeDIOverrides? = nil,
		            _ safeDIBuilder: ((A, B) -> Root)? = nil
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                a: a,
		                b: b,
		                safeDIBuilder: safeDIBuilder
		            )
		        }

		        var a: A.SafeDIOverrides? { __safeDI_storage.a }
		        var b: B.SafeDIOverrides? { __safeDI_storage.b }
		        /// Overrides how this type is constructed. Parameters match the type’s initializer or custom mock method. When `nil`, the default generated construction function is used.
		        var safeDIBuilder: ((A, B) -> Root)? { __safeDI_storage.safeDIBuilder }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                a: A.SafeDIOverrides?,
		                b: B.SafeDIOverrides?,
		                safeDIBuilder: ((A, B) -> Root)?
		            ) {
		                self.a = a
		                self.b = b
		                self.safeDIBuilder = safeDIBuilder
		            }

		            let a: A.SafeDIOverrides?
		            let b: B.SafeDIOverrides?
		            let safeDIBuilder: ((A, B) -> Root)?
		        }
		    }
		}
		#endif
		""")
	}

	@Test
