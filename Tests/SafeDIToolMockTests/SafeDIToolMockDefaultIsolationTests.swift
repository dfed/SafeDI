/// In a module whose declarations default to the main actor, the `SafeDIMockConfiguration` of a type on a global actor is
/// on that actor too, so a holder off that actor – the mocked type's `SafeDIOverrides`, or another type's configuration –
/// cannot default its field to `.init()`. Such a field holds the configuration as an optional defaulting to `nil`, which
/// `mock()`, on the type's actor wherever the tree compiles, resolves once at the top of its body. A field is deferred
/// when the child's declaration spells a global actor its holder's type does not, and every configuration field of the
/// `SafeDIOverrides` of a mock on a global actor only through `mockAttributes` is, since SafeDI cannot see the isolation
/// a child takes from a conformance or a superclass.
struct SafeDIToolMockDefaultIsolationTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

