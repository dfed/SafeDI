/// In a module whose declarations default to the main actor, the `SafeDIMockConfiguration` of a type on a global actor is
/// on that actor too, so a holder off that actor – the mocked type's `SafeDIOverrides`, or another type's configuration –
/// cannot default its field to `.init()`. Such a field holds the configuration as an optional defaulting to `nil`, which
/// `mock()` resolves once at the top of its body, where it builds the type on the type's actor wherever the type's
/// initializer is on that actor. A field is deferred when the child's declaration spells a global actor its holder's type
/// does not, and every configuration field of the `SafeDIOverrides` of a mock on a global actor only through
/// `mockAttributes` is, since SafeDI cannot see the isolation a child takes from a conformance or a superclass.
struct SafeDIToolMockDefaultIsolationTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test(arguments: ModuleDefaultIsolation.allCases)
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_resolvesMainActorConfigurationInMock_whenMockIsOnMainActorOnlyThroughMockAttributes(isolation: ModuleDefaultIsolation) async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@MainActor
				@Instantiable
				public final class Service: Instantiable {
				    public init(name: String = "service") {
				        self.name = name
				    }

				    public let name: String
				}
				""",
				"""
				@Instantiable(mockAttributes: "@MainActor", generateMock: true)
				public final class Screen: Instantiable {
				    public init(service: Service, serviceBuilder: Instantiator<Service>) {
				        self.service = service
				        self.serviceBuilder = serviceBuilder
				    }

				    @Instantiated let service: Service
				    @Instantiated let serviceBuilder: Instantiator<Service>
				}
				""",
				"""
				#if DEBUG
				@MainActor func makeScreens() -> [Screen] {
				    [
				        Screen.mock(),
				        Screen.mock(safeDIOverrides: .init(service: .init(name: "custom"))),
				        Screen.mock(safeDIOverrides: .init(service: .init { Service(name: $0 + "!") })),
				        Screen.mock(safeDIOverrides: .init(service: .init(name: "custom") { Service(name: $0) }, serviceBuilder: Service.SafeDIMockConfiguration(name: "built"))),
				        Screen.mock(safeDIOverrides: .init(service: .init())),
				    ]
				}
				#endif
				""",
			],
			buildSwiftOutputDirectory: true,
