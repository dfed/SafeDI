/// Which type a generated mock builds for an `@Instantiated(fulfilledByType:)` property when another type fulfills the
/// property's type: the type `fulfilledByType:` names, as the app does, unless a `mockOnly` declaration of another type
/// fulfills the property's type.
struct SafeDIToolMockFulfilledByTypeTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_buildsTypeFulfilledByTypeNames_whenAnotherTypeFulfillsPropertyType() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				public protocol FilterProtocol {}
				""",
				"""
				@Instantiable(isRoot: true, generateMock: true)
				public struct Root: Instantiable {
				    public init(filter: any FilterProtocol) {
				        self.filter = filter
				    }
				    @Instantiated(fulfilledByType: "AppFilter") let filter: any FilterProtocol
				}
				""",
				"""
				@Instantiable(fulfillingAdditionalTypes: [FilterProtocol.self])
				public struct CoreFilter: FilterProtocol, Instantiable {
				    public init() {}
				}
				""",
				"""
				@Instantiable
				public struct AppFilter: FilterProtocol, Instantiable {
				    public init(ruleSet: RuleSet) {
				        self.ruleSet = ruleSet
				    }
				    @Instantiated let ruleSet: RuleSet
				}
				""",
				"""
				@Instantiable
				public struct RuleSet: Instantiable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.dependencyTreeFiles["Root+SafeDI.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Root {
		    public init() {
		        func __safeDI_filter() -> AppFilter {
		            let ruleSet = RuleSet()
		            return AppFilter(ruleSet: ruleSet)
		        }
		        let filter: any FilterProtocol = __safeDI_filter()
		        self.init(filter: filter)
		    }
		}
		""", "Unexpected output \(output.dependencyTreeFiles["Root+SafeDI.swift"] ?? "")")
		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            filter: AppFilter.SafeDIMockConfiguration = .init()
		        ) {
		            self.filter = filter
		        }

		        let filter: AppFilter.SafeDIMockConfiguration
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        func __safeDI_filter() -> FilterProtocol {
		            let ruleSet = if let safeDIBuilder = safeDIOverrides.filter.ruleSet { safeDIBuilder() } else { RuleSet() }
		            return if let safeDIBuilder = safeDIOverrides.filter.safeDIBuilder { safeDIBuilder(ruleSet) } else { AppFilter(ruleSet: ruleSet) }
		        }
		        let filter: FilterProtocol = __safeDI_filter()
		        return Root(filter: filter)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")
		#expect(output.mockConfigurationFile == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension AppFilter {
		    /// Configuration for how this type is constructed within a mock tree.
		    struct SafeDIMockConfiguration {
		        init(
		            ruleSet: (() -> RuleSet)? = nil,
		            _ safeDIBuilder: ((RuleSet) -> AppFilter)? = nil
		        ) {
		            self.ruleSet = ruleSet
		            self.safeDIBuilder = safeDIBuilder
		        }

		        let ruleSet: (() -> RuleSet)?
		        /// Overrides how this type is constructed. Parameters match the type’s initializer or custom mock method. When `nil`, the default generated construction function is used.
		        let safeDIBuilder: ((RuleSet) -> AppFilter)?
		    }
		}
		#endif

		""", "Unexpected output \(output.mockConfigurationFile ?? "")")
	}

