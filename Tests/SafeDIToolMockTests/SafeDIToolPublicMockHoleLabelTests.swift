	/// `Screen`, which receives `settingsBuilder` and instantiates `gizmo`, a hole and its only place, and `Settings`.
	private static func singleHoleFiles(caller: MockCaptureCaller, renamedHole: RenamedHole) -> [String] {
		[
			"""
			\(caller.attribute)
			public final class Screen: Instantiable {
			    public init(settingsBuilder: Instantiator<Settings>, gizmo: \(renamedHole.type)) {
			        fatalError("SafeDI doesn't inspect the initializer body")
			    }

			    @Received let settingsBuilder: Instantiator<Settings>
			    @Instantiated let gizmo: \(renamedHole.type)
			}

			public final class Gizmo: Instantiable {}

			public final class Widget: Instantiable {}
			""",
			settingsFile,
		]
	}

	/// `Screen`, which receives `settingsBuilder` and instantiates `gizmo` (under `holeLabel`) and then `gadget`, two holes,
