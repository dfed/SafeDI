	            init(
	                settingsBuilder: ((Instantiator<Widget>) -> Settings)?
	            ) {
	                self.settingsBuilder = settingsBuilder
	            }

	            let settingsBuilder: ((Instantiator<Widget>) -> Settings)?
	        }
