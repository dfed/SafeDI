/// A mocked type whose own dependency the mock cannot build shares its label with what a promoted sibling receives as
/// another type. An internal mock takes the mocked type's dependency as a parameter under its label and names the sibling's
/// apart; a public mock would build the dependency at the site of a hole, through the builder it takes, and bind it apart
/// from the sibling's parameter, so it would hold two values under the label and hand its builders the mocked type's values
/// by label, and is rejected (`SafeDIToolPublicMockHoleBoundApartTests` has the rest of the shapes).
struct SafeDIToolPublicMockHoleLabelTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test(arguments: [MockCaptureCaller.internal, .listed], RenamedHole.allCases)
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_generatesMock_whenPromotedSiblingReceivesOtherTypeUnderLabelOfHoleThatInternalMockTakesAsParameter(caller: MockCaptureCaller, renamedHole: RenamedHole) async throws {
		// `Screen` receives `settingsBuilder`, which its mock builds at its root, and instantiates `gizmo`, which no
		// declaration fulfills; `Settings` receives `gizmo: Instantiator<Widget>`. An internal mock takes `gizmo` as a
		// parameter under its label and names `Settings`’s apart.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: Self.singleHoleFiles(caller: caller, renamedHole: renamedHole),
			swiftFileContentByFilePath: caller.configurationFiles,
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
			activeCompilationConditions: ["DEBUG"],
		)

		let internalMockBody = """
		\(Self.internalOverrides)

		    static func mock(
		        gizmo_Instantiator__Widget: Instantiator<Widget>,
		        gizmo: \(renamedHole.type),
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Screen {
		        func __safeDI_settingsBuilder() -> Settings {
		            let gizmo: Instantiator<Widget> = gizmo_Instantiator__Widget
		            return if let safeDIBuilder = safeDIOverrides.settingsBuilder { safeDIBuilder(gizmo) } else { Settings(gizmo: gizmo) }
		        }
		        let settingsBuilder = Instantiator<Settings>(__safeDI_settingsBuilder)
		        return Screen(settingsBuilder: settingsBuilder, gizmo: gizmo)
		    }
		"""
		let importLines = caller == .listed ? "#if canImport(SafeDI)\nimport SafeDI\n#endif\n\n" : ""
		#expect(output.mockFiles == ["Screen+SafeDIMock.swift": """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		\(importLines)#if DEBUG
		extension Screen {
		\(internalMockBody)
		}
		#endif
		"""])
	}

