}

/// How `Screen` holds `gizmo`, the hole a public mock would bind under a name of its own.
enum RenamedHole: CaseIterable, CustomTestStringConvertible {
	case constant
	case lazilyInstantiated
	case instantiator

	var type: String {
		switch self {
		case .constant:
			"Gizmo"
		case .lazilyInstantiated:
			"LazilyInstantiated<Gizmo>"
		case .instantiator:
			"Instantiator<Gizmo>"
		}
	}

	var testDescription: String {
		switch self {
		case .constant:
			"hole held as itself"
		case .lazilyInstantiated:
			"hole held in a LazilyInstantiated"
		case .instantiator:
			"hole held in an Instantiator"
		}
	}
}

/// How `Screen` holds `panel`, beneath which `gadget` is a hole.
enum PlaceHolder: CaseIterable, CustomTestStringConvertible {
	case constant
	case instantiator
	case lazilyInstantiated

	var type: String {
		switch self {
		case .constant:
			"Panel"
		case .instantiator:
			"Instantiator<Panel>"
		case .lazilyInstantiated:
			"LazilyInstantiated<Panel>"
		}
	}

	/// The lines that bind `panel` in an internal mock.
	var internalBinding: String {
		switch self {
		case .constant:
			"        let panel = if let safeDIBuilder = safeDIOverrides.panel { safeDIBuilder(gadget) } else { Panel(gadget: gadget) }"
		case .instantiator, .lazilyInstantiated:
			"""
			        func __safeDI_panel() -> Panel {
			            if let safeDIBuilder = safeDIOverrides.panel { safeDIBuilder(gadget) } else { Panel(gadget: gadget) }
			        }
			        let panel = \(type)(__safeDI_panel)
			"""
		}
	}

	var testDescription: String {
		switch self {
		case .constant:
			"place beneath a type held as itself"
		case .instantiator:
			"place beneath a type held in an Instantiator"
		case .lazilyInstantiated:
			"place beneath a type held in a LazilyInstantiated"
		}
	}
}
