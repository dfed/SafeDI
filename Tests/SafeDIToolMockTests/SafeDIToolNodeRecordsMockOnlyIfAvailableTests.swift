	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_laysOutNodesAsTheWalkWritesThem_whenReceivesOnlyIfAvailableFindSiblingBuiltBeforeOrNil() async throws {
		// `Screen` receives `session` only if available, which its sibling is, built before it; `Banner` receives `screen`
		// only if available, but `Screen` requires `banner`, so `Banner` is built first and passed `nil`.
		let fixture = [
			"""
			@Instantiable(generateMock: true)
			public struct Root: Instantiable {
			    public init(session: Session, banner: Banner, screen: Screen) {
			        self.session = session
			        self.banner = banner
			        self.screen = screen
			    }

			    @Instantiated let session: Session
			    @Instantiated let banner: Banner
			    @Instantiated let screen: Screen
			}
			""",
			"""
			@Instantiable
			public final class Banner: Instantiable {
			    public init(screen: Screen?) {
			        self.screen = screen
			    }

			    @Received(onlyIfAvailable: true) let screen: Screen?
			}
			""",
			"""
			@Instantiable
			public final class Screen: Instantiable {
			    public init(banner: Banner, session: Session?) {
			        self.banner = banner
			        self.session = session
			    }

			    @Received let banner: Banner
			    @Received(onlyIfAvailable: true) let session: Session?
			}
			""",
			"""
			@Instantiable
			public final class Session: Instantiable {
			    public init() {}
			}
			""",
		]
		let walkOutput = try await executeSafeDIToolTest(swiftFileContent: fixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		let (output, reports) = try await Self.layingOutMockRoots(filesToDelete: &filesToDelete) { filesToDelete in
			try await executeSafeDIToolTest(swiftFileContent: fixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}
		#expect(reports.filter(\.isMockRoot).map(\.refusal) == [nil])
		#expect(reports.filter(\.isMockRoot).map(\.isLaidOutFromNodeRecords) == [true])
		#expect(output.mockFiles == walkOutput.mockFiles)
		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            session: (() -> Session)? = nil,
		            banner: ((Screen?) -> Banner)? = nil,
		            screen: ((Banner, Session?) -> Screen)? = nil
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                session: session,
		                banner: banner,
		                screen: screen
		            )
		        }

		        var session: (() -> Session)? { __safeDI_storage.session }
		        var banner: ((Screen?) -> Banner)? { __safeDI_storage.banner }
		        var screen: ((Banner, Session?) -> Screen)? { __safeDI_storage.screen }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                session: (() -> Session)?,
		                banner: ((Screen?) -> Banner)?,
		                screen: ((Banner, Session?) -> Screen)?
		            ) {
		                self.session = session
		                self.banner = banner
		                self.screen = screen
		            }

		            let session: (() -> Session)?
		            let banner: ((Screen?) -> Banner)?
		            let screen: ((Banner, Session?) -> Screen)?
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        let session = if let safeDIBuilder = safeDIOverrides.session { safeDIBuilder() } else { Session() }
		        let banner = if let safeDIBuilder = safeDIOverrides.banner { safeDIBuilder(nil) } else { Banner(screen: nil) }
		        let screen = if let safeDIBuilder = safeDIOverrides.screen { safeDIBuilder(banner, session) } else { Screen(banner: banner, session: session) }
		        return Root(session: session, banner: banner, screen: screen)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_buildsTheWalksValues_whenEveryPlaceIsOverriddenAndReceivesOnlyIfAvailableAreBuiltInsideInstantiatorsFunction() async throws {
		let walkOutput = try await executeSafeDIToolTest(swiftFileContent: [], swiftFileContentByFilePath: Self.valueFixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		let (output, reports) = try await Self.layingOutMockRoots(filesToDelete: &filesToDelete) { filesToDelete in
			try await executeSafeDIToolTest(swiftFileContent: [], swiftFileContentByFilePath: Self.valueFixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}
		#expect(reports.filter(\.isMockRoot).map(\.refusal) == [nil])
		#expect(reports.filter(\.isMockRoot).map(\.isLaidOutFromNodeRecords) == [true])
		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            session: (() -> Session)? = nil,
		            footer: (() -> Footer)? = nil,
		            banner: ((Footer?) -> Banner)? = nil,
		            screenBuilder: Screen.SafeDIMockConfiguration = .init()
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                session: session,
		                footer: footer,
		                banner: banner,
		                screenBuilder: screenBuilder
		            )
		        }

		        var session: (() -> Session)? { __safeDI_storage.session }
		        var footer: (() -> Footer)? { __safeDI_storage.footer }
		        var banner: ((Footer?) -> Banner)? { __safeDI_storage.banner }
		        var screenBuilder: Screen.SafeDIMockConfiguration { __safeDI_storage.screenBuilder }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                session: (() -> Session)?,
		                footer: (() -> Footer)?,
		                banner: ((Footer?) -> Banner)?,
		                screenBuilder: Screen.SafeDIMockConfiguration
		            ) {
		                self.session = session
		                self.footer = footer
		                self.banner = banner
		                self.screenBuilder = screenBuilder
		            }

		            let session: (() -> Session)?
		            let footer: (() -> Footer)?
		            let banner: ((Footer?) -> Banner)?
		            let screenBuilder: Screen.SafeDIMockConfiguration
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        let session = if let safeDIBuilder = safeDIOverrides.session { safeDIBuilder() } else { Session() }
		        let footer = if let safeDIBuilder = safeDIOverrides.footer { safeDIBuilder() } else { Footer() }
		        let banner = if let safeDIBuilder = safeDIOverrides.banner { safeDIBuilder(footer) } else { Banner(footer: footer) }
		        func __safeDI_screenBuilder(safeDIOverrides: Screen.SafeDIMockConfiguration) -> Screen {
		            let panel = if let safeDIBuilder = safeDIOverrides.panel { safeDIBuilder(session, nil) } else { Panel(session: session, badge: nil) }
		            let badge = if let safeDIBuilder = safeDIOverrides.badge { safeDIBuilder(panel) } else { Badge(panel: panel) }
		            return if let safeDIBuilder = safeDIOverrides.safeDIBuilder { safeDIBuilder(panel, badge) } else { Screen(panel: panel, badge: badge) }
		        }
		        let screenBuilder = Instantiator<Screen> {
		            __safeDI_screenBuilder(safeDIOverrides: safeDIOverrides.screenBuilder)
		        }
		        return Root(session: session, banner: banner, screenBuilder: screenBuilder, footer: footer)
		    }
		}
		#endif
		""", "Unexpected output \(output.mockFiles["Root+SafeDIMock.swift"] ?? "")")
		let overridden = """
		Root.mock(safeDIOverrides: .init(\
		session: { marked(Session(), "session") }, \
		footer: { marked(Footer(), "footer") }, \
		banner: { marked(Banner(footer: $0), "banner") }, \
		screenBuilder: .init(\
		panel: { marked(Panel(session: $0, badge: $1), "screenBuilder.panel") }, \
		badge: { marked(Badge(panel: $0), "screenBuilder.badge") }, \
		{ marked(Screen(panel: $0, badge: $1), "screenBuilder") })\
		))
		"""
		let comparison = try await DifferentialValueOracle.compare(
			feature: DifferentialValuePath(fixtureFiles: Self.valueFixture, generatedFiles: #require(output.generatedFiles)),
			knownRight: DifferentialValuePath(fixtureFiles: Self.valueFixture, generatedFiles: #require(walkOutput.generatedFiles)),
			probes: [
				DifferentialValueProbe("Root.mock()"),
				DifferentialValueProbe("Root.mock().screenBuilder.instantiate()"),
				DifferentialValueProbe(name: "overridden root", expression: overridden),
				DifferentialValueProbe(name: "overridden screen", expression: "\(overridden).screenBuilder.instantiate()"),
			],
			filesToDelete: &filesToDelete,
		)
		// Nothing is compared where compile verification is off.
		guard let comparison else { return }
		#expect(comparison.differences.isEmpty, "\(comparison.report)")
		// Every override was read: each marks the value its closure built.
		for marker in ["session", "banner", "screenBuilder.panel", "screenBuilder.badge", "screenBuilder", "footer"] {
			#expect(comparison.featureDescription.contains("\"\(marker)\""), "No value is marked \(marker):\n\(comparison.featureDescription)")
		}
	}

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_bindsPromotedOptionalConstantAsUnwrappedType_whenNodeItBuildsReceivesItOnlyIfAvailable() async throws {
		// `Screen` requires `a: A?`, so the mock promotes it and builds `A`, whose `B` receives `a` only if available and is
		// passed `nil`. The root binds `a` as the `A` its function returns, as the walk does, not as the optional property.
		let fixture = [
			"""
			@Instantiable(generateMock: true)
			public final class Screen: Instantiable {
			    public init(a: A?) { self.a = a }
			    @Received let a: A?
			}
			""",
			"""
			@Instantiable
			public final class A: Instantiable {
			    public init(b: B) { self.b = b }
			    @Instantiated let b: B
			}
			""",
			"""
			@Instantiable
			public final class B: Instantiable {
			    public init(a: A?) { self.a = a }
			    @Received(onlyIfAvailable: true) let a: A?
			}
			""",
		]
		let (output, reports) = try await Self.layingOutMockRoots(filesToDelete: &filesToDelete) { filesToDelete in
			try await executeSafeDIToolTest(swiftFileContent: fixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}
		#expect(reports.filter(\.isMockRoot).map(\.isLaidOutFromNodeRecords) == [true])
		#expect(output.mockFiles["Screen+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Screen {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            a: A.SafeDIMockConfiguration = .init()
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                a: a
		            )
		        }

		        var a: A.SafeDIMockConfiguration { __safeDI_storage.a }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                a: A.SafeDIMockConfiguration
		            ) {
		                self.a = a
		            }

		            let a: A.SafeDIMockConfiguration
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Screen {
		        func __safeDI_a(safeDIOverrides: A.SafeDIMockConfiguration) -> A {
		            let b = if let safeDIBuilder = safeDIOverrides.b { safeDIBuilder(nil) } else { B(a: nil) }
		            return if let safeDIBuilder = safeDIOverrides.safeDIBuilder { safeDIBuilder(b) } else { A(b: b) }
