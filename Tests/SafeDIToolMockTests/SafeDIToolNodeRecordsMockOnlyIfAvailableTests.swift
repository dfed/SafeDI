	/// A root whose `Instantiator` builds a screen whose panel receives the root's session only if available, built before
	/// the screen, and the screen's badge only if available, which requires the panel and so is built after it, beside a
	/// banner that receives the footer only if available, built after it. Each type carries a marker an
	/// override's closure sets.
	private static let valueFixture: [String: String] = [
		"Marked.swift": """
		public protocol Marked: AnyObject {
		    var marker: String { get set }
		}

		func marked<Value: Marked>(_ value: Value, _ marker: String) -> Value {
		    value.marker = marker
		    return value
		}
		""",
		"Root.swift": """
		@Instantiable(generateMock: true)
		public final class Root: Instantiable {
		    public init(session: Session, banner: Banner, screenBuilder: Instantiator<Screen>, footer: Footer) {
		        self.session = session
		        self.banner = banner
		        self.screenBuilder = screenBuilder
		        self.footer = footer
		    }

		    @Instantiated let session: Session
		    @Instantiated let banner: Banner
		    @Instantiated let screenBuilder: Instantiator<Screen>
		    @Instantiated let footer: Footer
		}
		""",
		"Session.swift": """
		@Instantiable
		public final class Session: Instantiable, Marked {
		    public init() {}

		    public var marker = "built"
		}
		""",
		"Banner.swift": """
		@Instantiable
		public final class Banner: Instantiable, Marked {
