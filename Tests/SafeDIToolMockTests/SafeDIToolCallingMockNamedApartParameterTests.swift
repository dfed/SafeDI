/// A mock in one module whose tree calls another module’s public mock that takes one label in two forms, the second
/// named apart (`user: User? = nil` beside `user_Draft`), because the called type’s tree receives `user: User` and,
/// beneath, `user: Draft`. The call passes each form the caller’s nearest declaration of it, as the same types’ mocks
/// built inline in one module read it, plain and optional alike.
struct SafeDIToolCallingMockNamedApartParameterTests: ~Copyable {
	// MARK: Initialization

	init() {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try? FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

