	// MARK: Private

	private var filesToDelete: [URL]

	/// `Hub`, a `Feature` type with a public mock and an internal initializer, so that `App` calls the mock. `Hub`
	/// receives `promoted`, which receives `user: User`, and instantiates `Middle`, whose receive of `user` is
	/// `draftReceive`.
	private static func modules(draftReceive: String, rootReceive: String? = nil) -> [ModuleFixture] {
		let draftType = draftReceive.hasSuffix("?") ? "Draft?" : "Draft"
		let rootUserParameter = rootReceive.map { "user: \($0.hasSuffix("?") ? "Draft?" : "Draft"), " } ?? ""
		let rootUserAssignment = rootReceive == nil ? "" : "\n        self.user = user"
		let rootUserProperty = rootReceive.map { "\n    \($0)" } ?? ""
		return [
			ModuleFixture(name: "Feature", packageName: "shop", swiftFileContentByFilePath: ["Hub.swift": """
			import SafeDI

			@Instantiable
			public final class User: Instantiable {
			    public init() {}
			}

			public final class Draft {
			    public init(name: String) {
			        self.name = name
			    }

			    public let name: String
			}

			@Instantiable
			public final class Promoted: Instantiable {
			    public init(user: User) {
			        self.user = user
			    }

			    @Received let user: User
			}

			@Instantiable
			final class Middle: Instantiable {
			    init(user: \(draftType)) {
			        self.user = user
			    }

			    \(draftReceive)
			}

			@Instantiable(generateMock: .public)
			public final class Hub: Instantiable {
			    init(middle: Middle, promoted: Promoted) {
			        self.middle = middle
			        self.promoted = promoted
			    }

			    @Instantiated let middle: Middle
			    @Received let promoted: Promoted
			}

			"""]),
			ModuleFixture(name: "App", packageName: "other", swiftFileContentByFilePath: ["Root.swift": """
			import Feature
			import SafeDI

			@Instantiable(generateMock: true)
			public final class Root: Instantiable {
			    public init(\(rootUserParameter)promoted: Promoted, hub: Hub) {\(rootUserAssignment)
			        self.promoted = promoted
			        self.hub = hub
			    }
			\(rootUserProperty)
			    @Received let promoted: Promoted
			    @Instantiated let hub: Hub
			}

			"""], dependencies: ["Feature"]),
		]
	}

	/// Compares the values `probes` build with those of the same types’ mocks built inline in one module.
	private mutating func expectValuesAgreeWithInlineMocks(
		of modules: [ModuleFixture],
		output: MultiModuleTestOutput,
		probes: [DifferentialValueProbe],
		sourceLocation: SourceLocation = #_sourceLocation,
	) async throws {
		let moduleNames = Set(modules.map(\.name))
		func inline(_ source: String) -> String {
			source
				.split(separator: "\n", omittingEmptySubsequences: false)
				.filter { line in !moduleNames.contains { line == "import \($0)" } }
				.joined(separator: "\n")
				.replacingOccurrences(of: "generateMock: .public", with: "generateMock: true")
		}
		var inlineFiles = [String: String]()
		for module in modules {
			for (fileName, content) in module.swiftFileContentByFilePath {
				inlineFiles["\(module.name)_\(fileName)"] = inline(content)
			}
		}
		let inlineModules = [ModuleFixture(name: modules[0].name, packageName: modules[0].packageName, swiftFileContentByFilePath: inlineFiles)]
		let inlineOutput = try await executeSafeDIToolMultiModuleTest(modules: inlineModules, integration: .moduleInfo, filesToDelete: &filesToDelete)
		func path(of modules: [ModuleFixture], output: MultiModuleTestOutput) throws -> DifferentialValuePath {
			try DifferentialValuePath(modules: modules.map { module in
				try DifferentialValueModule(
					name: module.name,
					packageName: module.packageName,
					dependencyModuleNames: module.dependencies,
					fixtureFiles: module.swiftFileContentByFilePath,
					generatedFiles: #require(output.modules[module.name], sourceLocation: sourceLocation).generatedFiles,
				)
			})
		}
		try await expectDifferentialValuesAgree(
			feature: path(of: modules, output: output),
			knownRight: path(of: inlineModules, output: inlineOutput),
			probes: probes,
			filesToDelete: &filesToDelete,
			sourceLocation: sourceLocation,
		)
	}
