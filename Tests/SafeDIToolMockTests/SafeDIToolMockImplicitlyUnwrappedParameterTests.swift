		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Impl {
		        let logger = if let safeDIBuilder = safeDIOverrides.logger { safeDIBuilder() } else { Logger() }
		        func __safeDI_readerBuilder() -> Reader {
		            if let safeDIBuilder = safeDIOverrides.readerBuilder { safeDIBuilder(logger) } else { Reader(logger: logger) }
		        }
