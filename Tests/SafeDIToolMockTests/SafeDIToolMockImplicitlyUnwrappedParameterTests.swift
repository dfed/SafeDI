	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_takesImplicitlyUnwrappedValueAsOptionalInBuilderClosure_whenMockedTypeDeclaresImplicitlyUnwrappedRename() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				import SafeDI

				@Instantiable(isRoot: true)
				public final class Root: Instantiable {
				    public init(logger: Logger, middle: Middle) {
				        self.logger = logger
				        self.middle = middle
				    }

				    @Instantiated let logger: Logger
				    @Instantiated let middle: Middle
				}
				""",
				"""
				import SafeDI

				@Instantiable(generateMock: true)
				public final class Middle: Instantiable {
				    public init(currentLogger: Logger!, reader: Reader) {
				        self.currentLogger = currentLogger
				        self.reader = reader
				    }

				    @Received(fulfilledByDependencyNamed: "logger", ofType: Logger.self) let currentLogger: Logger!
				    @Instantiated let reader: Reader
				}
				""",
				"""
				import SafeDI

				@Instantiable
				public final class Reader: Instantiable {
				    public init(currentLogger: Logger!) {
