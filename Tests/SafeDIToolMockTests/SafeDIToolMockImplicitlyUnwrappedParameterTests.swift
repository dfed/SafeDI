/// A value a mock hands a builder closure, takes as a public mock's parameter, or stores behind a `@Sendable`
/// configuration's closure, that the type it builds declares implicitly unwrapped (`init(logger: Logger!)`): Swift
/// cannot spell `Logger!` inside a function type or an optional, so the mock takes it as `Logger?`, the type Swift gives
/// the initializer's own parameter.
struct SafeDIToolMockImplicitlyUnwrappedParameterTests: ~Copyable {
	// MARK: Initialization

	init() {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

