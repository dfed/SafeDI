	private static let logger = """
	import SafeDI

	@Instantiable
	public final class Logger: Instantiable {
	    public init() {}
	}
	"""

	/// `Middle` renames the root's `logger` implicitly unwrapped and instantiates `Impl`, whose mock is generated as
	/// `mockGeneration` says, and which builds `Reader` through an `Instantiator` and `ValueReader` by value; both receive
	/// `logger: Logger!`.
	private static func receiversBeneathMockedTypeFiles(mockGeneration: String) -> [String] {
		[
			"""
			import SafeDI

			@Instantiable(isRoot: true)
			public final class Root: Instantiable {
			    public init(logger: Logger, middle: Middle) {
			        self.logger = logger
			        self.middle = middle
			    }

			    @Instantiated let logger: Logger
			    @Instantiated let middle: Middle
			}
			""",
			"""
			import SafeDI

			@Instantiable
			public final class Middle: Instantiable {
			    public init(logger: Logger!, impl: Impl) {
			        self.logger = logger
			        self.impl = impl
			    }

			    @Received(fulfilledByDependencyNamed: "logger", ofType: Logger.self) let logger: Logger!
			    @Instantiated let impl: Impl
			}
			""",
			"""
			import SafeDI

			@Instantiable(generateMock: \(mockGeneration))
			public final class Impl: Instantiable {
			    public init(readerBuilder: Instantiator<Reader>, valueReader: ValueReader) {
			        self.readerBuilder = readerBuilder
			        self.valueReader = valueReader
			    }

			    @Instantiated let readerBuilder: Instantiator<Reader>
			    @Instantiated let valueReader: ValueReader
			}
			""",
			"""
			import SafeDI

			@Instantiable
			public final class Reader: Instantiable {
			    public init(logger: Logger!) {
			        self.logger = logger
			    }

			    @Received let logger: Logger!
			}
			""",
			"""
			import SafeDI

			@Instantiable
			public final class ValueReader: Instantiable {
			    public init(logger: Logger!) {
			        self.logger = logger
			    }

			    @Received let logger: Logger!
			}
			""",
			logger,
		]
	}

