	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_buildsTheWalksValues_whenTwoBuildersBuildEachOtherOverFourLaps() async throws {
		let walkOutput = try await executeSafeDIToolTest(swiftFileContent: [], swiftFileContentByFilePath: Self.ringFixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		let (output, reports) = try await Self.layingOutMockRoots(filesToDelete: &filesToDelete) { filesToDelete in
			try await executeSafeDIToolTest(swiftFileContent: [], swiftFileContentByFilePath: Self.ringFixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		}
		#expect(reports.filter(\.isMockRoot).map(\.isLaidOutFromNodeRecords) == [true])
		// The two write other text, so the comparison is of two programs.
		#expect(output.mockFiles["Root+SafeDIMock.swift"] != walkOutput.mockFiles["Root+SafeDIMock.swift"])
		// The parent’s override marks every parent of the ring: each is built by the place the root entered. The edge
		// from a parent to its child is the one the configurations leave out, so no override reaches a child.
		let overridden = """
		Root.mock(safeDIOverrides: .init(parentBuilder: .init({ marked(Parent(childBuilder: $0), "parent") })))
		"""
		let laps = [
			".parentBuilder.instantiate()",
			".parentBuilder.instantiate().childBuilder.instantiate()",
			".parentBuilder.instantiate().childBuilder.instantiate().parentBuilder.instantiate()",
			".parentBuilder.instantiate().childBuilder.instantiate().parentBuilder.instantiate().childBuilder.instantiate()",
			".parentBuilder.instantiate().childBuilder.instantiate().parentBuilder.instantiate().childBuilder.instantiate().parentBuilder.instantiate()",
		]
		let comparison = try await DifferentialValueOracle.compare(
			feature: DifferentialValuePath(fixtureFiles: Self.ringFixture, generatedFiles: #require(output.generatedFiles)),
			knownRight: DifferentialValuePath(fixtureFiles: Self.ringFixture, generatedFiles: #require(walkOutput.generatedFiles)),
			probes: laps.enumerated().flatMap { lap, path in
				[
					DifferentialValueProbe(name: "lap \(lap)", expression: "Root.mock()\(path)"),
					DifferentialValueProbe(name: "overridden lap \(lap)", expression: "\(overridden)\(path)"),
				]
			},
			filesToDelete: &filesToDelete,
		)
		// Nothing is compared where compile verification is off.
		guard let comparison else { return }
		#expect(comparison.differences.isEmpty, "\(comparison.report)")
		// The override was read: it marks the value its closure built.
		#expect(comparison.featureDescription.contains("\"parent\""), "No value is marked parent:\n\(comparison.featureDescription)")
	}

