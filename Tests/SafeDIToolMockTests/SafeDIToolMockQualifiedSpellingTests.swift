import Foundation
import SafeDICore
import Testing
@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

/// A mock is generated for an `@SafeDI.Instantiable` whose `generateMock:` is spelled with SafeDI's module name
/// (`SafeDI.MockGeneration.internal`), as for its bare spelling.
struct SafeDIToolMockQualifiedSpellingTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_generatesMock_whenGenerateMockIsQualifiedBySafeDI() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [],
			swiftFileContentByFilePath: [
				"Service.swift": """
				@SafeDI.Instantiable(generateMock: SafeDI.MockGeneration.internal)
				public final class Service: Instantiable {
				    public init(client: Client) {
				        self.client = client
				    }

				    @SafeDI.Instantiated let client: Client
				}
				""",
				"Client.swift": """
				@SafeDI.Instantiable
				public final class Client: Instantiable {
				    public init() {}
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.generatedFiles?["Service+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Service {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            client: (() -> Client)? = nil
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                client: client
		            )
		        }

		        var client: (() -> Client)? { __safeDI_storage.client }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                client: (() -> Client)?
		            ) {
		                self.client = client
		            }

		            let client: (() -> Client)?
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Service {
		        let client = if let safeDIBuilder = safeDIOverrides.client { safeDIBuilder() } else { Client() }
		        return Service(client: client)
		    }
		}
		#endif
		""")
	}

	// MARK: Private

	private var filesToDelete = [URL]()
}
