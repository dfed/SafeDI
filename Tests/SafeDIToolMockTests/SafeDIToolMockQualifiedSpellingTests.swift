import Foundation
import SafeDICore
import Testing
@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

/// A mock is generated for an `@SafeDI.Instantiable` whose `generateMock:` is spelled with SafeDI's module name
/// (`SafeDI.MockGeneration.internal`), and whose tree spells every macro and wrapper so, as for their bare spellings.
struct SafeDIToolMockQualifiedSpellingTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func run_generatesMock_whenMacrosWrappersAndGenerateMockAreQualifiedBySafeDI() async throws {
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [],
			swiftFileContentByFilePath: SafeDIToolQualifiedSpellingFixtures.fixtures(rootArguments: "generateMock: SafeDI.MockGeneration.internal"),
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.generatedFiles?["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            session: (() -> Session)? = nil,
		            screenBuilder: ((Session) -> Screen)? = nil,
		            sendableScreenBuilder: (@Sendable (Session) -> Screen)? = nil,
		            profileBuilder: ((User) -> AnyObject)? = nil,
		            sendableProfileBuilder: (@Sendable (User) -> Profile)? = nil,
		            settings: (() -> Settings)? = nil,
		            sendableSettings: (@Sendable () -> Settings)? = nil
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                session: session,
		                screenBuilder: screenBuilder,
		                sendableScreenBuilder: sendableScreenBuilder,
		                profileBuilder: profileBuilder,
		                sendableProfileBuilder: sendableProfileBuilder,
		                settings: settings,
		                sendableSettings: sendableSettings
		            )
		        }

		        var session: (() -> Session)? { __safeDI_storage.session }
		        var screenBuilder: ((Session) -> Screen)? { __safeDI_storage.screenBuilder }
		        var sendableScreenBuilder: (@Sendable (Session) -> Screen)? { __safeDI_storage.sendableScreenBuilder }
		        var profileBuilder: ((User) -> AnyObject)? { __safeDI_storage.profileBuilder }
		        var sendableProfileBuilder: (@Sendable (User) -> Profile)? { __safeDI_storage.sendableProfileBuilder }
		        var settings: (() -> Settings)? { __safeDI_storage.settings }
		        var sendableSettings: (@Sendable () -> Settings)? { __safeDI_storage.sendableSettings }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                session: (() -> Session)?,
		                screenBuilder: ((Session) -> Screen)?,
		                sendableScreenBuilder: (@Sendable (Session) -> Screen)?,
		                profileBuilder: ((User) -> AnyObject)?,
		                sendableProfileBuilder: (@Sendable (User) -> Profile)?,
		                settings: (() -> Settings)?,
		                sendableSettings: (@Sendable () -> Settings)?
		            ) {
		                self.session = session
		                self.screenBuilder = screenBuilder
		                self.sendableScreenBuilder = sendableScreenBuilder
		                self.profileBuilder = profileBuilder
		                self.sendableProfileBuilder = sendableProfileBuilder
		                self.settings = settings
		                self.sendableSettings = sendableSettings
		            }

		            let session: (() -> Session)?
		            let screenBuilder: ((Session) -> Screen)?
		            let sendableScreenBuilder: (@Sendable (Session) -> Screen)?
