	private var filesToDelete: [URL]

	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	private mutating func expectSharedMockBody(
		of fixture: [String],
		equals expectedMock: String,
		probes: [DifferentialValueProbe],
		sourceLocation: SourceLocation = #_sourceLocation,
	) async throws {
		let output = try await executeSafeDIToolTest(swiftFileContent: fixture, buildSwiftOutputDirectory: true, filesToDelete: &filesToDelete)
		#expect(output.mockFiles["Screen+SafeDIMock.swift"] == expectedMock, sourceLocation: sourceLocation)
		var expectedFiles = output.generatedFiles ?? [:]
		expectedFiles["Screen+SafeDIMock.swift"] = expectedMock
		try await expectDifferentialValuesAgree(
			feature: DifferentialValuePath(fixtureFiles: Self.fixtureFiles(fixture), generatedFiles: output.generatedFiles ?? [:]),
			knownRight: DifferentialValuePath(fixtureFiles: Self.fixtureFiles(fixture), generatedFiles: expectedFiles),
			probes: probes,
			filesToDelete: &filesToDelete,
			sourceLocation: sourceLocation,
		)
	}

	private static func type(_ name: String, generateMock: Bool = false, _ declarations: String...) -> String {
		let declaration = seamFixtureType(named: name, isFinalClass: true, declarations: declarations)
		guard generateMock else { return declaration }
		return declaration.replacingOccurrences(of: "@Instantiable\n", with: "@Instantiable(generateMock: true)\n")
	}

	private static func sendableType(_ name: String, _ declarations: String...) -> String {
		seamFixtureType(named: name, isFinalClass: true, declarations: declarations, conformances: ", Sendable")
	}

	/// `files` named as `executeSafeDIToolTest` names them, after the type each declares.
	private static func fixtureFiles(_ files: [String]) -> [String: String] {
		var fixtureFiles = [String: String]()
		for file in files {
			let name = file.split(separator: "\n").compactMap { line -> String? in
				guard let declarationRange = line.range(of: "final class ") ?? line.range(of: "public struct ") else { return nil }
				return String(line[declarationRange.upperBound...].prefix { $0 != ":" && $0 != " " })
			}.first ?? "File"
			fixtureFiles["\(name).swift"] = file
		}
		return fixtureFiles
	}
}
