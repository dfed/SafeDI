/// Shared mock bodies (the mock type key’s first pull request): inside one generated `mock()`, places that build one
/// type alike share one function, declared in the mock’s body as R1 declares production’s, which takes the
/// place’s configuration as a parameter. A root any of whose places cannot be shared keeps today’s body whole.
/// Each test pins one rule with the whole generated mock, and checks that the expected mock compiles and builds the
/// values, overrides included, that today’s mock builds.
///
/// Written before the change exists: each test fails until mock bodies take the type key, except the whole-root
/// guard, which pins output today’s generator already gives.
struct SafeDIToolMockSharedBodyTests: ~Copyable {
	// MARK: Initialization

	init() {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

