/// A type with a generated mock is built, wherever a mock of its module builds it in a closed subtree, by one builder
/// declared once in its own extension, `static func __safeDI_build_<hash>`, which every such mock calls. The type's own
/// `mock()` already builds the same constructions in the isolation that builder has, so the builder needs no knowledge of
/// isolation. The builder spells the attributes the type's `mock()` spells, so a mock calls it only where its own `mock()`
/// spells the same, or the type's spells none, and a type whose initializer is `nonisolated` is built inline. A type
/// without a generated mock stays inline in the builder of its nearest mocked ancestor.
struct SafeDIToolMockSharedBuilderTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

