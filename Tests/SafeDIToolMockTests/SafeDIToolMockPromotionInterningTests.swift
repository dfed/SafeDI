import Foundation
import Testing
@testable import SafeDICore
@testable import SafeDIToolLibrary
@testable import SafeDIToolTestSupport

/// A mock root's promotion can respell what its tree receives, in a spelling no declaration writes, so its freeze interns
/// that spelling (`ConstructionInternerMiss.internedAtFreeze`) before any tree is built from its table.
struct SafeDIToolMockPromotionInterningTests: ~Copyable {
	// MARK: Initialization

	init() {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_promotesRespelledReceiveAndInternsItsSpellingAtPromotion_whenMockedTypeSpellsInstanceAsNoReceiverSpellsWrapper() async throws {
		// `Screen` receives `service: any Service`, and `Child` beneath it `service: LazilyInstantiated<Service>`: the mock
		// promotes the wrapper once, spelled after `Screen`'s own receive, `LazilyInstantiated<any Service>`, which no
		// declaration spells.
		let (stream, continuation) = AsyncStream.makeStream(of: (ConstructionInternerMiss, String).self)
		let output = try await ConstructionInternerObservation.$missObserver.withValue({ bucket, value in
			continuation.yield((bucket, value))
		}) {
			try await executeSafeDIToolTest(
				swiftFileContent: [
					"""
					public protocol Service {}

					@Instantiable(fulfillingAdditionalTypes: [Service.self])
					public final class DefaultService: Service, Instantiable {
					    public init() {}
					}
					""",
					"""
					@Instantiable(generateMock: true)
					public final class Screen: Instantiable {
					    public init(service: any Service, child: Child) {
					        self.service = service
					        self.child = child
					    }

					    @Received let service: any Service
					    @Instantiated let child: Child
					}
					""",
					"""
					@Instantiable
					public final class Child: Instantiable {
					    public init(service: LazilyInstantiated<Service>) {
					        self.service = service
					    }

					    @Received let service: LazilyInstantiated<Service>
					}
					""",
				],
				buildSwiftOutputDirectory: true,
				filesToDelete: &filesToDelete,
			)
		}
		continuation.finish()
		var internedAtFreeze = [String]()
		for await (bucket, value) in stream {
			switch bucket {
			case .internedAtFreeze:
				internedAtFreeze.append(value)
			case .notExcluded, .excluded:
				break
			}
		}

		#expect(internedAtFreeze.contains("service: LazilyInstantiated<any Service>"), "Interned at freeze: \(internedAtFreeze)")
		#expect(output.mockFiles["Screen+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Screen {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            service: (() -> any Service)? = nil,
		            child: ((LazilyInstantiated<Service>) -> Child)? = nil
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                service: service,
		                child: child
		            )
		        }

		        var service: (() -> any Service)? { __safeDI_storage.service }
		        var child: ((LazilyInstantiated<Service>) -> Child)? { __safeDI_storage.child }

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
		            init(
		                service: (() -> any Service)?,
		                child: ((LazilyInstantiated<Service>) -> Child)?
		            ) {
		                self.service = service
		                self.child = child
		            }

		            let service: (() -> any Service)?
		            let child: ((LazilyInstantiated<Service>) -> Child)?
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Screen {
		        func __safeDI_service() -> any Service {
		            if let safeDIBuilder = safeDIOverrides.service { safeDIBuilder() } else { DefaultService() }
		        }
		        let service = LazilyInstantiated<any Service>(__safeDI_service)
		        let child = if let safeDIBuilder = safeDIOverrides.child { safeDIBuilder(service) } else { Child(service: service) }
		        return Screen(service: service.instance, child: child)
		    }
		}
		#endif
		""")
	}

	// MARK: Private

	private var filesToDelete: [URL]
}
