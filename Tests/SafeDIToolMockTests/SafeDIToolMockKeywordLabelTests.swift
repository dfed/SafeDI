/// Labels a generated configuration (`SafeDIOverrides`, `SafeDIMockConfiguration`, a public mock's module-level
/// configuration) declares as members: `Type` and `Protocol`, which Swift rejects as a member's name written bare, a
/// keyword, and `self`, which as an initializer's parameter name would hide the instance the initializer assigns to.
struct SafeDIToolMockKeywordLabelTests: ~Copyable {
	// MARK: Initialization

	init() throws {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests

