		            let gadget: ((Kind) -> Gadget)?
		        }
		    }

		    static func mock(
		        safeDIOverrides: SafeDIOverrides = .init()
		    ) -> Root {
		        let Protocol: Kind? = safeDIOverrides.Protocol
