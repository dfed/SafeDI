	@Test
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func mock_namesOverridesParameterApartFromSelf_whenPromotedDependencyIsLabeledSelf() async throws {
		// `Gadget`'s `instantiate(self:)` receives `self`, which `Root`'s mock builds as a promoted dependency, so its
		// overrides take `self` beside the override of what `Root` receives only if available, which they assign.
		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				Self.kind,
				"""
				public struct Gadget {
				    let kind: Kind
				}

				@Instantiable
				extension Gadget: Instantiable {
				    public static func instantiate(self: Kind) -> Gadget {
				        Gadget(kind: `self`)
				    }
				}
				""",
				"""
				@Instantiable(generateMock: true)
				public struct Root: Instantiable {
				    public init(gadget: Gadget, `Protocol`: Kind?) {
				        self.gadget = gadget
				        self.`Protocol` = `Protocol`
				    }

				    @Instantiated let gadget: Gadget
				    @Received(onlyIfAvailable: true) let `Protocol`: Kind?
				}
				""",
			],
			buildSwiftOutputDirectory: true,
			filesToDelete: &filesToDelete,
		)

		#expect(output.mockFiles["Root+SafeDIMock.swift"] == """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if DEBUG
		extension Root {
		    /// Overrides for the mock dependency tree.
		    struct SafeDIOverrides {
		        init(
		            self __safeDI_self: (() -> Kind)? = nil,
		            gadget: ((Kind) -> Gadget)? = nil,
		            Protocol: Kind? = nil
		        ) {
		            __safeDI_storage = __safeDI_Storage(
		                self: __safeDI_self,
		                gadget: gadget
		            )
		            self.Protocol = Protocol
		        }

		        var `self`: (() -> Kind)? { __safeDI_storage.`self` }
		        var gadget: ((Kind) -> Gadget)? { __safeDI_storage.gadget }
		        let `Protocol`: Kind?

		        private let __safeDI_storage: __safeDI_Storage

		        private final class __safeDI_Storage {
