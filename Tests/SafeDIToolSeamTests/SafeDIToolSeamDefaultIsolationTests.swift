				    public init(missing: Missing, part: Part, name: String) {
				        self.missing = missing
				        self.part = part
				        self.name = name
				    }

				    @Instantiated let missing: Missing
				    @Received let part: Part
				    @Forwarded let name: String
				}
				""",
				"""
