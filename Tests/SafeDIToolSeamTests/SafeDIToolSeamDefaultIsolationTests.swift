	@Test(arguments: MultiModuleIntegration.allCases, ModuleDefaultIsolationPair.allCases)
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_declaresStagedFillFunctionsNonisolated_whenRootFillsHoleInsideMainActorSeamsSendableBuilder(
		integration: MultiModuleIntegration,
		isolation: ModuleDefaultIsolationPair,
	) async throws {
		let output = try await executeSafeDIToolMultiModuleTest(
			modules: [
				ModuleFixture(
					name: "Feed",
					packageName: "pkg",
					swiftFileContentByFilePath: ["Feed.swift": """
					nonisolated public protocol Clock: Sendable {}

					@MainActor
					@Instantiable(generateDependencyTree: true)
					public final class Feed: Instantiable {
					    public init(detailBuilder: SendableInstantiator<Detail>, part: Part) {
					        self.detailBuilder = detailBuilder
					        self.part = part
					    }

					    @Instantiated let detailBuilder: SendableInstantiator<Detail>
					    @Instantiated let part: Part
					}

					@Instantiable
					public final class Detail: Instantiable {
					    public init(clock: any Clock, part: Part, name: String) {
					        self.clock = clock
					        self.part = part
					        self.name = name
					    }

					    @Instantiated let clock: any Clock
					    @Received let part: Part
					    @Forwarded let name: String
					}

					@Instantiable
					public final class Part: Instantiable, Sendable {
					    public init() {}
					}
					"""],
					compilerSettings: isolation.declaringModule.compilerSettings,
				),
				ModuleFixture(
					name: "App",
					packageName: "pkg",
					swiftFileContentByFilePath: ["App.swift": """
					import Feed

					@MainActor
					@Instantiable(isRoot: true)
					public final class App: Instantiable {
					    public init(feed: Feed) {
					        self.feed = feed
					    }

					    @Instantiated let feed: Feed
					}

					@Instantiable(fulfillingAdditionalTypes: [(any Clock).self])
					public final class SystemClock: Instantiable, Clock {
					    public init(part: Part) {
					        self.part = part
					    }

					    @Received let part: Part
					}
					"""],
					dependencies: ["Feed"],
					compilerSettings: isolation.callingModule.compilerSettings,
				),
			],
			integration: integration,
			filesToDelete: &filesToDelete,
		)

		let (feedFileName, appFileName) = switch integration {
		case .moduleInfo:
			("Feed.swift", "App.swift")
		case .swiftPackagePlugin:
			("Feed+SafeDI.swift", "App+SafeDI.swift")
		}
		#expect(output.modules["Feed"]?.generatedFiles == [feedFileName: """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		extension Feed {
		    public enum SafeDIStagedScope_Clock_detailBuilder_clock {
		        public struct Stage1 {
		            public let part: Part
		        }

		        public struct Stage2 {
		            public let name: String
		        }
		    }

		    /// Only code SafeDI generates calls this initializer, and its shape can change in any release of SafeDI.
		    /// To call this type from code you write, set `generatePlainDependencyTreeInitializers: true` in this module's `#SafeDIConfiguration`.
		    public convenience init(__safeDI_clockBuilder_detailBuilder_clock: @escaping (SafeDIStagedScope_Clock_detailBuilder_clock.Stage1) -> @Sendable (SafeDIStagedScope_Clock_detailBuilder_clock.Stage2) -> any Clock) {
		        let part = Part()
		        let __safeDI_clockBuilder_detailBuilder_clock_Stage2 = __safeDI_clockBuilder_detailBuilder_clock(SafeDIStagedScope_Clock_detailBuilder_clock.Stage1(part: part))
		        @Sendable nonisolated func __safeDI_detailBuilder(name: String) -> Detail {
		            let clock: any Clock = __safeDI_clockBuilder_detailBuilder_clock_Stage2(SafeDIStagedScope_Clock_detailBuilder_clock.Stage2(name: name))
		            return Detail(clock: clock, part: part, name: name)
		        }
		        let detailBuilder = SendableInstantiator<Detail> {
		            __safeDI_detailBuilder(name: $0)
		        }
		        self.init(detailBuilder: detailBuilder, part: part)
		    }
		}

		extension Feed {
		    public enum __safeDI_Feed_B1EC2036ECBB0903 {}
		}
		"""])
		#expect(output.modules["App"]?.generatedFiles == [appFileName: """
		// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
		// Any modifications made to this file will be overwritten on subsequent builds.
		// Please refrain from editing this file directly.

		#if canImport(Feed)
		import Feed
		#endif

		extension App {
		    public convenience init() {
		        func __safeDI_feed() -> Feed {
		            _ = Feed.__safeDI_Feed_B1EC2036ECBB0903.self\(integration.seamCallComment(type: "Feed", declaringModule: "Feed"))
		            func __safeDI_clockBuilder_detailBuilder_clock(_ scope: Feed.SafeDIStagedScope_Clock_detailBuilder_clock.Stage1) -> @Sendable (Feed.SafeDIStagedScope_Clock_detailBuilder_clock.Stage2) -> any Clock {
		                let part = scope.part
		                @Sendable nonisolated func __safeDI_clockBuilder_detailBuilder_clock_Stage2(_ scope: Feed.SafeDIStagedScope_Clock_detailBuilder_clock.Stage2) -> any Clock {
		                    let clock: any Clock = SystemClock(part: part)
		                    return clock
		                }
		                return __safeDI_clockBuilder_detailBuilder_clock_Stage2
		            }
		            return Feed(__safeDI_clockBuilder_detailBuilder_clock: __safeDI_clockBuilder_detailBuilder_clock)
		        }
		        let feed: Feed = __safeDI_feed()
		        self.init(feed: feed)
		    }
		}
		"""])
	}

	@Test(arguments: ModuleDefaultIsolationPair.allCases)
