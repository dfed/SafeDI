		let output = try await executeSafeDIToolTest(
			swiftFileContent: [
				"""
				@MainActor
				@Instantiable(generateDependencyTree: true)
				public final class SeamHub: Instantiable {
				    public init(missingBuilder: SendableInstantiator<Missing>, lazyMissing: SendableLazilyInstantiated<Missing>, detailBuilder: SendableInstantiator<Detail>, part: Part) {
				        self.missingBuilder = missingBuilder
				        self.lazyMissing = lazyMissing
				        self.detailBuilder = detailBuilder
				        self.part = part
				    }

				    @Instantiated let missingBuilder: SendableInstantiator<Missing>
				    @Instantiated let lazyMissing: SendableLazilyInstantiated<Missing>
				    @Instantiated let detailBuilder: SendableInstantiator<Detail>
				    @Instantiated let part: Part
				}
				""",
				"""
				public final class Missing: Instantiable, Sendable {
				    public init(part: Part) {}
				}
				""",
				"""
