	private var filesToDelete: [URL]

	/// The comment `integration` puts on a call of `seam`, which `module` declares.
	private static func callComment(_ integration: MultiModuleIntegration, seam: String, module: String) -> String {
		integration.seamCallComment(type: seam, declaringModule: module)
	}

	/// `Feature`: the protocol `Analytics`, the seam `Screen` (by default building `detail`), `Detail` (by default
	/// instantiating `analytics` only if available and building `footer`), and `Footer`, which receives `analytics` only if
	/// available.
	private static func featureModule(
		screenDeclarations: [String] = ["@Instantiated let detail: Detail"],
		detailDeclarations: [String] = ["@Instantiated(onlyIfAvailable: true) let analytics: Analytics?", "@Instantiated let footer: Footer"],
		extra: [String] = [],
		sendable: Bool = false,
	) -> ModuleFixture {
		let conformances = sendable ? ", Sendable" : ""
		return ModuleFixture(name: "Feature", packageName: "Shop", swiftFileContent: [
			sendable ? "public protocol Analytics: Sendable {}" : "public protocol Analytics {}",
			seamFixtureType(named: "Screen", isSeam: true, declarations: screenDeclarations, conformances: conformances),
			seamFixtureType(named: "Detail", declarations: detailDeclarations, conformances: conformances),
			seamFixtureType(named: "Footer", declarations: ["@Received(onlyIfAvailable: true) let analytics: Analytics?"], conformances: conformances),
		] + extra)
	}

	/// `Feature`, and `App`, which depends on it and declares `app`.
	private static func modules(
		screenDeclarations: [String] = ["@Instantiated let detail: Detail"],
		detailDeclarations: [String] = ["@Instantiated(onlyIfAvailable: true) let analytics: Analytics?", "@Instantiated let footer: Footer"],
		extraFeature: [String] = [],
		sendable: Bool = false,
		app: [String],
	) -> [ModuleFixture] {
		[
			featureModule(screenDeclarations: screenDeclarations, detailDeclarations: detailDeclarations, extra: extraFeature, sendable: sendable),
			ModuleFixture(name: "App", packageName: "Other", swiftFileContent: app.map { "import Feature\n\n" + $0 }, dependencies: ["Feature"]),
		]
	}

