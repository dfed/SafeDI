/// A seam whose tree declares `@Instantiated(onlyIfAvailable: true) let analytics: Analytics?` cannot see whether the
/// app has an implementation of `Analytics`, so its generated initializer takes a builder that returns `Analytics?`,
/// required like every builder. A caller whose module sees a production declaration that fulfills `Analytics` fills it
/// with that declaration; a root whose module sees none fills it with `{ nil }`, where a required builder would be an
/// error; a seam that calls the seam passes the builder up unchanged. The values equal those of the same types built in
/// one module, present and absent.
struct SafeDIToolSeamInstantiatedOnlyIfAvailableTests: ~Copyable {
	// MARK: Initialization

	init() {
		filesToDelete = [URL]()
	}

	deinit {
		for fileToDelete in filesToDelete {
			try! FileManager.default.removeItem(at: fileToDelete)
		}
	}

	// MARK: Tests – A seam's tree instantiates a type only if available

	@Test(arguments: MultiModuleIntegration.allCases)
	@available(macOS 13.0, iOS 16.0, tvOS 16.0, watchOS 9.0, *)
	mutating func generate_fillsBuilderWithImplementation_whenAppDeclaresTypeSeamInstantiatesOnlyIfAvailable(integration: MultiModuleIntegration) async throws {
		// `Detail`, beneath the seam `Screen`, instantiates `analytics` only if available, and `Footer` receives it only if
		// available. `Screen` takes a builder that returns `Analytics?`, which `App`, declaring `DefaultAnalytics`, fills.
		let modules = Self.modules(app: [Self.defaultAnalytics, Self.root])
		let output = try await executeSafeDIToolMultiModuleTest(modules: modules, integration: integration, filesToDelete: &filesToDelete)

		expectGeneratedFiles(output.modules["Feature"]?.generatedFiles, [
			integration == .moduleInfo ? "Feature.swift" : "Screen+SafeDI.swift": """
			// This file was generated by the SafeDIGenerateDependencyTree build tool plugin.
			// Any modifications made to this file will be overwritten on subsequent builds.
			// Please refrain from editing this file directly.

			extension Screen {
			    /// Only code SafeDI generates reads this type, and its shape can change in any release of SafeDI.
			    nonisolated public final class __safeDI_AnalyticsOptionalCarrier<__safeDI_Built> {
			        public let detail: __safeDI_AnalyticsOptionalCarrier_Detail<__safeDI_Built>

			        public init(detail: __safeDI_AnalyticsOptionalCarrier_Detail<__safeDI_Built>) {
			            self.detail = detail
			        }

			        public convenience init(__safeDI_noScope __safeDI_builder: @escaping () -> __safeDI_Built) {
			            self.init(detail: .init(__safeDI_noScope: __safeDI_builder))
			        }
